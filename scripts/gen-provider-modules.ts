// Embeds each cloud server provider's vendored HCL module (packages/providers/<id>/module/**) into
// that package's src/generated/module.ts, so the bundled CLI can write it into a user's repository
// (ADR 0029). OpsCrew adds the shared cloud-init.yaml.tftpl to every server module itself, so a
// provider's module folder never holds a copy.
// Run `pnpm gen:provider-modules` after changing a provider's module.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const providersDir = join(dirname(fileURLToPath(import.meta.url)), "..", "packages", "providers");

const read = (path: string) => readFileSync(path, "utf8").replace(/\r\n/g, "\n");

/** The files of the provider package's `module/` folder (path within it → content), sorted. */
export function collectProviderModule(packageDir: string): Record<string, string> {
  const moduleDir = join(packageDir, "module");
  const files: Record<string, string> = {};
  const walk = (current: string) => {
    for (const entry of readdirSync(current).sort()) {
      const full = join(current, entry);
      if (statSync(full).isDirectory()) walk(full);
      else files[relative(moduleDir, full).split("\\").join("/")] = read(full);
    }
  };
  walk(moduleDir);
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1)));
}

/** The generated `src/generated/module.ts` for `files`. */
export function renderProviderModule(files: Record<string, string>): string {
  const body = Object.entries(files)
    .map(([path, content]) => `  ${JSON.stringify(path)}: ${JSON.stringify(content)},`)
    .join("\n");
  return [
    "// Generated by scripts/gen-provider-modules.ts from this package's module/ folder. Do not edit.",
    "// Run `pnpm gen:provider-modules` after changing the module.",
    "export const MODULE_FILES: Readonly<Record<string, string>> = {",
    body,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const id of readdirSync(providersDir).sort()) {
    const packageDir = join(providersDir, id);
    if (!existsSync(join(packageDir, "module"))) continue;
    const generated = join(packageDir, "src", "generated");
    mkdirSync(generated, { recursive: true });
    writeFileSync(
      join(generated, "module.ts"),
      renderProviderModule(collectProviderModule(packageDir)),
    );
    console.log(`wrote ${relative(join(providersDir, ".."), join(generated, "module.ts"))}`);
  }
}
