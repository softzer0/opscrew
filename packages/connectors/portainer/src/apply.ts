/** Secrets supplied at apply; never part of the plan, its hash, the record or an error. */
export interface ApplySecrets {
  /** The app stack's `Env` values, exactly for the plan's env keys. */
  env: Readonly<Record<string, string>>;
  /** The app stack's webhook UUID (`AutoUpdate.Webhook`), generated by the caller and kept locally. */
  webhookId?: string;
  /** Read-only token for a private repository. */
  repositoryToken?: string;
  /** Classic token with only `read:packages`, for the registry entry (administrator token). */
  registryToken?: string;
  /** The Cloudflare connector stack's `TUNNEL_TOKEN`. */
  tunnelToken?: string;
  /**
   * The updater stack's `Env` values, exactly for the `${VARS}` of its stack file. One must be an
   * `http:` or `https:` URL whose path ends in `/api/stacks/webhooks/<webhookId>` (the app
   * stack's webhook). The others (the pinned public key) may be empty only when that URL is
   * `http:`, or `https:` while the client reaches Portainer without a pinned certificate.
   */
  updaterEnv?: Readonly<Record<string, string>>;
}

/** Options for {@link applyStackPlan}. */
export interface ApplyStackOptions {
  /** The hash the user approved (`stack-apply`); any other plan is refused. */
  approvedHash: string;
  secrets: ApplySecrets;
  /**
   * The local value key. When the plan carries `valuesDigest`, the digest is recomputed from
   * `secrets` with it and a mismatch refuses before any request (a plan with a digest needs it).
   */
  valueKey?: Uint8Array;
  /** Bounded wait for asynchronous deploys (default 10 minutes, polling every 2 seconds). */
  wait?: {
    timeoutMs?: number;
    intervalMs?: number;
    now?: () => number;
    sleep?: (ms: number) => Promise<void>;
  };
}

/** What changed and what OpsCrew has created afterwards (write it to `server.json`). */
export interface ApplyStackResult {
  /** The changes that changed Portainer, in order. */
  applied: StackChangeId[];
  record: CreatedRecord;
}

/**
 * An apply that stopped at a failure: `applied` lists the changes completed before it, `record`
 * everything OpsCrew has created so far (save it, so the next plan knows these are OpsCrew's).
 */
export class StackApplyError extends OpsCrewError {
  readonly applied: StackChangeId[];
  readonly record: CreatedRecord;

  constructor(
    code: OpsCrewError["code"],
    message: string,
    hint: string | undefined,
    applied: StackChangeId[],
    record: CreatedRecord,
  ) {
    super(code, message, hint === undefined ? undefined : { hint });
    this.name = "StackApplyError";
    this.applied = applied;
    this.record = record;
  }
}

const DEFAULT_TIMEOUT_MS = 10 * 60_000;
const DEFAULT_INTERVAL_MS = 2_000;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const MAX_VALUE_BYTES = 64 * 1024;

/**
 * Applies an approved stack plan through the Portainer client. Refuses with PLAN_HASH_MISMATCH
 * when the plan's hash is not `approvedHash`, with PHASE_PRECONDITION when it has findings or
 * blocked changes, and with INVALID_INPUT when a secret it needs is missing or the plan would
 * touch something OpsCrew's record does not list, all before any change. Changes run in order;
 * asynchronous deploys are polled until Portainer reports them active, or the error it reports,
 * or the timeout. The first failure stops the apply with a {@link StackApplyError} that says
 * what was done. Updates always send the full `Env`.
 */
export async function applyStackPlan(
  client: PortainerClient,
  plan: StackPlan,
  opts: ApplyStackOptions,
): Promise<ApplyStackResult> {
  const parsed = StackPlanSchema.safeParse(plan);
  if (!parsed.success) {
    throw new OpsCrewError("INVALID_INPUT", "The stack plan is not valid.", {
      hint: "Make a fresh stack plan with opscrew provision and approve it.",
    });
  }
  const valid = parsed.data;
  if (!isPlanHash(opts?.approvedHash) || opts.approvedHash.toLowerCase() !== stackPlanHash(valid)) {
    throw new OpsCrewError(
      "PLAN_HASH_MISMATCH",
      "This stack plan is not the one that was approved, so OpsCrew changes nothing in Portainer.",
      { hint: "Look at the current stack plan and approve it by its hash." },
    );
  }
  if (valid.findings.length > 0) {
    throw new OpsCrewError(
      "PHASE_PRECONDITION",
      `OpsCrew cannot change Portainer yet: ${valid.findings.map((finding) => finding.message).join(" ")}`,
      { hint: valid.findings.map((finding) => finding.hint).join(" ") },
    );
  }
  const blocked = valid.changes.filter((change) => change.state === "blocked");
  if (blocked.length > 0) {
    throw new OpsCrewError(
      "PHASE_PRECONDITION",
      `The stack plan has blocked changes (${blocked.map((change) => change.id).join(", ")}), so OpsCrew changes nothing in Portainer.`,
      { hint: "Resolve what blocks them, then make and approve a fresh stack plan." },
    );
  }

  const secrets = opts.secrets ?? { env: {} };
  registerSecrets(client, secrets);
  const work = valid.changes.filter(
    (change) => change.state === "change" || change.params.action === "forget",
  );
  // Everything is checked before the first call: a bad plan or a missing secret changes nothing.
  for (const change of work) check(valid, change, secrets, client.pinned);
  checkValuesDigest(valid, secrets, opts.valueKey);

  const wait = {
    timeoutMs: opts.wait?.timeoutMs ?? DEFAULT_TIMEOUT_MS,
    intervalMs: opts.wait?.intervalMs ?? DEFAULT_INTERVAL_MS,
    now: opts.wait?.now ?? Date.now,
    sleep: opts.wait?.sleep ?? ((ms: number) => new Promise<void>((r) => setTimeout(r, ms))),
  };
  const record: CreatedRecord = structuredClone(valid.record);
  const applied: StackChangeId[] = [];
  const done: string[] = [];
  const context: Context = {
    client,
    plan: valid,
    secrets,
    record,
    wait,
    done: (text) => done.push(text),
  };

  for (const change of work) {
    try {
      const changed = await run(context, change);
      if (changed) applied.push(change.id);
    } catch (error) {
      throw failure(client, error, done, applied, record);
    }
  }
  if (valid.purpose === "setup") {
    const app = valid.changes.find((change) => change.id === "app-stack");
    const volumes = app === undefined ? [] : list(app.params, "volumes");
    record.volumes = [...new Set([...record.volumes, ...volumes])].sort();
  }
  return { applied, record };
}

/**
 * The values supplied now must be the ones the plan was made with: their fingerprints (with the
 * local key) give the plan's `valuesDigest`. Names only in errors, never values.
 */
function checkValuesDigest(
  plan: StackPlan,
  secrets: ApplySecrets,
  valueKey: Uint8Array | undefined,
): void {
  const sent = sentValues(plan.changes);
  if (plan.valuesDigest === undefined) {
    if (sendsNothing(sent)) return;
    // Values never go out unbound: a plan that sends them must carry their digest.
    throw invalid(
      "This stack plan sends values but is not bound to them (it has no values digest), so OpsCrew changes nothing.",
      "Make the stack plan with the fingerprints of the local values (valueFingerprints) and approve it by its hash.",
    );
  }
  if (valueKey === undefined) {
    throw invalid(
      "This stack plan is bound to the values it was made with, and the value key to check them is missing, so OpsCrew changes nothing.",
      "Apply it with the value key OpsCrew keeps for this project.",
    );
  }
  const parts: DesiredValueFingerprints = {};
  if (sent.app !== undefined) parts.app = valueFingerprints(valueKey, only(secrets.env, sent.app));
  if (sent.updater !== undefined) {
    parts.updater = valueFingerprints(valueKey, only(secrets.updaterEnv, sent.updater));
  }
  if (sent.connector !== undefined) {
    parts.connector = valueFingerprints(
      valueKey,
      only({ TUNNEL_TOKEN: secrets.tunnelToken ?? "" }, sent.connector),
    );
  }
  if (sent.webhook) {
    parts.webhook = valueFingerprints(valueKey, {
      [WEBHOOK_FINGERPRINT_NAME]: secrets.webhookId ?? "",
    })[WEBHOOK_FINGERPRINT_NAME];
  }
  if (valuesDigestOf(parts) !== plan.valuesDigest) {
    throw new OpsCrewError(
      "PLAN_HASH_MISMATCH",
      "The values supplied are not the ones this stack plan was approved with, so OpsCrew changes nothing in Portainer.",
      { hint: "Make a fresh stack plan with the current values and approve it by its hash." },
    );
  }
}

function only(
  values: Readonly<Record<string, string>> | undefined,
  keys: readonly string[],
): Record<string, string> {
  return Object.fromEntries(keys.map((key) => [key, values?.[key] ?? ""]));
}

interface Context {
  client: PortainerClient;
  plan: StackPlan;
  secrets: ApplySecrets;
  record: CreatedRecord;
  wait: {
    timeoutMs: number;
    intervalMs: number;
    now: () => number;
    sleep: (ms: number) => Promise<void>;
  };
  done: (text: string) => void;
}

type Role = CreatedRecord["stacks"][number]["role"];

const ROLE_OF: Partial<Record<StackChangeId, Role>> = {
  "app-stack": "app",
  "updater-stack": "updater",
  "tunnel-connector-stack": "tunnel-connector",
};

function registerSecrets(client: PortainerClient, secrets: ApplySecrets): void {
  for (const [key, value] of Object.entries(secrets.env ?? {})) {
    if (typeof value === "string") client.registerSecret(value, key);
  }
  for (const [key, value] of Object.entries(secrets.updaterEnv ?? {})) {
    if (typeof value === "string") client.registerSecret(value, key);
  }
  if (typeof secrets.webhookId === "string") client.registerSecret(secrets.webhookId, "webhook-id");
  if (typeof secrets.repositoryToken === "string") {
    client.registerSecret(secrets.repositoryToken, "repository-token");
  }
  if (typeof secrets.registryToken === "string") {
    client.registerSecret(secrets.registryToken, "OPSCREW_GHCR_READ_TOKEN");
  }
  if (typeof secrets.tunnelToken === "string")
    client.registerSecret(secrets.tunnelToken, "tunnel-token");
}

function invalid(message: string, hint?: string): OpsCrewError {
  return new OpsCrewError("INVALID_INPUT", message, hint === undefined ? undefined : { hint });
}

/** Refuses a change the plan should never contain, or one whose secrets are missing. */
function check(plan: StackPlan, change: StackChange, secrets: ApplySecrets, pinned: boolean): void {
  const names = opscrewNames(plan.app);
  const action = str(change.params, "action");
  const role = ROLE_OF[change.id];
  const recordedStack = (id: number) =>
    plan.record.stacks.find((stack) => stack.id === id && stack.role === role);
  const notOurs = () =>
    invalid(
      `The stack plan would change something OpsCrew's record does not list (${change.id}), so OpsCrew changes nothing.`,
      "Make a fresh stack plan with opscrew provision and approve it.",
    );

  if (plan.purpose === "teardown" && action !== "remove" && action !== "forget") throw notOurs();
  if (role !== undefined) {
    const name = str(change.params, "name");
    const expected =
      role === "app" ? names.app : role === "updater" ? names.updater : names.tunnelConnector;
    if (name !== expected) throw notOurs();
    if (action !== "create" && recordedStack(num(change.params, "stackId")) === undefined) {
      throw notOurs();
    }
  }
  if (change.id === "registry") {
    if (action === "create") {
      if (
        str(change.params, "name") !== names.registry ||
        str(change.params, "url") !== "ghcr.io"
      ) {
        throw notOurs();
      }
      requireToken(secrets.registryToken, "the registry token (OPSCREW_GHCR_READ_TOKEN)");
    } else if (num(change.params, "registryId") !== plan.record.registryId) {
      // Grants and removals touch only the entry OpsCrew's record lists.
      throw notOurs();
    }
  }
  if (change.id === "volumes") {
    // Volumes are deleted only by a teardown that deletes data, and only the app stack's.
    if (plan.purpose !== "teardown" || plan.deleteData !== true) throw notOurs();
    for (const name of list(change.params, "names")) {
      if (!plan.record.volumes.includes(name) || !name.startsWith(`${names.app}_`)) {
        throw notOurs();
      }
    }
    const stop = change.params.stopStackId;
    if (stop !== undefined && !plan.record.stacks.some((s) => s.id === stop && s.role === "app")) {
      throw notOurs();
    }
  }
  const sendsEnv = action === "create" || action === "update" || action === "redeploy";
  if (change.id === "app-stack" && sendsEnv) {
    if (
      str(change.params, "reference") !== DEPLOY_REFERENCE ||
      str(change.params, "composeFile") !== DEPLOY_COMPOSE_FILE
    ) {
      throw notOurs();
    }
    // A redeploy sends the Env but not AutoUpdate, so it needs no webhook id.
    if (action !== "redeploy") requireWebhook(secrets.webhookId);
    exactValues(secrets.env, list(change.params, "envKeys"), "the app");
    if (bool(change.params, "repositoryAuthentication")) {
      requireToken(secrets.repositoryToken, "the repository token");
    }
  }
  if (change.id === "updater-stack" && sendsEnv) {
    requireWebhook(secrets.webhookId);
    const env = secrets.updaterEnv ?? {};
    exactValues(env, list(change.params, "envKeys"), "the updater");
    checkUpdaterEnv(env, secrets.webhookId as string, pinned);
  }
  if (change.id === "tunnel-connector-stack" && sendsEnv) {
    const keys = list(change.params, "envKeys");
    if (keys.join(",") !== "TUNNEL_TOKEN") throw notOurs();
    requireToken(secrets.tunnelToken, "the Cloudflare connector's tunnel token");
  }
}

/**
 * The updater's values: one is an `http:`/`https:` URL whose path ends in
 * `/api/stacks/webhooks/<webhookId>` (the app stack's webhook), and none calls another webhook.
 * The updater skips the pin when it is empty, so another value (the pinned public key) may be
 * empty only when that URL is `http:`, or `https:` while OpsCrew itself reaches Portainer without
 * a pinned certificate (curl then checks the certificate against the public authorities).
 */
function checkUpdaterEnv(
  env: Readonly<Record<string, string>>,
  webhookId: string,
  pinned: boolean,
): void {
  const suffix = `/api/stacks/webhooks/${webhookId}`.toLowerCase();
  const urls: URL[] = [];
  for (const value of Object.values(env)) {
    const other = /\/api\/stacks\/webhooks\/([^/?#\s]+)/.exec(value);
    if (other !== null && other[1]?.toLowerCase() !== webhookId.toLowerCase()) {
      throw invalid(
        "The updater's webhook URL does not call the same webhook as the app stack, so OpsCrew changes nothing.",
        "Build PORTAINER_WEBHOOK_URL from the webhook id kept for this app.",
      );
    }
    const url = parseUrl(value);
    if (
      url !== undefined &&
      (url.protocol === "https:" || url.protocol === "http:") &&
      url.pathname.toLowerCase().endsWith(suffix)
    ) {
      urls.push(url);
    }
  }
  if (urls.length === 0) {
    throw invalid(
      "None of the updater's values is a URL calling the app stack's webhook (…/api/stacks/webhooks/<id>), so OpsCrew changes nothing.",
      "Build PORTAINER_WEBHOOK_URL from Portainer's address and the webhook id kept for this app.",
    );
  }
  const empty = Object.entries(env)
    .filter(([, value]) => value.trim() === "")
    .map(([key]) => key);
  if (empty.length > 0 && pinned && urls.some((url) => url.protocol === "https:")) {
    throw invalid(
      `The updater's ${empty.join(", ")} ${empty.length === 1 ? "is" : "are"} empty while its webhook URL uses https and OpsCrew reaches Portainer through a pinned certificate, so OpsCrew changes nothing.`,
      "Supply Portainer's pinned public key (PORTAINER_PINNED_KEY), so the updater checks the same certificate.",
    );
  }
}

function parseUrl(value: string): URL | undefined {
  try {
    return new URL(value);
  } catch {
    // Not a URL (the pinned key).
    return undefined;
  }
}

function requireWebhook(webhookId: string | undefined): void {
  if (typeof webhookId !== "string" || !UUID.test(webhookId)) {
    throw invalid(
      "The app stack's webhook id is missing or is not a UUID, so OpsCrew changes nothing.",
      "Supply the webhook id OpsCrew keeps for this app (or a new UUID on the first setup).",
    );
  }
}

function requireToken(value: string | undefined, what: string): void {
  if (typeof value !== "string" || !/^[\x21-\x7e]{1,4096}$/.test(value)) {
    throw invalid(
      `${what[0]?.toUpperCase()}${what.slice(1)} is missing, so OpsCrew changes nothing.`,
    );
  }
}

/** `values` must hold exactly `keys` (no secret shown: only names). */
function exactValues(
  values: Readonly<Record<string, string>> | undefined,
  keys: readonly string[],
  whose: string,
): void {
  const given = values ?? {};
  const missing = keys.filter((key) => typeof given[key] !== "string");
  if (missing.length > 0) {
    throw invalid(
      `Values for ${whose}'s ${missing.join(", ")} are missing, so OpsCrew changes nothing.`,
      "Set every variable the plan lists, then apply the same plan again.",
    );
  }
  const extra = Object.keys(given).filter((key) => !keys.includes(key));
  if (extra.length > 0) {
    throw invalid(
      `${extra.join(", ")} ${extra.length === 1 ? "is" : "are"} not in the approved plan for ${whose}, so OpsCrew changes nothing.`,
      "Make a fresh stack plan that lists every variable, and approve it.",
    );
  }
  for (const key of keys) {
    const value = given[key] as string;
    if (value.includes("\0") || Buffer.byteLength(value, "utf8") > MAX_VALUE_BYTES) {
      throw invalid(`The value of ${key} must be text of at most 64 KiB without NUL bytes.`);
    }
  }
}

function pairs(values: Readonly<Record<string, string>>, keys: readonly string[]): EnvPair[] {
  return [...keys].sort().map((name) => ({ name, value: values[name] as string }));
}

async function run(ctx: Context, change: StackChange): Promise<boolean> {
  const { client, plan, record, secrets } = ctx;
  const params = change.params;
  const action = str(params, "action");
  const envId = plan.environmentId;

  if (change.id === "registry") {
    const name = str(params, "name");
    if (action === "create") {
      const created = await client.createRegistry({
        name,
        url: "ghcr.io",
        username: str(params, "username"),
        password: secrets.registryToken as string,
      });
      record.registryId = created.id;
      ctx.done(`Added the registry entry ${name} (id ${created.id})`);
      await client.grantRegistry(envId, created.id, num(params, "grantUserId"));
      ctx.done("allowed its use on the environment");
      return true;
    }
    if (action === "grant") {
      await client.grantRegistry(envId, num(params, "registryId"), num(params, "grantUserId"));
      ctx.done(`Allowed the registry entry ${name} on the environment`);
      return true;
    }
    if (action === "remove") {
      const result = await client.removeRegistry(num(params, "registryId"));
      delete record.registryId;
      ctx.done(
        result === "removed"
          ? `Removed the registry entry ${name}`
          : `Found the registry entry ${name} already gone`,
      );
      return result === "removed";
    }
    if (action === "forget") {
      delete record.registryId;
      return false;
    }
  }

  if (change.id === "volumes" && action === "remove") {
    const stopId = params.stopStackId;
    if (typeof stopId === "number") {
      const stack = await client.getStack(stopId);
      if (stack !== undefined && stack.status !== 2) {
        await client.stopStack(stopId, envId);
        ctx.done(`Stopped the stack ${stack.name}`);
      }
    }
    for (const name of list(params, "names")) {
      const result = await client.removeVolume(envId, name);
      record.volumes = record.volumes.filter((volume) => volume !== name);
      ctx.done(
        result === "removed"
          ? `Deleted the volume ${name}`
          : `Found the volume ${name} already gone`,
      );
    }
    return true;
  }

  const role = ROLE_OF[change.id];
  if (role === undefined) throw new OpsCrewError("INTERNAL", `Unknown stack change ${change.id}.`);
  const name = str(params, "name");

  if (action === "remove" || action === "forget") {
    const stackId = num(params, "stackId");
    const result = action === "remove" ? await client.removeStack(stackId, envId) : "absent";
    record.stacks = record.stacks.filter((stack) => stack.id !== stackId);
    if (action === "remove") {
      ctx.done(
        result === "removed" ? `Removed the stack ${name}` : `Found the stack ${name} already gone`,
      );
    }
    return action === "remove" && result === "removed";
  }

  if (action === "start") {
    const stackId = num(params, "stackId");
    if (role === "app") recordVolumes(record, params);
    const started = await client.startStack(stackId, envId);
    ctx.done(`Started the stack ${name}`);
    await waitForDeploy(ctx, started, START, name);
    return true;
  }

  if (role === "app") {
    const keys = list(params, "envKeys");
    const env = pairs(secrets.env, keys);
    const authentication = bool(params, "repositoryAuthentication")
      ? { username: str(params, "repositoryUsername"), password: secrets.repositoryToken as string }
      : undefined;
    if (action === "create") {
      const created = await client.createGitStack(envId, {
        name,
        repositoryUrl: str(params, "repository"),
        referenceName: DEPLOY_REFERENCE,
        composeFile: DEPLOY_COMPOSE_FILE,
        ...(authentication !== undefined && { authentication }),
        webhookId: secrets.webhookId as string,
        env,
      });
      remember(record, created.id, name, role);
      recordVolumes(record, params);
      ctx.done(`Created the stack ${name} (id ${created.id})`);
      await waitForDeploy(ctx, created, NEW_DEPLOY, name);
      return true;
    }
    const stackId = num(params, "stackId");
    recordVolumes(record, params);
    const before = await deployBaseline(client, stackId);
    if (action === "update") {
      await client.updateGitStack(stackId, envId, {
        repositoryUrl: str(params, "repository"),
        referenceName: DEPLOY_REFERENCE,
        composeFile: DEPLOY_COMPOSE_FILE,
        ...(authentication !== undefined && { authentication }),
        webhookId: secrets.webhookId as string,
        env,
      });
      ctx.done(`Saved the Git settings and environment of the stack ${name}`);
    }
    const started = await client.redeployGitStack(stackId, envId, {
      referenceName: DEPLOY_REFERENCE,
      ...(authentication !== undefined && { authentication }),
      env,
    });
    await waitForDeploy(ctx, started, before, name);
    ctx.done(`Redeployed the stack ${name}`);
    return true;
  }

  // String stacks: a redeploy sends the same file again, with the full Env.
  const compose = str(params, "compose");
  const keys = list(params, "envKeys");
  const values: Readonly<Record<string, string>> =
    role === "updater"
      ? (secrets.updaterEnv ?? {})
      : { TUNNEL_TOKEN: secrets.tunnelToken as string };
  const env = pairs(values, keys);
  if (action === "create") {
    const created = await client.createStringStack(envId, { name, compose, env });
    remember(record, created.id, name, role);
    ctx.done(`Created the stack ${name} (id ${created.id})`);
    await waitForDeploy(ctx, created, NEW_DEPLOY, name);
    return true;
  }
  const stackId = num(params, "stackId");
  const before = await deployBaseline(client, stackId);
  const started = await client.updateStringStack(stackId, envId, { compose, env });
  ctx.done(`${action === "redeploy" ? "Redeployed" : "Updated"} the stack ${name}`);
  await waitForDeploy(ctx, started, before, name);
  return true;
}

function remember(record: CreatedRecord, id: number, name: string, role: Role): void {
  record.stacks = [
    ...record.stacks.filter((stack) => stack.role !== role),
    { id, name, role },
  ].sort((a, b) => ORDER[a.role] - ORDER[b.role]);
}

/** The app stack's volumes go into the record as soon as the stack is OpsCrew's. */
function recordVolumes(record: CreatedRecord, params: Readonly<Record<string, StackParamValue>>) {
  record.volumes = [...new Set([...record.volumes, ...list(params, "volumes")])].sort();
}

const ORDER: Record<Role, number> = { app: 0, updater: 1, "tunnel-connector": 2 };

/**
 * Which deploy to wait for: any (a new stack), a start (the stack leaves Status 2), or one after
 * the stack's deploy history as read before the call (its last entry's Time and its length).
 */
type Baseline =
  | { kind: "new" }
  | { kind: "start" }
  | { kind: "after"; time: number | undefined; count: number };
const NEW_DEPLOY: Baseline = { kind: "new" };
const START: Baseline = { kind: "start" };

/** The stack's deploy history before changing it: the last entry's Time and the entry count. */
async function deployBaseline(client: PortainerClient, stackId: number): Promise<Baseline> {
  const stack = await client.getStack(stackId);
  if (stack === undefined) {
    throw new OpsCrewError("PROVIDER_ERROR", `Portainer no longer has stack ${stackId}.`, {
      hint: "Run opscrew provision again: the new plan creates it again.",
    });
  }
  return {
    kind: "after",
    time: stack.deploymentStatus.at(-1)?.time,
    count: stack.deploymentStatus.length,
  };
}

/**
 * Whether `current` shows the deploy this apply started. A new stack: any status. A start: any
 * status but 2 (still stopped). Otherwise, with timed entries, the last one must be newer than
 * before the call; without them (or with no baseline time), the history must have grown or the
 * stack must have been seen deploying (Status 3), since the history may be capped.
 */
function isFresh(baseline: Baseline, current: StackDetails, seenDeploying: boolean): boolean {
  if (baseline.kind === "new") return true;
  if (baseline.kind === "start") return current.status !== 2;
  const last = current.deploymentStatus.at(-1)?.time;
  if (last !== undefined && baseline.time !== undefined) return last > baseline.time;
  return current.deploymentStatus.length > baseline.count || seenDeploying;
}

/**
 * Polls until Portainer reports the deploy this apply started (see {@link isFresh}) as finished:
 * `Status` 1 (active) succeeds, 4 (error) fails with `DeploymentStatus[-1].Message`; 3
 * (deploying), and 2 (stopped) after a start, keep polling until the timeout.
 */
async function waitForDeploy(
  ctx: Context,
  started: StackDetails,
  baseline: Baseline,
  name: string,
): Promise<void> {
  const { client, wait } = ctx;
  const start = wait.now();
  let current = started;
  let seenDeploying = false;
  for (;;) {
    if (current.status === 3) seenDeploying = true;
    const fresh = isFresh(baseline, current, seenDeploying);
    if (fresh && current.status !== 3 && current.status !== undefined) {
      if (current.status === 1) return;
      if (current.status === 4) {
        const message = current.deploymentStatus.at(-1)?.message;
        throw new OpsCrewError(
          "PROVIDER_ERROR",
          `The stack ${name} did not deploy: Portainer reports "${message ?? "an error, without a reason"}".`,
          { hint: deployHint(message) },
        );
      }
      throw new OpsCrewError(
        "PROVIDER_ERROR",
        `The stack ${name} is not running after its deploy (Portainer reports it as ${current.status === 2 ? "stopped" : `status ${current.status}`}).`,
        {
          hint: "Look at the stack in Portainer (Stacks → the stack), then run opscrew provision again.",
        },
      );
    }
    const elapsed = wait.now() - start;
    if (elapsed >= wait.timeoutMs) {
      const seconds = Math.round(wait.timeoutMs / 1000);
      throw new OpsCrewError(
        "PROVIDER_ERROR",
        baseline.kind === "start" && current.status === 2
          ? `The stack ${name} is still stopped ${seconds} seconds after OpsCrew started it.`
          : `The stack ${name} is still deploying after ${seconds} seconds${current.status === 3 ? "" : " (Portainer has not reported the new deploy yet)"}.`,
        {
          hint: "Portainer may still finish it: look at the stack in Portainer (Stacks → the stack). Then run opscrew provision again; it shows no changes if the deploy worked.",
        },
      );
    }
    await wait.sleep(Math.min(wait.intervalMs, wait.timeoutMs - elapsed));
    const next = await client.getStack(started.id);
    if (next === undefined) {
      throw new OpsCrewError(
        "PROVIDER_ERROR",
        `Portainer removed the stack ${name} while it deployed.`,
        {
          hint: "Look at Portainer's logs, then run opscrew provision again.",
        },
      );
    }
    current = next;
  }
}

/** Research R7: what Portainer leaves behind after a failed deploy. */
function deployHint(message: string | undefined): string {
  if (message !== undefined && /port is already allocated|address already in use/i.test(message)) {
    return "Another container uses that host port: Portainer recreated the stack's containers and left them stopped, so the app is down. Free the port (or choose another way to reach the app in `opscrew interview`), then run opscrew provision again.";
  }
  return "Portainer kept the stack's last working file (and its containers, if they were healthy) but saved the new environment values. Fix the cause shown above, then run opscrew provision again.";
}

function failure(
  client: PortainerClient,
  error: unknown,
  done: readonly string[],
  applied: StackChangeId[],
  record: CreatedRecord,
): StackApplyError {
  const known = error instanceof OpsCrewError;
  const message = known ? error.message : "Portainer's answer could not be handled.";
  const summary =
    done.length === 0 ? "Nothing was changed before it." : `Done before it: ${done.join("; ")}.`;
  return new StackApplyError(
    known ? error.code : "INTERNAL",
    client.redact(`${message} ${summary}`),
    known && error.hint !== undefined ? client.redact(error.hint) : undefined,
    [...applied],
    structuredClone(record),
  );
}

// --- Typed access to the plan's params (validated shapes) --------------------------------------

function param(params: Readonly<Record<string, StackParamValue>>, key: string): StackParamValue {
  const value = params[key];
  if (value === undefined) throw invalid(`The stack plan lacks ${key}; make a fresh plan.`);
  return value;
}

function str(params: Readonly<Record<string, StackParamValue>>, key: string): string {
  const value = param(params, key);
  if (typeof value !== "string")
    throw invalid(`The stack plan's ${key} is not text; make a fresh plan.`);
  return value;
}

function num(params: Readonly<Record<string, StackParamValue>>, key: string): number {
  const value = param(params, key);
  if (typeof value !== "number" || !Number.isSafeInteger(value) || value <= 0) {
    throw invalid(`The stack plan's ${key} is not an id; make a fresh plan.`);
  }
  return value;
}

function bool(params: Readonly<Record<string, StackParamValue>>, key: string): boolean {
  const value = param(params, key);
  if (typeof value !== "boolean")
    throw invalid(`The stack plan's ${key} is not yes or no; make a fresh plan.`);
  return value;
}

function list(params: Readonly<Record<string, StackParamValue>>, key: string): string[] {
  const value = param(params, key);
  if (!Array.isArray(value))
    throw invalid(`The stack plan's ${key} is not a list; make a fresh plan.`);
  return [...value];
}
