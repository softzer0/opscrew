export function desiredFor(fake: FakeHost, overrides: Partial<DesiredHost> = {}): DesiredHost {
  const base: DesiredHost = {
    app: "shop",
    projectId: "shop-0123456789ab",
    admin: { user: fake.login, isRoot: fake.login === "root" },
    deploy: { user: "deploy", publicKey: DEPLOY_KEY },
    sshPort: 22,
    access: "public",
  };
  return { ...base, ...overrides };
}

export function tunnelDesired(fake: FakeHost, overrides: Partial<DesiredHost> = {}): DesiredHost {
  return desiredFor(fake, { access: "tunnel", tunnel: { compose: TUNNEL_COMPOSE }, ...overrides });
}

export function portainerDesired() {
  return { version: "2.33.1", compose: { initial: PORTAINER_INITIAL, final: PORTAINER_FINAL } };
}

export async function planFor(fake: FakeHost, desired: DesiredHost = desiredFor(fake)): Promise<HostPlan> {
  return planHost(await inspectHost(fake), desired);
}

/** Applies a plan with its own hash and a verifyLogin that succeeds (unless given). */
export function applyApproved(
  fake: FakeHost,
  plan: HostPlan,
  options: Partial<ApplyOptions> = {},
) {
  return applyHostPlan(fake, plan, {
    approvedHash: hostPlanHash(plan),
    verifyLogin: async () => true,
    ...options,
  });
}

/** Inspects, plans and applies in one go; returns the plan and the result. */
export async function provision(
  fake: FakeHost,
  desired: DesiredHost = desiredFor(fake),
  options: Partial<ApplyOptions> = {},
) {
  const plan = await planFor(fake, desired);
  const result = await applyApproved(fake, plan, options);
  return { plan, result };
}

/** `sh -n` on a script; `undefined` when no POSIX shell can be started here. */
export function shSyntax(script: string): { ok: boolean; stderr: string } | undefined {
  const run = spawnSync("sh", ["-n"], { input: script, encoding: "utf8" });
  if (run.error) return undefined;
  return { ok: run.status === 0, stderr: run.stderr };
}

export const SH_AVAILABLE = shSyntax("true") !== undefined;
