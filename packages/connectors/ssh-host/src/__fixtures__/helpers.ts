export async function planFor(fake: FakeHost, desired: DesiredHost = desiredFor(fake)): Promise<HostPlan> {
  return planHost(await inspectHost(fake), desired, "opscrew provision");
}

/** Applies a plan with its own hash and a verifyLogin that succeeds (unless given). */
export function applyApproved(
  fake: FakeHost,
  plan: HostPlan,
  options: Partial<ApplyOptions> = {},
) {
  return applyHostPlan(fake, plan, {
    approvedHash: hostPlanHash(plan), command: "opscrew provision",
    verifyLogin: async () => true,
    ...options,
  });
}

/** Inspects, plans and applies in one go; returns the plan and the result. */
export async function provision(
  fake: FakeHost,
  desired: DesiredHost = desiredFor(fake),
  options: Partial<ApplyOptions> = {},
) {
  const plan = await planFor(fake, desired);
  const result = await applyApproved(fake, plan, options);
  return { plan, result };
}

/**
 * Removes the app from the server with an approved teardown (its data too, by default), from the
 * project its record names.
 */
export async function removeApp(fake: FakeHost, app = "shop", deleteData = true) {
  const facts = await inspectHost(fake);
  const projectId = facts.apps.find((item) => item.name === app)?.record?.projectId ?? SHOP_PROJECT;
  const plan = planTeardown(
    facts,
    { deleteData, app, projectId, repositoryUrl: SHOP_REPOSITORY },
    "opscrew destroy",
  );
  return applyApproved(fake, plan, { command: "opscrew destroy" });
}

