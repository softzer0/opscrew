import { OpsCrewError } from "@opscrew/core";

/** Minimum passphrase length accepted by OpenTofu's `pbkdf2` key provider. */
export const MIN_PASSPHRASE_LENGTH = 16;

/** Escapes `value` for use inside a double-quoted HCL string (no interpolation or directives). */
export function hclString(value: string): string {
  let out = "";
  for (const char of value) {
    const code = char.codePointAt(0) ?? 0;
    if (char === "\\") out += "\\\\";
    else if (char === '"') out += '\\"';
    else if (char === "\n") out += "\\n";
    else if (char === "\r") out += "\\r";
    else if (char === "\t") out += "\\t";
    else if (code < 0x20 || code === 0x7f) out += `\\u${code.toString(16).padStart(4, "0")}`;
    else out += char;
  }
  // `${` and `%{` start templates in HCL strings; doubling the sigil makes them literal.
  return `"${out.replaceAll("${", () => "$${").replaceAll("%{", () => "%%{")}"`;
}

/**
 * Returns the value for OpenTofu's `TF_ENCRYPTION` environment variable: a PBKDF2 key provider
 * and an AES-GCM method applied to both state and plan files. Use it only with OpenTofu, pass it
 * through `IacRunOptions.env`, and never log or write it to a file (it contains the passphrase).
 */
export function tofuEncryptionEnv(passphrase: string): string {
  if ([...passphrase].length < MIN_PASSPHRASE_LENGTH) {
    throw new OpsCrewError(
      "INVALID_INPUT",
      `The state encryption passphrase is too short (OpenTofu needs at least ${MIN_PASSPHRASE_LENGTH} characters).`,
      { hint: "Use a longer passphrase, for example one generated by a password manager." },
    );
  }
  return [
    `key_provider "pbkdf2" "opscrew" {`,
    `  passphrase = ${hclString(passphrase)}`,
    `}`,
    `method "aes_gcm" "opscrew" {`,
    `  keys = key_provider.pbkdf2.opscrew`,
    `}`,
    `state {`,
    `  method = method.aes_gcm.opscrew`,
    `}`,
    `plan {`,
    `  method = method.aes_gcm.opscrew`,
    `}`,
    ``,
  ].join("\n");
}

/**
 * Extracts passphrase values from a `TF_ENCRYPTION` value (raw and unescaped) so they can be
 * registered with the redactor.
 */
export function encryptionSecrets(value: string): string[] {
  const out: string[] = [];
  for (const match of value.matchAll(/passphrase\s*=\s*"((?:[^"\\]|\\.)*)"/g)) {
    const raw = match[1] ?? "";
    out.push(raw);
    try {
      out.push(
        JSON.parse(
          `"${raw.replaceAll("$${", () => "${").replaceAll("%%{", () => "%{")}"`,
        ) as string,
      );
    } catch {
      // Not a JSON-compatible escape sequence; the raw form is still registered.
    }
  }
  return out;
}
