// Feature 025: credential rotation (T2501, plan.md 1. and 11.). The committed record
// `opscrew/credentials.yaml`, and the plan's `credentials.maxAgeDays` and `check.credentials`.
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import {
  type CredentialsRecord,
  CredentialsRecordSchema,
  credentialMaxAgeDaysOf,
  DeployPlanSchema,
  parseArtifact,
  readArtifact,
  serializeArtifact,
  writeArtifact,
} from "./index";

const FIXTURES = new URL("./__fixtures__/", import.meta.url);

// biome-ignore lint/suspicious/noExplicitAny: a test plan is edited as loose JSON before parsing.
type Loose = Record<string, any>;

const RECORD: CredentialsRecord = {
  schemaVersion: 1,
  environments: {
    prod: {
      db: { madeAt: "2026-01-02T03:04:05.000Z", generation: 1 },
      "app:SECRET_KEY_BASE": { rotatedAt: "2026-11-08T10:00:00.000Z", generation: 2 },
      "deploy-key": { madeAt: "2026-01-02T03:04:05.000Z", generation: 1 },
      "grant:laptop/cache": { rotatedAt: "2026-11-08T10:00:00.000Z", generation: 3 },
      hetzner: { generation: 1 },
    },
    staging: {},
  },
};

const issuesOf = (value: unknown) => {
  const result = CredentialsRecordSchema.safeParse(value);
  expect(result.success).toBe(false);
  return result.error?.issues.map((i) => i.path.join(".")) ?? [];
};

describe("CredentialsRecordSchema", () => {
  it("accepts dates and generations per environment and credential", () => {
    expect(CredentialsRecordSchema.parse(RECORD)).toEqual(RECORD);
  });

  it("refuses a value-like or unknown field in an entry (strict objects)", () => {
    const withValue = structuredClone(RECORD) as Loose;
    withValue.environments.prod.db.value = "x";
    expect(issuesOf(withValue)).toEqual(["environments.prod.db"]);
    expect(issuesOf({ ...RECORD, secrets: {} })).toEqual([""]);
  });

  it("refuses a generation below 1 or not an integer, and a date that is not ISO", () => {
    const bad = structuredClone(RECORD) as Loose;
    bad.environments.prod.db.generation = 0;
    bad.environments.prod.hetzner.generation = 1.5;
    bad.environments.prod["deploy-key"].madeAt = "yesterday";
    bad.environments.prod["app:SECRET_KEY_BASE"] = { rotatedAt: "2026-11-08T10:00:00.000Z" };
    expect(issuesOf(bad).sort()).toEqual([
      "environments.prod.app:SECRET_KEY_BASE.generation",
      "environments.prod.db.generation",
      "environments.prod.deploy-key.madeAt",
      "environments.prod.hetzner.generation",
    ]);
  });

  it("refuses a bad environment name, a bad credential name and another schema version", () => {
    expect(issuesOf({ ...RECORD, schemaVersion: 2 })).toEqual(["schemaVersion"]);
    expect(issuesOf({ ...RECORD, environments: { "Bad Env": {} } })).toEqual([
      "environments.Bad Env",
    ]);
    for (const name of ["", "DB", "app:", "a b", ":db"]) {
      expect(
        issuesOf({ ...RECORD, environments: { prod: { [name]: { generation: 1 } } } }),
      ).toEqual([`environments.prod.${name}`]);
    }
  });
});

describe("opscrew/credentials.yaml as an artefact", () => {
  let dir: string;
  beforeEach(async () => {
    dir = await mkdtemp(join(tmpdir(), "opscrew-credentials-"));
  });
  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it("writes, reads back equal and serialises stably", async () => {
    const file = join(dir, "opscrew", "credentials.yaml");
    await writeArtifact("credentials", file, RECORD);
    const text = await readFile(file, "utf8");
    expect(text).toBe(serializeArtifact("credentials", RECORD));
    expect(text.startsWith("# Generated by OpsCrew (schema v1).")).toBe(true);
    expect(await readArtifact("credentials", file)).toEqual(RECORD);
    expect(parseArtifact("credentials", text, "opscrew/credentials.yaml")).toEqual(RECORD);
  });

  it("names the file and the next step when it is invalid", () => {
    expect(() =>
      parseArtifact("credentials", "schemaVersion: 1\nenvironments: []\n", "c.yaml"),
    ).toThrow(/c\.yaml is not valid:\n {2}- environments: /);
  });
});

describe("the plan's credential fields", () => {
  async function plan(): Promise<Loose> {
    const text = await readFile(new URL("plan.yaml", FIXTURES), "utf8");
    return parseArtifact("plan", text, "fixture");
  }

  it("keeps an existing plan as it is: no maxAgeDays read as 365, the check's credentials off", async () => {
    const parsed = DeployPlanSchema.parse(await plan());
    expect(parsed.credentials).toBeUndefined();
    expect(credentialMaxAgeDaysOf(parsed)).toBe(365);
    const checked = DeployPlanSchema.parse({
      ...(await plan()),
      observability: { check: { enabled: true } },
    });
    expect(checked.observability?.check?.credentials).toBeUndefined();
  });

  it("accepts maxAgeDays from 30 to 3650 and check.credentials", async () => {
    const parsed = DeployPlanSchema.parse({
      ...(await plan()),
      credentials: { maxAgeDays: 90 },
      observability: { check: { enabled: true, credentials: true } },
    });
    expect(credentialMaxAgeDaysOf(parsed)).toBe(90);
    expect(parsed.observability?.check?.credentials).toBe(true);
    for (const maxAgeDays of [30, 3650]) {
      expect(
        DeployPlanSchema.safeParse({ ...(await plan()), credentials: { maxAgeDays } }).success,
      ).toBe(true);
    }
  });

  it("refuses maxAgeDays outside 30–3650 or not an integer, and an unknown field", async () => {
    for (const maxAgeDays of [29, 3651, 90.5]) {
      const result = DeployPlanSchema.safeParse({ ...(await plan()), credentials: { maxAgeDays } });
      expect(result.error?.issues.map((i) => i.path.join("."))).toEqual(["credentials.maxAgeDays"]);
    }
    const extra = DeployPlanSchema.safeParse({ ...(await plan()), credentials: { other: 1 } });
    expect(extra.success).toBe(false);
  });
});
