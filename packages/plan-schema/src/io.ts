import {
  errorMessage,
  OpsCrewError,
  readTextIfExists,
  stripBom,
  writeFileAtomic,
} from "@opscrew/core";
import { parseDocument, stringify } from "yaml";
import type { z } from "zod";
import { type Architecture, ArchitectureSchema } from "./architecture";
import { type DeployPlan, DeployPlanSchema } from "./plan";
import { type Requirements, RequirementsSchema } from "./requirements";

/** The three committed OpsCrew artefacts. */
export type ArtifactKind = "architecture" | "requirements" | "plan";

/** All artefact kinds, in pipeline order. */
export const ARTIFACT_KINDS = [
  "architecture",
  "requirements",
  "plan",
] as const satisfies readonly ArtifactKind[];

interface ArtifactMap {
  architecture: Architecture;
  requirements: Requirements;
  plan: DeployPlan;
}

/** The validated value type of an artefact kind. */
export type ArtifactOf<K extends ArtifactKind> = ArtifactMap[K];

/** The zod schema of each artefact kind. */
export const ARTIFACT_SCHEMAS = {
  architecture: ArchitectureSchema,
  requirements: RequirementsSchema,
  plan: DeployPlanSchema,
} as const satisfies Record<ArtifactKind, z.ZodType>;

/** Repo-relative location of each artefact. */
export const ARTIFACT_FILES: Record<ArtifactKind, string> = {
  architecture: "opscrew/architecture.json",
  requirements: "opscrew/requirements.yaml",
  plan: "opscrew/plan.yaml",
};

/** Next step shown when an artefact is invalid. */
const ARTIFACT_HINTS: Record<ArtifactKind, string> = {
  architecture: "Run `opscrew analyze` to regenerate it.",
  requirements: "Run `opscrew interview` to answer the questions again.",
  plan: "Run `opscrew design` to regenerate the plan, or fix the field shown above.",
};

/** Next step shown when an artefact does not exist yet. */
const ARTIFACT_MISSING_HINTS: Record<ArtifactKind, string> = {
  architecture: "Run `opscrew analyze` to create it.",
  requirements: "Run `opscrew interview` to answer the deployment questions.",
  plan: "Run `opscrew design` to create the plan (after `opscrew analyze` and `opscrew interview`).",
};

/** First line of every YAML artefact. */
export const YAML_HEADER = "# Generated by OpsCrew (schema v1). Validated on every read.";

/** One validation problem: a dotted field path (`codeChanges.2.path`, `(root)` for the file). */
export interface ArtifactIssue {
  path: string;
  message: string;
}

/** A missing or invalid artefact. The message names the file, each bad field and the next step. */
export class ArtifactError extends OpsCrewError {
  override readonly name = "ArtifactError";
  readonly file: string;
  readonly issues: ArtifactIssue[];

  constructor(init: {
    code: "ARTIFACT_INVALID" | "ARTIFACT_MISSING";
    file: string;
    issues?: ArtifactIssue[];
    hint: string;
    message?: string;
    cause?: unknown;
  }) {
    const issues = init.issues ?? [];
    const message =
      init.message ??
      (init.code === "ARTIFACT_MISSING"
        ? `${init.file} does not exist. ${init.hint}`
        : [
            `${init.file} is not valid:`,
            ...issues.map((issue) => `  - ${issue.path}: ${issue.message}`),
            init.hint,
          ].join("\n"));
    super(init.code, message, { hint: init.hint, cause: init.cause });
    this.file = init.file;
    this.issues = issues;
  }
}

/** Per-parse error map: plain-English messages for the most common hand-editing mistakes. */
const errorMap: z.core.$ZodErrorMap = (issue) => {
  if (issue.code === "invalid_type" && issue.input === undefined) return "is missing";
  return undefined;
};

function formatPath(path: readonly PropertyKey[]): string {
  return path.length === 0 ? "(root)" : path.map(String).join(".");
}

function toIssues(error: z.ZodError): ArtifactIssue[] {
  const issues: ArtifactIssue[] = [];
  for (const issue of error.issues) {
    if (issue.code === "unrecognized_keys") {
      for (const key of issue.keys) {
        issues.push({
          path: formatPath([...issue.path, key]),
          message: "is not a known field (check the spelling or remove it)",
        });
      }
    } else {
      issues.push({ path: formatPath(issue.path), message: issue.message });
    }
  }
  return issues;
}

function invalid(kind: ArtifactKind, file: string, issues: ArtifactIssue[], cause?: unknown) {
  return new ArtifactError({
    code: "ARTIFACT_INVALID",
    file,
    issues,
    hint: ARTIFACT_HINTS[kind],
    cause,
  });
}

function validate<K extends ArtifactKind>(kind: K, data: unknown, file: string): ArtifactOf<K> {
  const schema = ARTIFACT_SCHEMAS[kind] as unknown as z.ZodType<ArtifactOf<K>>;
  const result = schema.safeParse(data, { error: errorMap });
  if (!result.success) throw invalid(kind, file, toIssues(result.error));
  return result.data;
}

/** Strips a UTF-8 BOM and normalises CRLF / CR line endings to LF. */
function normalizeText(text: string): string {
  return stripBom(text).replace(/\r\n?/g, "\n");
}

function decode(kind: ArtifactKind, text: string, file: string): unknown {
  if (text.trim() === "")
    throw invalid(kind, file, [{ path: "(root)", message: "the file is empty" }]);
  if (kind === "architecture") {
    try {
      return JSON.parse(text);
    } catch (cause) {
      throw invalid(
        kind,
        file,
        [{ path: "(root)", message: `is not valid JSON: ${errorMessage(cause)}` }],
        cause,
      );
    }
  }
  const doc = parseDocument(text, { prettyErrors: true });
  if (doc.errors.length > 0) {
    throw invalid(
      kind,
      file,
      doc.errors.map((e) => ({ path: "(root)", message: `is not valid YAML: ${e.message}` })),
    );
  }
  const data: unknown = doc.toJS();
  if (data === null || data === undefined) {
    throw invalid(kind, file, [{ path: "(root)", message: "the file is empty" }]);
  }
  return data;
}

/**
 * Parses and validates artefact text. Accepts a UTF-8 BOM and CRLF line endings.
 * @param file shown in error messages (usually the repo-relative path).
 * @throws ArtifactError with code `ARTIFACT_INVALID`.
 */
export function parseArtifact<K extends ArtifactKind>(
  kind: K,
  text: string,
  file: string,
): ArtifactOf<K> {
  return validate(kind, decode(kind, normalizeText(text), file), file);
}

function encode(kind: ArtifactKind, value: unknown): string {
  if (kind === "architecture") return `${JSON.stringify(value, null, 2)}\n`;
  // `yaml` always emits LF; lineWidth 0 disables folding so output does not depend on text length.
  const body = stringify(value, { indent: 2, lineWidth: 0, aliasDuplicateObjects: false });
  return `${YAML_HEADER}\n${body}`;
}

function serializeTo<K extends ArtifactKind>(kind: K, value: ArtifactOf<K>, file: string): string {
  return encode(kind, validate(kind, value, file));
}

/**
 * Validates and serialises an artefact deterministically (same value, same bytes; LF endings).
 * `architecture` is 2-space JSON; `requirements` and `plan` are YAML with a header comment.
 * @throws ArtifactError with code `ARTIFACT_INVALID` (invalid data is never serialised).
 */
export function serializeArtifact<K extends ArtifactKind>(kind: K, value: ArtifactOf<K>): string {
  return serializeTo(kind, value, ARTIFACT_FILES[kind]);
}

/**
 * Reads and validates an artefact file.
 * @throws ArtifactError with code `ARTIFACT_MISSING` when the file does not exist, or
 * `ARTIFACT_INVALID` when it cannot be parsed or fails validation.
 */
export async function readArtifact<K extends ArtifactKind>(
  kind: K,
  file: string,
): Promise<ArtifactOf<K>> {
  const value = await readOptionalArtifact(kind, file);
  if (value === undefined) {
    throw new ArtifactError({ code: "ARTIFACT_MISSING", file, hint: ARTIFACT_MISSING_HINTS[kind] });
  }
  return value;
}

/**
 * {@link readArtifact} for an artefact that may not exist yet: `undefined` when the file is
 * missing.
 * @throws ArtifactError with code `ARTIFACT_INVALID` when it cannot be parsed or fails validation.
 */
export async function readOptionalArtifact<K extends ArtifactKind>(
  kind: K,
  file: string,
): Promise<ArtifactOf<K> | undefined> {
  const text = await readTextIfExists(file);
  return text === undefined ? undefined : parseArtifact(kind, text, file);
}

/**
 * Validates, serialises and writes an artefact atomically (temp file in the same directory, then
 * rename). Creates parent directories.
 * @throws ArtifactError with code `ARTIFACT_INVALID`; nothing is written in that case.
 */
export async function writeArtifact<K extends ArtifactKind>(
  kind: K,
  file: string,
  value: ArtifactOf<K>,
): Promise<void> {
  // Committed files: the umask decides who may read them, as for any file the user creates.
  await writeFileAtomic(file, serializeTo(kind, value, file), { mode: 0o666 });
}
