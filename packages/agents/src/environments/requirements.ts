import {
  canonicalJson,
  type ProjectPaths,
  readTextIfExists,
  stripBom,
  toPosixRelative,
  writeFileAtomic,
} from "@opscrew/core";
import {
  ArtifactError,
  type Requirements,
  RequirementsSchema,
  readArtifact,
} from "@opscrew/plan-schema";
import { parseDocument, stringify } from "yaml";
import { z } from "zod";

/** An environment's own answers: a mapping, checked field by field once merged over prod's. */
const OwnAnswersSchema = z.record(z.string(), z.unknown());

/**
 * The requirements of the environment `paths` belong to: prod's answers
 * (`files.shared.requirementsBase`) with the environment's own (`files.requirements`, only the
 * answers that differ) over them, answered when the newer of the two was; prod's file as it is
 * for prod.
 * @throws ArtifactError `ARTIFACT_MISSING` without prod's answers, `ARTIFACT_INVALID` when the
 * environment's file is not a YAML mapping or the merged answers are not valid.
 */
export async function readEnvironmentRequirements(paths: ProjectPaths): Promise<Requirements> {
  const base = await readArtifact("requirements", paths.files.shared.requirementsBase);
  if (paths.environment === "prod") return base;
  const file = paths.files.requirements;
  const text = await readTextIfExists(file);
  if (text === undefined) return base;
  const invalid = (issues: { path: string; message: string }[]) =>
    new ArtifactError({
      code: "ARTIFACT_INVALID",
      file,
      issues,
      hint: `Fix the answers shown above in ${toPosixRelative(paths.root, file)}; every answer it leaves out is prod's.`,
    });
  const doc = parseDocument(stripBom(text));
  if (doc.errors.length > 0) {
    throw invalid(doc.errors.map((e) => ({ path: "(root)", message: e.message })));
  }
  const own = OwnAnswersSchema.safeParse(doc.toJS() ?? {});
  if (!own.success) throw invalid([{ path: "(root)", message: "must be a mapping of answers" }]);
  const merged = RequirementsSchema.safeParse({ ...base, ...own.data });
  if (!merged.success) {
    throw invalid(
      merged.error.issues.flatMap((issue) =>
        issue.code === "unrecognized_keys"
          ? issue.keys.map((key) => ({ path: key, message: "is not a known answer" }))
          : [{ path: issue.path.join(".") || "(root)", message: issue.message }],
      ),
    );
  }
  const answeredAt =
    Date.parse(base.answeredAt) > Date.parse(merged.data.answeredAt)
      ? base.answeredAt
      : merged.data.answeredAt;
  return { ...merged.data, answeredAt };
}

/**
 * Writes the environment's own answers (`files.requirements`): those of `requirements` that differ
 * from prod's, and when they were given. Every answer it leaves out stays prod's.
 */
export async function writeEnvironmentRequirements(
  paths: ProjectPaths,
  requirements: Requirements,
): Promise<void> {
  const base: Record<string, unknown> = await readArtifact(
    "requirements",
    paths.files.shared.requirementsBase,
  );
  const own = Object.fromEntries(
    Object.entries(RequirementsSchema.parse(requirements)).filter(
      ([key, value]) => key === "answeredAt" || canonicalJson(value) !== canonicalJson(base[key]),
    ),
  );
  const prods = toPosixRelative(paths.root, paths.files.shared.requirementsBase);
  const header = `# Generated by OpsCrew: the answers of the ${paths.environment} environment that differ from prod's (${prods}), which gives every other answer.`;
  const body = stringify(own, { indent: 2, lineWidth: 0 });
  // Committed files: the umask decides who may read them, as for any file the user creates.
  await writeFileAtomic(paths.files.requirements, `${header}\n${body}`, { mode: 0o666 });
}
