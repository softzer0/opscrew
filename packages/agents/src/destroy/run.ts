const SNAPSHOT_TIMEOUT_MS = 15 * 60_000;
const SNAPSHOT_POLL_MS = 5_000;
/** Input variable that lifts the server's delete and rebuild protection (root module, T303). */
const PROTECTION_OFF: Readonly<Record<string, string>> = { delete_protection: "false" };

/** Everything the plan and apply steps share. */
interface DestroyContext {
  deps: PhaseDeps;
  plan: DeployPlan;
  engine: IacEngine;
  /** Engine environment: provider tokens and `TF_ENCRYPTION`. Never logged. */
  env: Record<string, string | undefined>;
  /** Absolute root module directory. */
  dir: string;
  /** Prefix of this run's plan file names. */
  stamp: string;
}

/** Where the deploy secrets live, and why they cannot be removed when `api` is missing. */
interface GitHubTarget {
  owner?: string;
  repo?: string;
  api?: DestroyGitHubApi;
  skipReason?: string;
}

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

function lastLines(text: string, count = 8): string {
  return text.trim().split(/\r?\n/).slice(-count).join("\n");
}

function nothingDeployed(plan: DeployPlan): OpsCrewError {
  return new OpsCrewError(
    "PHASE_PRECONDITION",
    "Nothing is deployed for this project, so there is nothing to destroy.",
    {
      hint: plan.deployment.destroyedAt
        ? `OpsCrew already tore this deployment down (${plan.deployment.destroyedAt}). Run \`opscrew provision\` to create a new one.`
        : "Run `opscrew provision` to create a deployment.",
    },
  );
}

/** 1. A deployment and its state must be on this computer, with code that can lift protection. */
async function requirePreconditions(deps: PhaseDeps, plan: DeployPlan, statePath: string) {
  if (!(await exists(statePath))) {
    if (plan.deployment.serverIpv4 === undefined) throw nothingDeployed(plan);
    throw new OpsCrewError(
      "PHASE_PRECONDITION",
      `The infrastructure state of ${plan.app.name} is not on this computer (.opscrew/tfstate/prod.tfstate), so OpsCrew cannot tell what to delete. Nothing was changed.`,
      {
        hint: "Run `opscrew destroy` on the computer that ran `opscrew provision`, or copy its .opscrew/tfstate folder (and, with OpenTofu, its state passphrase from ~/.opscrew/projects/<project>/state_passphrase) here, then try again.",
      },
    );
  }
  const dir = join(deps.paths.root, plan.infra.dir);
  let names: string[];
  try {
    names = await readdir(dir);
  } catch {
    throw new OpsCrewError(
      "PHASE_PRECONDITION",
      `The infrastructure code (${plan.infra.dir}) is missing, so OpsCrew cannot plan the teardown. Nothing was changed.`,
      {
        hint: `Check out the branch that contains ${plan.infra.dir} (OpsCrew added it with the pull request \`opscrew provision\` opened), then run \`opscrew destroy\` again.`,
      },
    );
  }
  for (const name of names.filter((n) => n.endsWith(".tf")).sort()) {
    const text = await readFile(join(dir, name), "utf8").catch(() => "");
    if (/variable\s+"delete_protection"/.test(text)) return;
  }
  throw new OpsCrewError(
    "PHASE_PRECONDITION",
    `The infrastructure code in ${plan.infra.dir} was generated by an older OpsCrew and cannot lift the server's delete protection. Nothing was changed.`,
    {
      hint: "Run `opscrew provision` to regenerate the infrastructure files (its plan should show no changes), then run `opscrew destroy` again.",
    },
  );
}

/** 2. Cloudflare token (only when the plan manages DNS there); stops when it is missing or broken. */
async function checkCloudflare(
  deps: PhaseDeps,
  plan: DeployPlan,
  services: DestroyServices,
): Promise<boolean> {
  if (plan.dns.provider !== "cloudflare") return false;
  const connector = cloudflareConnector({
    env: deps.env,
    fetch: deps.fetch,
    redactor: deps.redactor,
    version: deps.version,
  });
  const requirement = connector.credentials;
  const api = services.cloudflare === undefined ? (connector.client ?? null) : services.cloudflare;
  const help = `It needs: ${requirement.scopes.join(", ")}. Create one at ${requirement.createUrl}`;
  if (api === null) {
    throw new OpsCrewError(
      "CREDENTIALS_MISSING",
      `No Cloudflare token found: set ${requirement.envVars.join(" or ")}. Nothing was changed.`,
      {
        hint: `The deployment's DNS records for ${plan.dns.domain ?? "the app"} are on Cloudflare; deleting the server without them would leave them pointing at a dead address. ${help}`,
      },
    );
  }
  const check = await api.verifyToken();
  if (!check.ok) {
    throw new OpsCrewError(
      "CREDENTIALS_INVALID",
      `Cloudflare: ${deps.redactor.redact(check.message)}`,
      {
        hint: `The token ${help}`,
      },
    );
  }
  return true;
}

/** 2. GitHub repository and token for the secret cleanup; optional, so problems become a reason. */
async function resolveGitHub(deps: PhaseDeps, services: DestroyServices): Promise<GitHubTarget> {
  const git = new GitClient({
    cwd: deps.paths.root,
    runner: deps.runner,
    env: deps.env,
    redactor: deps.redactor,
  });
  let coordinates: { owner: string; repo: string };
  try {
    if (!(await git.isRepo())) return { skipReason: "this project is not a git repository" };
    coordinates = await githubCoordinates(git);
  } catch {
    return { skipReason: "the repository has no GitHub remote named origin" };
  }
  let api: DestroyGitHubApi | null | undefined = services.github;
  if (api === undefined) {
    const token = await resolveGitHubToken(deps.env, deps.runner);
    if (token) deps.redactor.addLiteral(token, "github-token");
    api = token ? new GitHubClient({ token, fetch: deps.fetch, version: deps.version }) : null;
  }
  if (api === null) {
    const variables = githubConnector({ token: undefined, fetch: deps.fetch }).credentials.envVars;
    return {
      ...coordinates,
      skipReason: `no GitHub token was found (set ${variables.join(" or ")}, or sign in with \`gh auth login\`)`,
    };
  }
  return { ...coordinates, api };
}

function secretsPage(github: GitHubTarget): string {
  return github.owner && github.repo
    ? `https://github.com/${github.owner}/${github.repo}/settings/secrets/actions`
    : "your repository's Settings → Secrets and variables → Actions";
}

/** 3. Engine, state encryption and `init` with the same backend path as provisioning. */
async function setupEngine(
  deps: PhaseDeps,
  plan: DeployPlan,
  options: DestroyOptions,
  statePath: string,
): Promise<{ engine: IacEngine; env: Record<string, string | undefined> }> {
  const services = options.services ?? {};
  const preference = options.engine ?? plan.infra.engine;
  const engine = services.engine
    ? await services.engine(preference)
    : await selectEngine(preference, {
        runner: deps.runner,
        env: deps.env,
        redactor: deps.redactor,
        now: () => deps.clock.now(),
      });
  deps.reporter.info(`Using ${engineLabel(engine.info.name)} ${engine.info.version}.`);
  const env: Record<string, string | undefined> = { ...deps.env };
  if (plan.infra.stateEncryption) {
    if (engine.info.name === "tofu") {
      // Read, never create: a new passphrase could not decrypt the existing state.
      const passphrase = (
        await readFile(deps.paths.files.statePassphrase, "utf8").catch(() => undefined)
      )?.trim();
      if (!passphrase) {
        throw new OpsCrewError(
          "PHASE_PRECONDITION",
          "The OpenTofu state is encrypted, but this computer does not have its passphrase. Nothing was changed.",
          {
            hint: `Copy the state passphrase file from the computer that ran \`opscrew provision\` to ${deps.paths.files.statePassphrase}, then run \`opscrew destroy\` again.`,
          },
        );
      }
      deps.redactor.addLiteral(passphrase, "state-passphrase");
      env.TF_ENCRYPTION = tofuEncryptionEnv(passphrase);
    } else {
      deps.reporter.warn(
        "Terraform cannot read state that OpenTofu encrypted. If OpenTofu provisioned this deployment, run `opscrew destroy --engine tofu` instead.",
      );
    }
  }
  await mkdir(deps.paths.files.plansDir, { recursive: true });
  deps.reporter.step(`Initialising ${engineLabel(engine.info.name)} in ${plan.infra.dir}`);
  await engine.init(join(deps.paths.root, plan.infra.dir), {
    env,
    backendConfig: { path: statePath },
  });
  return { engine, env };
}

/** Saves a plan with delete protection off under `.opscrew/plans/`; removes the file on failure. */
async function makePlan(
  ctx: DestroyContext,
  suffix: string,
  destroy: boolean,
): Promise<PlanSummary> {
  const file = join(ctx.deps.paths.files.plansDir, `${ctx.stamp}-${suffix}.tfplan`);
  try {
    return await ctx.engine.plan(ctx.dir, file, {
      env: ctx.env,
      vars: { ...PROTECTION_OFF },
      ...(destroy ? { destroy: true } : {}),
    });
  } catch (error) {
    await rm(file, { force: true });
    throw error;
  }
}

/** Deletes a plan file so it can never be applied later. */
async function discard(summary: PlanSummary): Promise<void> {
  await rm(summary.planFile, { force: true });
}

/** Applies an approved saved plan, audits the outcome and stops with the log tail on failure. */
async function applyApproved(
  ctx: DestroyContext,
  summary: PlanSummary,
  options: { allowDestroy: boolean; what: string; hint: string },
): Promise<void> {
  const { deps } = ctx;
  const audit = (ok: boolean) =>
    deps.audit.append({
      kind: "iac",
      actor: "opscrew",
      action: "apply",
      phase: "provision",
      target: summary.planHash,
      decision: ok ? "approved" : "refused",
      detail: `${options.what}: ${ok ? "apply finished" : "apply failed"}`,
    });
  let result: Awaited<ReturnType<IacEngine["apply"]>>;
  try {
    result = await ctx.engine.apply(
      ctx.dir,
      summary.planFile,
      { approvedPlanHash: summary.planHash, allowDestroy: options.allowDestroy },
      { env: ctx.env },
    );
  } catch (error) {
    await audit(false);
    throw error;
  }
  await audit(result.ok);
  if (!result.ok) {
    const log = deps.redactor.redact(lastLines(result.log));
    const what = options.what.charAt(0).toUpperCase() + options.what.slice(1);
    throw new OpsCrewError("ENGINE_FAILED", `${what} failed:\n${log}`, { hint: options.hint });
  }
}

function snapshotFailed(
  deps: PhaseDeps,
  name: string,
  error: unknown,
  imageId?: number,
): OpsCrewError {
  const reason = (isUserFacingError(error) ? error.message : "unexpected error").replace(
    /[.\s]+$/,
    "",
  );
  return new OpsCrewError(
    "PROVIDER_ERROR",
    deps.redactor.redact(`The snapshot of ${name} failed: ${reason}. Nothing was deleted.`),
    {
      hint:
        imageId === undefined
          ? "Check the server in the Hetzner Cloud Console, then run `opscrew destroy` again, or `opscrew destroy --no-snapshot` to delete without a snapshot."
          : `The snapshot (Hetzner image ${imageId}) may still be in progress: check it in the Hetzner Cloud Console, then run \`opscrew destroy --no-snapshot\` once it is ready, or \`opscrew destroy\` again to take a new one.`,
    },
  );
}

/** `20261011T120000Z`: a Hetzner label value (no colons). */
function labelTime(date: Date): string {
  return date
    .toISOString()
    .replace(/[-:]/g, "")
    .replace(/\.\d+Z$/, "Z");
}

/** Whether this run takes a snapshot first (`auto`: when data lives only on the server). */
function snapshotWanted(plan: DeployPlan, options: DestroyOptions): boolean {
  const choice = options.snapshot ?? "auto";
  return choice === "auto" ? plan.services.postgres || plan.target.backups : choice;
}

/** Where a destroy snapshot is remembered, so a re-run reuses it instead of taking another. */
function snapshotRecordFile(deps: PhaseDeps): string {
  return join(deps.paths.stateDir, "destroy-snapshot.json");
}

/** 5. Snapshot of the server (when wanted and the server still exists); any failure stops. */
async function takeSnapshot(
  deps: PhaseDeps,
  plan: DeployPlan,
  options: DestroyOptions,
): Promise<number | undefined> {
  const services = options.services ?? {};
  const name = plan.app.name;
  const choice = options.snapshot ?? "auto";
  const wanted = snapshotWanted(plan, options);
  if (!wanted) {
    deps.reporter.info(
      choice === false
        ? "Skipping the snapshot, as requested."
        : "No snapshot: the database does not run on the server and Hetzner backups are off.",
    );
    return undefined;
  }
  const client: HetznerSnapshotApi | undefined =
    services.hetznerClient ??
    hetznerConnector({
      env: deps.env,
      fetch: deps.fetch,
      redactor: deps.redactor,
      version: deps.version,
    }).client;
  if (!client) {
    throw new OpsCrewError(
      "CREDENTIALS_MISSING",
      "No Hetzner Cloud token found: set HCLOUD_TOKEN.",
      {
        hint: "Create a Read & Write API token in the Hetzner Cloud Console (your project → Security → API tokens).",
      },
    );
  }

  const selector = `managed-by=opscrew,app=${name}`;
  let servers: Awaited<ReturnType<HetznerSnapshotApi["listServers"]>>;
  try {
    servers = await client.listServers({ labelSelector: selector });
  } catch (error) {
    throw snapshotFailed(deps, name, error);
  }
  if (servers.length === 0) {
    deps.reporter.info(
      `No snapshot: the server ${name} no longer exists in Hetzner Cloud, so there is nothing to keep.`,
    );
    return undefined;
  }
  const server = servers.find((s) => s.name === name) ?? (servers.length === 1 ? servers[0] : null);
  if (!server) {
    throw new OpsCrewError(
      "PHASE_PRECONDITION",
      `Several servers are labelled ${selector} and none is named ${name}, so OpsCrew cannot tell which one to snapshot. Nothing was changed.`,
      {
        hint: "Take a snapshot in the Hetzner Cloud Console yourself, then run `opscrew destroy --no-snapshot`.",
      },
    );
  }

  // A run that stopped after its snapshot (refused, failed apply) reuses it on the next try.
  const earlier = await readFile(snapshotRecordFile(deps), "utf8")
    .then((text) => JSON.parse(text) as { serverId?: number; imageId?: number })
    .catch(() => undefined);
  if (earlier?.serverId === server.id && typeof earlier.imageId === "number") {
    deps.reporter.info(
      `Reusing the snapshot taken by the earlier run (Hetzner image ${earlier.imageId}).`,
    );
    return earlier.imageId;
  }

  deps.reporter.step(
    `Taking a snapshot of the server ${server.name} (this can take several minutes)`,
  );
  const takenAt = deps.clock.now();
  let created: Awaited<ReturnType<HetznerSnapshotApi["createSnapshot"]>>;
  try {
    created = await client.createSnapshot(server.id, {
      description: `OpsCrew snapshot of ${name} before opscrew destroy (${takenAt.toISOString()})`,
      labels: {
        app: name,
        "created-by": "opscrew",
        reason: "destroy",
        "taken-at": labelTime(takenAt),
      },
    });
  } catch (error) {
    throw snapshotFailed(deps, name, error);
  }
  await deps.audit.append({
    kind: "provider-call",
    actor: "opscrew",
    action: "create snapshot",
    phase: "provision",
    target: `hetzner server ${server.id}`,
    detail: `snapshot image ${created.imageId} of ${name} before destroy`,
  });
  try {
    await client.waitForAction(created.actionId, {
      timeoutMs: SNAPSHOT_TIMEOUT_MS,
      intervalMs: SNAPSHOT_POLL_MS,
      ...(services.sleep ? { sleep: services.sleep } : {}),
      ...(services.now ? { now: services.now } : {}),
    });
  } catch (error) {
    throw snapshotFailed(deps, name, error, created.imageId);
  }
  deps.reporter.success(`The snapshot of ${name} is ready (Hetzner image ${created.imageId}).`);
  await writeFileAtomic(
    snapshotRecordFile(deps),
    `${JSON.stringify({ serverId: server.id, imageId: created.imageId, takenAt: takenAt.toISOString() })}\n`,
  );
  return created.imageId;
}

function snapshotKept(imageId: number | undefined): string {
  return imageId === undefined
    ? ""
    : ` The snapshot (Hetzner image ${imageId}) was kept; delete it in the Hetzner Cloud Console if you do not need it.`;
}

/**
 * 6. Lifts delete protection with a plan that may only change the server's protection, after an
 * `iac-apply` approval. Returns whether protection is off now and the approval, when one was given.
 */
async function liftProtection(
  ctx: DestroyContext,
  serverInState: boolean,
  snapshotImageId: number | undefined,
): Promise<{ off: boolean; approval?: ApprovalRecord }> {
  const { deps, plan } = ctx;
  const name = plan.app.name;
  if (!serverInState) {
    deps.reporter.info(
      "The server is no longer in the infrastructure state, so there is no delete protection to lift.",
    );
    return { off: false };
  }
  deps.reporter.step(`Planning to lift delete protection on ${name}`);
  const summary = await makePlan(ctx, "unprotect", false);
  try {
    if (summary.changes.length === 0) {
      deps.reporter.info(`Delete protection on ${name} is already off.`);
      return { off: true };
    }
    const problems = unprotectPlanProblems(summary.changes, summary.planJson);
    if (problems.length > 0) {
      throw new OpsCrewError(
        "PHASE_PRECONDITION",
        [
          `Lifting the delete protection on ${name} would also change other things, so OpsCrew stopped. Nothing was changed.`,
          ...problems.map((p) => `  ${p}`),
        ].join("\n"),
        {
          hint: "The infrastructure was probably changed outside OpsCrew, or its files no longer match what was applied. Run `opscrew drift` to see the differences and `opscrew provision` to bring everything back in line, then run `opscrew destroy` again.",
        },
      );
    }
    const approval = await deps.approvals.request({
      kind: "iac-apply",
      title: `Lift delete protection on ${name}`,
      details: [
        `${engineLabel(summary.engine.name)} ${summary.engine.version} plan:`,
        ...describeChanges(summary.changes),
        "This only turns off the server's delete and rebuild protection so that the next plan can delete it. Nothing is deleted yet.",
        `Plan hash: ${summary.planHash}`,
      ].join("\n"),
      planHash: summary.planHash,
    });
    if (!approval.approved) {
      throw new OpsCrewError(
        "APPROVAL_REFUSED",
        `Delete protection on ${name} was not lifted${approval.reason ? ` (${approval.reason})` : ""}. Nothing was deleted.${snapshotKept(snapshotImageId)}`,
        { hint: "Run `opscrew destroy` again when you are ready." },
      );
    }
    await deps.approvals.assertApprovedPlan(summary.planHash);
    deps.reporter.step(`Lifting delete protection on ${name}`);
    await applyApproved(ctx, summary, {
      allowDestroy: false,
      what: "lifting delete protection",
      hint: "Fix the cause shown above, then run `opscrew destroy` again. Nothing was deleted.",
    });
    deps.reporter.success(`Delete protection on ${name} is off.`);
    return { off: true, approval };
  } finally {
    await discard(summary);
  }
}

/**
 * 7. The destroy plan, approved with `allowDestroy` and the typed server name, then applied.
 * Returns the deleted resources and the approval (none when nothing was left to delete).
 */
async function destroyInfrastructure(
  ctx: DestroyContext,
  snapshotImageId: number | undefined,
  protectionOff: boolean,
  confirmed: ReadonlySet<string>,
): Promise<{ destroyed: ResourceChange[]; approval?: ApprovalRecord }> {
  const { deps, plan } = ctx;
  const name = plan.app.name;
  deps.reporter.step("Planning the teardown");
  const summary = await makePlan(ctx, "destroy", true);
  try {
    if (summary.changes.length === 0) {
      deps.reporter.info("Nothing is left to delete.");
      return { destroyed: [] };
    }
    const problems = destroyPlanProblems(summary.changes);
    if (problems.length > 0) {
      throw new OpsCrewError(
        "PHASE_PRECONDITION",
        [
          "The teardown plan would do more than delete, so OpsCrew stopped. Nothing was changed.",
          ...problems.map((p) => `  ${p}`),
        ].join("\n"),
        { hint: "Run `opscrew drift` to see what changed, then run `opscrew destroy` again." },
      );
    }
    const unexpected = summary.changes.filter((change) => !confirmed.has(change.address));
    if (unexpected.length > 0) {
      throw new OpsCrewError(
        "PHASE_PRECONDITION",
        [
          "The teardown plan now deletes resources that were not in the list you confirmed, so OpsCrew stopped. Nothing was deleted.",
          ...unexpected.map((change) => `  ${change.address}`),
        ].join("\n"),
        { hint: "Run `opscrew destroy` again to see the current list and confirm it." },
      );
    }
    const serverDeleted = deletesServer(summary.changes);
    const warning = dataWarning(plan, serverDeleted);
    const snapshotLine =
      snapshotImageId !== undefined
        ? `Snapshot: Hetzner image ${snapshotImageId} keeps a copy of the server (billed per GB per month; OpsCrew never deletes it).`
        : serverDeleted
          ? "Snapshot: none. What is stored on the server cannot be recovered after this."
          : "Snapshot: none.";
    const providers =
      plan.dns.provider === "cloudflare" ? "Hetzner Cloud and Cloudflare" : "Hetzner Cloud";
    const count = summary.changes.length;
    const approval = await deps.approvals.request({
      kind: "iac-apply",
      title: `Delete ${name} on ${providers} (${count} ${count === 1 ? "resource" : "resources"} to delete)`,
      details: [
        `${engineLabel(summary.engine.name)} ${summary.engine.version} destroy plan:`,
        ...describeChanges(summary.changes),
        ...(warning ? [warning] : []),
        snapshotLine,
        `Plan hash: ${summary.planHash}`,
      ].join("\n"),
      planHash: summary.planHash,
      allowDestroy: true,
      confirmPhrase: name,
      costDelta: { amount: -plan.cost.monthly.amount, currency: plan.cost.monthly.currency },
    });
    if (!approval.approved) {
      const lifted = protectionOff
        ? ` Delete protection on ${name} is already lifted, so the server is not protected against deletion now.`
        : "";
      throw new OpsCrewError(
        "APPROVAL_REFUSED",
        `The teardown was not approved${approval.reason ? ` (${approval.reason})` : ""}. Nothing was deleted.${lifted}${snapshotKept(snapshotImageId)}`,
        {
          hint: protectionOff
            ? `Run \`opscrew provision\` to turn delete protection back on, or run \`opscrew destroy\` again and type ${name} to delete the deployment.`
            : `Run \`opscrew destroy\` again and type ${name} when you are ready.`,
        },
      );
    }
    await deps.approvals.assertApprovedPlan(summary.planHash, { allowDestroy: true });
    deps.reporter.step("Deleting the infrastructure (this usually takes a minute or two)");
    await applyApproved(ctx, summary, {
      allowDestroy: true,
      what: "deleting the infrastructure",
      hint: "Fix the cause shown above, then run `opscrew destroy` again; it continues with what is left.",
    });
    deps.reporter.success(`Deleted ${count} ${count === 1 ? "resource" : "resources"}.`);
    return { destroyed: summary.changes, approval };
  } finally {
    await discard(summary);
  }
}

/** 8. Removes the deploy secrets after a `github-secrets` approval. Names only, never values. */
async function removeDeploySecrets(deps: PhaseDeps, github: GitHubTarget): Promise<string[]> {
  const { api, owner, repo } = github;
  if (!api || !owner || !repo) return [];
  const names = Object.values(DEPLOY_SECRETS).sort();
  const where = `${owner}/${repo}`;
  const approval = await deps.approvals.request({
    kind: "github-secrets",
    title: `Remove the deploy secrets from ${where}`,
    details: [
      "GitHub Actions secrets to delete (names only):",
      ...names.map((name) => `  ${name}`),
      "Without them the deploy workflow cannot reach a server; `opscrew provision` stores new ones.",
    ].join("\n"),
  });
  if (!approval.approved) {
    throw new OpsCrewError(
      "APPROVAL_REFUSED",
      `The deploy secrets were not removed from ${where}. The infrastructure is deleted.`,
      {
        hint: "Run `opscrew destroy` again to remove them and finish the cleanup (the pinned host key and opscrew/plan.yaml).",
      },
    );
  }
  const removed: string[] = [];
  for (const name of names) {
    try {
      await api.deleteActionsSecret(owner, repo, name);
    } catch (error) {
      const reason = isUserFacingError(error) ? error.message : "unexpected error";
      throw new OpsCrewError(
        error instanceof OpsCrewError ? error.code : "PROVIDER_ERROR",
        deps.redactor.redact(
          `The infrastructure is deleted, but removing the GitHub secret ${name} failed: ${reason}`,
        ),
        {
          hint: `${error instanceof OpsCrewError && error.hint ? `${error.hint} ` : ""}Then run \`opscrew destroy\` again to finish the cleanup.`,
        },
      );
    }
    await deps.audit.append({
      kind: "secret-set",
      actor: "opscrew",
      action: `delete secret ${name}`,
      phase: "provision",
      target: where,
      decision: "approved",
    });
    removed.push(name);
  }
  deps.reporter.success(
    `Removed ${removed.length} deploy secrets from GitHub Actions in ${where}.`,
  );
  return removed;
}

/** 8. Forgets the server's pinned SSH host key; other hosts in the file are kept. */
async function forgetHostKey(deps: PhaseDeps, plan: DeployPlan): Promise<void> {
  const hosts = [plan.deployment.serverIpv4, plan.deployment.serverIpv6].filter(
    (host): host is string => host !== undefined && host !== "",
  );
  if (hosts.length === 0) return;
  const file = deps.paths.files.knownHosts;
  let text: string;
  try {
    text = await readFile(file, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return;
    throw error;
  }
  const result = removeHostKeys(text, hosts);
  if (result.removed === 0) return;
  await writeFileAtomic(file, result.text, { mode: 0o644 });
  deps.reporter.info("Removed the server's SSH host key from OpsCrew's known_hosts.");
}

/** 8. The plan without the server's addresses, with `destroyedAt` and the approvals recorded. */
function destroyedPlan(
  plan: DeployPlan,
  at: string,
  approvals: readonly (ApprovalRecord | undefined)[],
): DeployPlan {
  const { serverIpv4, serverIpv6, url, lastCompletedPhase, ...kept } = plan.deployment;
  const recorded = approvals
    .filter((a): a is ApprovalRecord => a?.planHash !== undefined)
    .map((a) => ({
      planHash: a.planHash as string,
      approver: a.approver,
      at: a.decidedAt,
      kind: "iac-apply",
    }));
  return {
    ...plan,
    updatedAt: at,
    approvals: [...plan.approvals, ...recorded],
    deployment: { ...kept, destroyedAt: at },
  };
}

/** 9. What still exists after the teardown, in plain English. */
function remainingAfterDestroy(input: {
  plan: DeployPlan;
  snapshotImageId: number | undefined;
  github: GitHubTarget;
  secretsRemoved: readonly string[];
}): string[] {
  const { plan, github } = input;
  const items: string[] = [];
  if (input.snapshotImageId !== undefined) {
    items.push(
      `The snapshot of ${plan.app.name} (Hetzner image ${input.snapshotImageId}). Hetzner bills snapshots per GB per month and OpsCrew never deletes them; delete it in the Hetzner Cloud Console when you no longer need it.`,
    );
  }
  if (input.secretsRemoved.length === 0 && github.skipReason) {
    items.push(
      `The deploy secrets in GitHub Actions (${Object.values(DEPLOY_SECRETS).sort().join(", ")}): OpsCrew did not remove them because ${github.skipReason}. Delete them at ${secretsPage(github)}.`,
    );
  }
  const image =
    github.owner && github.repo
      ? `ghcr.io/${github.owner}/${github.repo}`.toLowerCase()
      : "ghcr.io/<owner>/<repo>";
  items.push(
    `The app's container images in GitHub's container registry (${image}). Delete them in the package settings on GitHub if you no longer need them.`,
  );
  items.push(
    `The deployment files in the repository (opscrew/ and ${plan.cicd.workflowPath}). Pushes still build an image, but the deploy step fails until \`opscrew provision\` creates a new server from these files.`,
  );
  items.push(
    "The project's SSH deploy key on this computer, kept so a new deployment can reuse it.",
  );
  return items;
}

/**
 * `opscrew destroy`: tears a deployment down through the same plan → approval → apply path as
 * provisioning (constitution I). In order: preconditions → credentials (Hetzner; Cloudflare when
 * used; GitHub optional) → engine and `init` → a preview destroy plan (never applied) → optional
 * server snapshot → a protection-lifting plan that may only change the server's protection
 * (`iac-apply` approval) → the destroy plan (`iac-apply` approval with `allowDestroy` and the
 * server name typed to confirm) → removal of the GitHub deploy secrets (`github-secrets`
 * approval), the pinned host key and the plan's server addresses. A refusal or failure at any step
 * leaves everything after it untouched, and running it again continues where it stopped.
 */
export async function runDestroy(
  deps: PhaseDeps,
  options: DestroyOptions = {},
): Promise<DestroyResult> {
  const services = options.services ?? {};
  const plan = await readArtifact("plan", deps.paths.files.plan);
  const name = plan.app.name;
  const statePath = join(deps.paths.files.tfstateDir, "prod.tfstate");

  // 1. Preconditions
  await requirePreconditions(deps, plan, statePath);

  // 2. Credentials
  const usesCloudflare = plan.dns.provider === "cloudflare";
  deps.reporter.step(
    `Checking your Hetzner Cloud${usesCloudflare ? ", Cloudflare" : ""} and GitHub access`,
  );
  await checkHetzner(deps, services.hetzner ? { hetzner: services.hetzner } : {});
  await checkCloudflare(deps, plan, services);
  const github = await resolveGitHub(deps, services);
  if (github.skipReason) {
    deps.reporter.warn(
      `OpsCrew cannot remove the deploy secrets from GitHub Actions: ${github.skipReason}. The teardown continues; delete them yourself afterwards at ${secretsPage(github)}.`,
    );
  }

  // 3. Engine, state encryption, init
  const { engine, env } = await setupEngine(deps, plan, options, statePath);
  const ctx: DestroyContext = {
    deps,
    plan,
    engine,
    env,
    dir: join(deps.paths.root, plan.infra.dir),
    stamp: deps.clock.now().toISOString().replace(/[:.]/g, "-"),
  };

  // 4. Preview: what the teardown deletes (this plan is never applied)
  deps.reporter.step("Planning the teardown to see what it deletes");
  const preview = await makePlan(ctx, "destroy-preview", true);
  await discard(preview);
  if (preview.changes.length === 0 && plan.deployment.serverIpv4 === undefined) {
    throw nothingDeployed(plan);
  }
  const serverInState = deletesServer(preview.changes);
  if (preview.changes.length > 0) {
    deps.reporter.info(
      ["The teardown deletes these resources:", ...describeChanges(preview.changes)].join("\n"),
    );
  } else {
    deps.reporter.info("The infrastructure is already deleted; OpsCrew finishes the cleanup.");
  }
  const warning = dataWarning(plan, serverInState);
  if (warning) deps.reporter.warn(warning);
  const snapshotFirst = serverInState && snapshotWanted(plan, options);
  if (snapshotFirst) {
    deps.reporter.info(
      "A snapshot of the server is taken first, so its data can be restored later (Hetzner bills snapshots per GB per month; `--no-snapshot` skips it).",
    );
  }
  if (options.confirm !== undefined && preview.changes.length > 0) {
    const confirmed = await options.confirm({
      name,
      resources: preview.changes,
      snapshot: snapshotFirst,
      ...(warning ? { dataWarning: warning } : {}),
    });
    await deps.audit.append({
      kind: "approval",
      actor: "user",
      action: "destroy-confirm",
      phase: "provision",
      target: name,
      decision: confirmed ? "approved" : "refused",
      detail: `typed confirmation for deleting ${preview.changes.length} resources`,
    });
    if (!confirmed) {
      throw new OpsCrewError(
        "APPROVAL_REFUSED",
        `The server name was not confirmed, so nothing was deleted and nothing was changed.`,
        { hint: `Run \`opscrew destroy\` again and type ${name} when asked.` },
      );
    }
  }

  // 5. Snapshot
  const snapshotImageId = await takeSnapshot(deps, plan, options);

  // 6. Lift delete protection
  const protection = await liftProtection(ctx, serverInState, snapshotImageId);

  // 7. Destroy
  const { destroyed, approval: destroyApproval } = await destroyInfrastructure(
    ctx,
    snapshotImageId,
    protection.off,
    new Set(preview.changes.map((change) => change.address)),
  );

  // 8. Cleanup: deploy secrets, pinned host key, plan, stored-secrets record, phase state
  const secretsRemoved = await removeDeploySecrets(deps, github);
  await forgetHostKey(deps, plan);
  const at = deps.clock.now().toISOString();
  await writeArtifact(
    "plan",
    deps.paths.files.plan,
    destroyedPlan(plan, at, [protection.approval, destroyApproval]),
  );
  await rm(join(deps.paths.projectHomeDir, "deploy_secrets.json"), { force: true });
  await rm(snapshotRecordFile(deps), { force: true });
  await deps.state.markPhase("provision", "skipped", "infrastructure destroyed");
  await deps.audit.append({
    kind: "phase",
    actor: "opscrew",
    action: "destroy",
    phase: "provision",
    target: name,
    detail: `infrastructure destroyed: ${destroyed.length} resources deleted, ${secretsRemoved.length} deploy secrets removed${snapshotImageId !== undefined ? `, snapshot image ${snapshotImageId} kept` : ""}`,
  });
  deps.reporter.success(`${name} is torn down. opscrew/plan.yaml records when.`);

  // 9. What remains
  const remaining = remainingAfterDestroy({ plan, snapshotImageId, github, secretsRemoved });
  deps.reporter.info(["What remains:", ...remaining.map((item) => `  - ${item}`)].join("\n"));
  return {
    ...(snapshotImageId !== undefined ? { snapshotImageId } : {}),
    destroyed,
    secretsRemoved,
    remaining,
  };
}
