/**
 * The shared edge on every server (contracts/components.md "The edge on a server"): one Compose
 * project, `opscrew-edge` in `/srv/edge`, with Caddy and kamal-proxy in front of every OpsCrew app
 * on the server. Each app is its own Compose project in `/srv/apps/<app>`, its data in
 * `/srv/data/<app>`.
 */
import { sha256Hex } from "@opscrew/core";
import type { DeployPlan } from "@opscrew/plan-schema";
import { stringify } from "yaml";
import { IMAGES } from "../pins";
import { memoryLimit } from "../runtime/components";
import { composeLiteral, hardened } from "../runtime/services";
import { TUNNEL_ORIGIN_PORT, tunnelMode, webFilterMode } from "../tunnel";
import type { RenderedFile } from "../types";

/** The edge's Compose project, and the external network the edge and every app's web service join. */
export const EDGE_PROJECT = "opscrew-edge";

/** Where the edge lives on the server: its `compose.yaml` and `sites/<app>.caddy`. */
export const EDGE_DIR = "/srv/edge";

/** The app's folder on the server (its Compose project, env files and logs): `/srv/apps/<app>`. */
export function appDir(plan: DeployPlan): string {
  return `/srv/apps/${plan.app.name}`;
}

/**
 * The edge's version stamp: the date OpsCrew last changed the edge (its pins or its files) as
 * YYYYMMDD, then that day's change number (01, 02 …), so a later edge always has a larger number.
 * A deploy replaces the server's edge only with a larger one. Change it with every change of the
 * edge's Compose file; a test fails until it is changed.
 */
export const EDGE_VERSION = 2026101902;

/** The key of {@link EDGE_VERSION} in the edge's Compose file (a Compose extension field). */
export const EDGE_VERSION_KEY = "x-opscrew-edge-version";

/** Where Caddy sends every app's traffic: kamal-proxy, which routes by hostname to the app's copy. */
export const EDGE_UPSTREAM = "kamal-proxy:80";

/**
 * The memory limits of the edge's containers, in MB: with 32 MB for each tunnelled app's
 * connector, they make up the edge's 128 MB that design counts on every server (data-model.md
 * "Sizing figures").
 */
export const CADDY_MEMORY_MB = 64;
const KAMAL_PROXY_MEMORY_MB = 32;

/** The folder of the apps' site files in the Caddy container (the server's `/srv/edge/sites`). */
const CADDY_SITES = "/etc/caddy/sites";

/** Caddy's main configuration: only the apps' site files. */
const CADDYFILE = [
  "# OpsCrew's shared edge: each OpsCrew app on this server has its site in /srv/edge/sites/<app>.caddy.",
  `import ${CADDY_SITES}/*.caddy`,
  "",
].join("\n");

/**
 * Caddy's published ports: loopback in tunnel mode (the tunnel connector reaches it there), IPv4
 * only behind OpsCrew's web filter (the filter covers IPv4 only), otherwise HTTP, HTTPS and HTTP/3.
 */
function caddyPorts(plan: DeployPlan): string[] {
  if (tunnelMode(plan)) return [`127.0.0.1:${TUNNEL_ORIGIN_PORT}:80`];
  if (webFilterMode(plan)) return ["0.0.0.0:80:80", "0.0.0.0:443:443", "0.0.0.0:443:443/udp"];
  return ["80:80", "443:443", "443:443/udp"];
}

const HEADER = [
  "# Generated by OpsCrew from opscrew/plan.yaml; `opscrew provision` regenerates it.",
  "# OpsCrew's shared edge on the server (/srv/edge, Compose project opscrew-edge): Caddy and",
  "# kamal-proxy in front of every OpsCrew app there. Each app's deploy brings this file and puts it",
  `# in /srv/edge only when its ${EDGE_VERSION_KEY} is larger than the server's.`,
].join("\n");

/**
 * `opscrew/runtime/edge/compose.yaml`: Caddy and kamal-proxy on the external network
 * `opscrew-edge`, stamped with {@link EDGE_VERSION}. kamal-proxy keeps the apps' routes on a named
 * volume, so they survive a recreate; Caddy reads each app's site file from `/srv/edge/sites` and
 * publishes the ports the server's access mode needs (the same for every app on the server).
 */
export function renderEdgeCompose(plan: DeployPlan): RenderedFile {
  const document = {
    name: EDGE_PROJECT,
    [EDGE_VERSION_KEY]: EDGE_VERSION,
    services: {
      "kamal-proxy": {
        image: IMAGES.kamalProxy.ref,
        restart: "unless-stopped",
        volumes: ["kamal-proxy-config:/home/kamal-proxy/.config/kamal-proxy"],
        ...memoryLimit(KAMAL_PROXY_MEMORY_MB),
        ...hardened({ noCapabilities: true }),
        networks: [EDGE_PROJECT],
      },
      caddy: {
        image: IMAGES.caddy.ref,
        restart: "unless-stopped",
        ...memoryLimit(CADDY_MEMORY_MB),
        ports: caddyPorts(plan),
        configs: [{ source: "caddyfile", target: "/etc/caddy/Caddyfile" }],
        volumes: [`./sites:${CADDY_SITES}:ro`, "caddy_data:/data", "caddy_config:/config"],
        // A changed main configuration changes this label, so Compose recreates Caddy with it.
        labels: { "dev.opscrew.caddyfile-sha256": sha256Hex(CADDYFILE) },
        depends_on: ["kamal-proxy"],
        ...hardened(),
        networks: [EDGE_PROJECT],
      },
    },
    configs: { caddyfile: { content: composeLiteral(CADDYFILE) } },
    networks: { [EDGE_PROJECT]: { external: true } },
    volumes: { caddy_data: {}, caddy_config: {}, "kamal-proxy-config": {} },
  };
  return {
    path: "opscrew/runtime/edge/compose.yaml",
    content: `${HEADER}\n${stringify(document, { lineWidth: 0 })}`,
    kind: "runtime",
  };
}
