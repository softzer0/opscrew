// biome-ignore-all lint/suspicious/noTemplateCurlyInString: these strings are Compose, bash and GitHub Actions syntax, not JavaScript templates.
// Feature 025 (T2509): the previous values a credential rotation keeps beside a generated app
// secret (`APP_PREVIOUS_KEYS`, `BETTER_AUTH_SECRETS`) reach the app in a Portainer stack and on a
// site, and an unset one is no variable at all.
import { spawnSync } from "node:child_process";
import { findExecutable } from "@opscrew/core";
import { type DeployPlan, DeployPlanSchema } from "@opscrew/plan-schema";
import { describe, expect, it } from "vitest";
import { parse } from "yaml";
import { testContext } from "./__fixtures__/plans";
import { portainerStackEnvKeys, renderPortainerStack } from "./portainer-target";
import { portainerTestPlan } from "./portainer-target/__fixtures__/plans";
import { previousValueVariables } from "./previous-values";
import { pagesPlan, ssrPlan } from "./serverless/__fixtures__/plans";
import { deploySecretNamesFor, renderCloudflareWorkersWorkflow, renderWorkflow } from "./workflow";

/** `plan` with Laravel's key and Better Auth's secret generated by OpsCrew. */
function generating(plan: DeployPlan): DeployPlan {
  return DeployPlanSchema.parse({
    ...plan,
    app: {
      ...plan.app,
      env: [
        ...plan.app.env,
        { name: "APP_KEY", secret: true, source: "generated" },
        { name: "BETTER_AUTH_SECRET", secret: true, source: "generated" },
      ],
    },
  });
}

type Step = { name?: string; env?: Record<string, string>; run?: string };
const steps = (content: string, job: string): Step[] =>
  (parse(content) as { jobs: Record<string, { steps: Step[] }> }).jobs[job]?.steps ?? [];

describe("previousValueVariables", () => {
  it("names the previous values of the secrets OpsCrew generates, not of the user's own", () => {
    expect(previousValueVariables(generating(portainerTestPlan()))).toEqual([
      "APP_PREVIOUS_KEYS",
      "BETTER_AUTH_SECRETS",
    ]);
    const theirs = portainerTestPlan({
      env: [{ name: "APP_KEY", secret: true, source: "user" }],
    });
    expect(previousValueVariables(theirs)).toEqual([]);
  });
});

describe("a Portainer stack", () => {
  const plan = generating(portainerTestPlan());

  it("names each previous value bare, and its Env holds only those that have a value", () => {
    const doc = parse(renderPortainerStack(plan, testContext()).content) as {
      services: { app: { environment: Record<string, string | null> } };
    };
    const environment = doc.services.app.environment;
    // Bare (`NAME:` with no value): Compose takes it from the stack's Env, and leaves it unset
    // in the container when the Env has none.
    expect(environment.APP_PREVIOUS_KEYS).toBeNull();
    expect(environment.BETTER_AUTH_SECRETS).toBeNull();
    expect(environment.APP_KEY).toBe("${APP_KEY}");

    expect(portainerStackEnvKeys(plan).app).not.toContain("APP_PREVIOUS_KEYS");
    const held = portainerStackEnvKeys(plan, { previousValues: ["APP_PREVIOUS_KEYS"] }).app;
    expect(held).toContain("APP_PREVIOUS_KEYS");
    expect(held).not.toContain("BETTER_AUTH_SECRETS");
  });

  it("has none without a generated secret that keeps previous values", () => {
    const content = renderPortainerStack(portainerTestPlan(), testContext()).content;
    expect(content).not.toContain("APP_PREVIOUS_KEYS");
  });
});

describe("a site's workflow", () => {
  it("reads each previous value from its own secret on Cloudflare and GitHub Pages", () => {
    for (const plan of [generating(ssrPlan()), generating(pagesPlan())]) {
      expect(deploySecretNamesFor(plan)).toEqual(
        expect.arrayContaining([
          "OPSCREW_ENV_APP_KEY",
          "OPSCREW_ENV_APP_PREVIOUS_KEYS",
          "OPSCREW_ENV_BETTER_AUTH_SECRETS",
        ]),
      );
    }
  });

  it("always gives a server-rendered version the previous values, empty when their secret is", () => {
    const content = renderCloudflareWorkersWorkflow(generating(ssrPlan()), testContext()).content;
    const prepare = steps(content, "deploy").find((s) => s.name === "Prepare Wrangler");
    expect(prepare?.env?.OPSCREW_ENV_APP_PREVIOUS_KEYS).toBe(
      "${{ secrets.OPSCREW_ENV_APP_PREVIOUS_KEYS }}",
    );
    const filter = /jq -n '([^']*)'/.exec(prepare?.run ?? "")?.[1] ?? "";
    expect(filter).toBe(
      '{"APP_KEY": env.OPSCREW_ENV_APP_KEY, "BETTER_AUTH_SECRET": env.OPSCREW_ENV_BETTER_AUTH_SECRET, "APP_PREVIOUS_KEYS": (env.OPSCREW_ENV_APP_PREVIOUS_KEYS // ""), "BETTER_AUTH_SECRETS": (env.OPSCREW_ENV_BETTER_AUTH_SECRETS // "")}',
    );
  });

  it.skipIf(!findExecutable("jq"))("writes an empty or unset previous value as empty", () => {
    const content = renderCloudflareWorkersWorkflow(generating(ssrPlan()), testContext()).content;
    const prepare = steps(content, "deploy").find((s) => s.name === "Prepare Wrangler");
    const filter = /jq -n '([^']*)'/.exec(prepare?.run ?? "")?.[1] ?? "";
    const { OPSCREW_ENV_APP_PREVIOUS_KEYS: _unset, ...env } = process.env;
    const result = spawnSync("jq", ["-c", "-n", filter], {
      encoding: "utf8",
      env: {
        ...env,
        OPSCREW_ENV_APP_KEY: "k2",
        OPSCREW_ENV_BETTER_AUTH_SECRET: "s1",
        OPSCREW_ENV_BETTER_AUTH_SECRETS: "",
      },
    });
    expect(JSON.parse(result.stdout)).toEqual({
      APP_KEY: "k2",
      BETTER_AUTH_SECRET: "s1",
      APP_PREVIOUS_KEYS: "",
      BETTER_AUTH_SECRETS: "",
    });
  });

  it.skipIf(!findExecutable("jq"))("writes a set previous value into the secrets file", () => {
    const content = renderCloudflareWorkersWorkflow(generating(ssrPlan()), testContext()).content;
    const prepare = steps(content, "deploy").find((s) => s.name === "Prepare Wrangler");
    const filter = /jq -n '([^']*)'/.exec(prepare?.run ?? "")?.[1] ?? "";
    const result = spawnSync("jq", ["-c", "-n", filter], {
      encoding: "utf8",
      env: {
        ...process.env,
        OPSCREW_ENV_APP_KEY: "k2",
        OPSCREW_ENV_BETTER_AUTH_SECRET: "s1",
        OPSCREW_ENV_APP_PREVIOUS_KEYS: "k1",
        OPSCREW_ENV_BETTER_AUTH_SECRETS: "1:s0",
      },
    });
    expect(JSON.parse(result.stdout)).toEqual({
      APP_KEY: "k2",
      BETTER_AUTH_SECRET: "s1",
      APP_PREVIOUS_KEYS: "k1",
      BETTER_AUTH_SECRETS: "1:s0",
    });
  });

  it.skipIf(!findExecutable("bash"))(
    "unsets an empty previous value before the site's build",
    () => {
      const content = renderWorkflow(generating(pagesPlan()), testContext()).content;
      const build = steps(content, "build").find((s) => s.name === "Build the site");
      expect(build?.env?.APP_PREVIOUS_KEYS).toBe("${{ secrets.OPSCREW_ENV_APP_PREVIOUS_KEYS }}");
      const lines = (build?.run ?? "").split("\n").filter((line) => line.includes("unset"));
      expect(lines).toEqual([
        '[ -n "${APP_PREVIOUS_KEYS-}" ] || unset APP_PREVIOUS_KEYS',
        '[ -n "${BETTER_AUTH_SECRETS-}" ] || unset BETTER_AUTH_SECRETS',
      ]);
      const script = `set -euo pipefail\n${lines.join("\n")}\nenv | grep -E '^(APP_PREVIOUS_KEYS|BETTER_AUTH_SECRETS)=' || true`;
      const result = spawnSync("bash", ["-c", script], {
        encoding: "utf8",
        env: { ...process.env, APP_PREVIOUS_KEYS: "", BETTER_AUTH_SECRETS: "2:b,1:a" },
      });
      expect(result.stdout.trim()).toBe("BETTER_AUTH_SECRETS=2:b,1:a");
    },
  );
});
