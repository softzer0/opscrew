import type { ProjectFacts } from "@opscrew/plan-schema";

/** Container recipe chosen for an app. */
export type DockerStack =
  | "next-standalone"
  | "node-server"
  | "static-spa"
  | "python-fastapi"
  | "python-django"
  | "python-generic";

/** Prefixes of environment variables that frameworks bake into the frontend at build time. */
export const CLIENT_ENV_PREFIXES = [
  "VITE_",
  "NEXT_PUBLIC_",
  "REACT_APP_",
  "PUBLIC_",
  "NUXT_PUBLIC_",
  "EXPO_PUBLIC_",
  "GATSBY_",
] as const;

/** True when a variable is read at build time and shipped to browsers (never put secrets there). */
export function isClientExposedEnvName(name: string): boolean {
  return CLIENT_ENV_PREFIXES.some((prefix) => name.startsWith(prefix));
}

const NODE_SERVER_FRAMEWORKS = ["express", "fastify", "@nestjs/core", "nestjs", "hono", "koa"];

function hasFramework(facts: ProjectFacts, ...names: string[]): boolean {
  return facts.frameworks.some((f) => names.includes(f.name));
}

/** Picks the recipe for the detected stack, or undefined when OpsCrew has no template for it. */
export function detectStack(facts: ProjectFacts): DockerStack | undefined {
  const usesPython = facts.languages.includes("python");
  const usesJs = facts.languages.includes("javascript") || facts.languages.includes("typescript");
  if (hasFramework(facts, "fastapi")) return "python-fastapi";
  if (hasFramework(facts, "django")) return "python-django";
  if (facts.appKind === "static-spa") return "static-spa";
  if (hasFramework(facts, "next")) return "next-standalone";
  if (usesJs && (hasFramework(facts, ...NODE_SERVER_FRAMEWORKS) || facts.build.startCommand)) {
    return "node-server";
  }
  if (usesPython) return "python-generic";
  if (usesJs) return "node-server";
  return undefined;
}

const HEADER = (stack: DockerStack) =>
  [
    "# syntax=docker/dockerfile:1",
    `# Generated by OpsCrew (${stack}). You own this file: edit it freely; OpsCrew only creates it`,
    "# when it is missing.",
  ].join("\n");

/** Shell snippet installing JS dependencies with the detected package manager. */
function jsInstall(facts: ProjectFacts): string {
  switch (facts.packageManager) {
    case "pnpm":
      return "corepack enable && if [ -f pnpm-lock.yaml ]; then pnpm install --frozen-lockfile; else pnpm install; fi";
    case "yarn":
      return "corepack enable && if [ -f yarn.lock ]; then yarn install --frozen-lockfile; else yarn install; fi";
    default:
      return "if [ -f package-lock.json ]; then npm ci; else npm install; fi";
  }
}

function jsRun(facts: ProjectFacts, script: string): string {
  switch (facts.packageManager) {
    case "pnpm":
      return `pnpm run ${script}`;
    case "yarn":
      return `yarn ${script}`;
    default:
      return `npm run ${script}`;
  }
}

/** `ARG`/`ENV` lines so client-exposed variables are available while the frontend is built. */
function buildArgs(facts: ProjectFacts): string[] {
  const names = facts.envVars.map((v) => v.name).filter(isClientExposedEnvName);
  if (names.length === 0) return [];
  return [
    "# Values baked into the frontend at build time (public by design; never put secrets here).",
    ...names.flatMap((name) => [`ARG ${name}`, `ENV ${name}=$${name}`]),
  ];
}

function needsCorepack(facts: ProjectFacts): boolean {
  return facts.packageManager === "pnpm" || facts.packageManager === "yarn";
}

export function nextStandaloneDockerfile(facts: ProjectFacts, port: number): string {
  const build = facts.build.buildCommand ?? jsRun(facts, "build");
  return [
    HEADER("next-standalone"),
    '# Requires `output: "standalone"` in next.config.* (OpsCrew adds it as a code change).',
    "",
    "FROM node:22-alpine AS build",
    "WORKDIR /app",
    "COPY . .",
    `RUN ${jsInstall(facts)}`,
    "ENV NEXT_TELEMETRY_DISABLED=1",
    ...buildArgs(facts),
    `RUN ${build} && mkdir -p public`,
    "",
    "FROM node:22-alpine AS runtime",
    "WORKDIR /app",
    `ENV NODE_ENV=production NEXT_TELEMETRY_DISABLED=1 PORT=${port} HOSTNAME=0.0.0.0`,
    "COPY --from=build --chown=node:node /app/public ./public",
    "COPY --from=build --chown=node:node /app/.next/standalone ./",
    "COPY --from=build --chown=node:node /app/.next/static ./.next/static",
    "USER node",
    `EXPOSE ${port}`,
    'CMD ["node", "server.js"]',
    "",
  ].join("\n");
}

export function nodeServerDockerfile(facts: ProjectFacts, port: number): string {
  const start = facts.build.startCommand ?? jsRun(facts, "start");
  const lines = [
    HEADER("node-server"),
    "",
    "FROM node:22-alpine AS build",
    "WORKDIR /app",
    "COPY . .",
    `RUN ${jsInstall(facts)}`,
    ...buildArgs(facts),
  ];
  if (facts.build.buildCommand) lines.push(`RUN ${facts.build.buildCommand}`);
  lines.push(
    "",
    "FROM node:22-alpine AS runtime",
    "WORKDIR /app",
    `ENV NODE_ENV=production PORT=${port}`,
  );
  if (needsCorepack(facts)) lines.push("RUN corepack enable");
  lines.push(
    "COPY --from=build --chown=node:node /app ./",
    "USER node",
    `EXPOSE ${port}`,
    `CMD ["sh", "-c", ${JSON.stringify(start)}]`,
    "",
  );
  return lines.join("\n");
}

export function staticSpaDockerfile(facts: ProjectFacts): string {
  const build = facts.build.buildCommand ?? jsRun(facts, "build");
  const outputDir = facts.build.outputDir ?? "dist";
  const caddyfile = [
    "{",
    "\tauto_https off",
    "\tadmin off",
    "}",
    ":8080 {",
    "\troot * /srv",
    "\tencode zstd gzip",
    "\ttry_files {path} /index.html",
    "\tfile_server",
    "}",
  ];
  return [
    HEADER("static-spa"),
    "# Builds the site with Node, then serves the static files with Caddy on port 8080 as an",
    "# unprivileged user (OpsCrew's outer Caddy terminates TLS in front of it).",
    "",
    "FROM node:22-alpine AS build",
    "WORKDIR /app",
    "COPY . .",
    `RUN ${jsInstall(facts)}`,
    ...buildArgs(facts),
    `RUN ${build}`,
    "",
    "FROM caddy:2-alpine",
    `COPY --from=build /app/${outputDir} /srv`,
    `RUN printf '%s\\n' ${caddyfile.map((line) => `'${line}'`).join(" ")} > /etc/caddy/Caddyfile \\`,
    "  && chown -R 65534:65534 /data /config",
    "USER 65534",
    "EXPOSE 8080",
    "",
  ].join("\n");
}

function pythonBase(stack: DockerStack, port: number, facts: ProjectFacts): string[] {
  const version = facts.runtimeVersions.python?.match(/^3\.\d+/)?.[0] ?? "3.13";
  return [
    HEADER(stack),
    "",
    `FROM python:${version}-slim`,
    `ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PIP_NO_CACHE_DIR=1 PORT=${port}`,
    "WORKDIR /app",
    "RUN useradd --create-home --uid 10001 app",
    ...pythonInstall(facts),
    "COPY --chown=app:app . .",
  ];
}

function pythonInstall(facts: ProjectFacts): string[] {
  switch (facts.packageManager) {
    case "poetry":
      return [
        "COPY pyproject.toml poetry.lock* ./",
        "RUN pip install poetry && poetry config virtualenvs.create false && poetry install --only main --no-root",
      ];
    case "uv":
      return [
        "COPY pyproject.toml uv.lock* ./",
        "RUN pip install uv && uv pip install --system -r pyproject.toml",
      ];
    case "pipenv":
      return [
        "COPY Pipfile Pipfile.lock* ./",
        "RUN pip install pipenv && pipenv install --system --deploy",
      ];
    default:
      return ["COPY requirements*.txt ./", "RUN pip install -r requirements.txt"];
  }
}

/** Uvicorn target (`module:app`) from the detected start command, or `main:app`. */
function uvicornTarget(facts: ProjectFacts): string {
  const match = facts.build.startCommand?.match(/uvicorn\s+([\w.]+:[\w]+)/);
  return match?.[1] ?? "main:app";
}

export function fastapiDockerfile(facts: ProjectFacts, port: number): string {
  return [
    ...pythonBase("python-fastapi", port, facts),
    "RUN pip install uvicorn",
    "USER app",
    `EXPOSE ${port}`,
    `CMD ["sh", "-c", "uvicorn ${uvicornTarget(facts)} --host 0.0.0.0 --port \${PORT}"]`,
    "",
  ].join("\n");
}

export function djangoDockerfile(facts: ProjectFacts, port: number): string {
  const module =
    facts.build.startCommand?.match(/([\w.]+)\.wsgi/)?.[1] ?? facts.name.replace(/-/g, "_");
  return [
    ...pythonBase("python-django", port, facts),
    "RUN pip install gunicorn",
    `ENV DJANGO_WSGI_MODULE=${module}.wsgi`,
    "USER app",
    `EXPOSE ${port}`,
    "# Run migrations as part of your release process (for example `python manage.py migrate`).",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: shell variables expanded inside the container.
    'CMD ["sh", "-c", "gunicorn ${DJANGO_WSGI_MODULE} --bind 0.0.0.0:${PORT}"]',
    "",
  ].join("\n");
}

export function pythonGenericDockerfile(facts: ProjectFacts, port: number): string {
  const start = facts.build.startCommand ?? "python main.py";
  return [
    ...pythonBase("python-generic", port, facts),
    "USER app",
    `EXPOSE ${port}`,
    `CMD ["sh", "-c", ${JSON.stringify(start)}]`,
    "",
  ].join("\n");
}
