import type { ProjectFacts } from "@opscrew/plan-schema";

/** Container recipe chosen for an app. */
export type DockerStack =
  | "next-standalone"
  | "node-server"
  | "static-spa"
  | "python-fastapi"
  | "python-django"
  | "python-generic";

/** Prefixes of environment variables that frameworks bake into the frontend at build time. */
export const CLIENT_ENV_PREFIXES = [
  "VITE_",
  "NEXT_PUBLIC_",
  "REACT_APP_",
  "PUBLIC_",
  "NUXT_PUBLIC_",
  "EXPO_PUBLIC_",
  "GATSBY_",
] as const;

/** True when a variable is read at build time and shipped to browsers (never put secrets there). */
export function isClientExposedEnvName(name: string): boolean {
  return CLIENT_ENV_PREFIXES.some((prefix) => name.startsWith(prefix));
}

const NODE_SERVER_FRAMEWORKS = ["express", "fastify", "@nestjs/core", "nestjs", "hono", "koa"];

function hasFramework(facts: ProjectFacts, ...names: string[]): boolean {
  return facts.frameworks.some((f) => names.includes(f.name));
}

/** Picks the recipe for the detected stack, or undefined when OpsCrew has no template for it. */
export function detectStack(facts: ProjectFacts): DockerStack | undefined {
  const usesPython = facts.languages.includes("python");
  const usesJs = facts.languages.includes("javascript") || facts.languages.includes("typescript");
  if (hasFramework(facts, "fastapi")) return "python-fastapi";
  if (hasFramework(facts, "django")) return "python-django";
  if (facts.appKind === "static-spa") return "static-spa";
  if (hasFramework(facts, "next")) return "next-standalone";
  if (usesJs && (hasFramework(facts, ...NODE_SERVER_FRAMEWORKS) || facts.build.startCommand)) {
    return "node-server";
  }
  if (usesPython) return "python-generic";
  if (usesJs) return "node-server";
  return undefined;
}

const HEADER = (stack: DockerStack) =>
  [
    "# syntax=docker/dockerfile:1",
    `# Generated by OpsCrew (${stack}). You own this file: edit it freely; OpsCrew only creates it`,
    "# when it is missing.",
  ].join("\n");

/** Shell snippet installing JS dependencies with the detected package manager. */
function jsInstall(facts: ProjectFacts): string {
  switch (facts.packageManager) {
    case "pnpm":
      return "corepack enable && if [ -f pnpm-lock.yaml ]; then pnpm install --frozen-lockfile; else pnpm install; fi";
    case "yarn":
      return "corepack enable && if [ -f yarn.lock ]; then yarn install --frozen-lockfile; else yarn install; fi";
    default:
      return "if [ -f package-lock.json ]; then npm ci; else npm install; fi";
  }
}

function jsRun(facts: ProjectFacts, script: string): string {
  switch (facts.packageManager) {
    case "pnpm":
      return `pnpm run ${script}`;
    case "yarn":
      return `yarn ${script}`;
    default:
      return `npm run ${script}`;
  }
}

/** `ARG`/`ENV` lines so client-exposed variables are available while the frontend is built. */
function buildArgs(facts: ProjectFacts): string[] {
  const names = facts.envVars.map((v) => v.name).filter(isClientExposedEnvName);
  if (names.length === 0) return [];
  return [
    "# Values baked into the frontend at build time (public by design; never put secrets here).",
    ...names.flatMap((name) => [`ARG ${name}`, `ENV ${name}=$${name}`]),
  ];
}

function needsCorepack(facts: ProjectFacts): boolean {
  return facts.packageManager === "pnpm" || facts.packageManager === "yarn";
}

/** Normalised repo-relative directory (`.` for the repository root). */
function normaliseDir(path: string): string {
  const dir = path
    .replace(/^(?:\.\/)+/, "")
    .replace(/\/+$/, "")
    .replace(/\/\.$/, "");
  return dir === "" ? "." : dir;
}

/** Frameworks whose folder locates the app when `facts.appDir` is absent (older facts). */
const STACK_FRAMEWORKS: Record<DockerStack, string[]> = {
  "next-standalone": ["next"],
  "node-server": NODE_SERVER_FRAMEWORKS,
  "static-spa": [],
  "python-fastapi": ["fastapi"],
  "python-django": ["django"],
  "python-generic": [],
};

/**
 * Repo-relative directory of the app (`.` for the repository root): `facts.appDir` when detection
 * recorded it, otherwise the folder of the stack's framework (or of the first framework).
 */
export function appDirectory(facts: ProjectFacts, stack: DockerStack): string {
  if (facts.appDir !== undefined) return normaliseDir(facts.appDir);
  const names = STACK_FRAMEWORKS[stack];
  const framework = facts.frameworks.find((f) => names.includes(f.name)) ?? facts.frameworks.at(0);
  return normaliseDir(framework?.path ?? ".");
}

const PLAIN_PATH = /^[A-Za-z0-9._/@+-]+$/;
const PLAIN_SOURCE = /^[A-Za-z0-9._/@+*-]+$/;

/** A `COPY` instruction that switches to the JSON form when a path needs quoting. */
function copy(prefix: string, sources: string[], destination: string): string {
  const paths = [...sources, destination];
  return paths.every((path) => PLAIN_SOURCE.test(path))
    ? `${prefix} ${paths.join(" ")}`
    : `${prefix} [${paths.map((path) => JSON.stringify(path)).join(", ")}]`;
}

/** `COPY --from=build` that switches to the JSON form when a path needs quoting. */
function copyFromBuild(source: string, destination: string): string {
  return copy("COPY --from=build --chown=node:node", [source], destination);
}

function shellQuote(value: string): string {
  return PLAIN_PATH.test(value) ? value : `'${value.replace(/'/g, `'\\''`)}'`;
}

/** Package name of a yarn workspace, read from the commands detection wrote. */
function yarnWorkspaceName(facts: ProjectFacts): string | undefined {
  const { buildCommand, startCommand, installCommand } = facts.build;
  for (const command of [startCommand, buildCommand, installCommand]) {
    const name = command?.match(/\byarn workspace (\S+)/)?.[1];
    if (name) return name;
  }
  return undefined;
}

/**
 * Command running a package script of the app from the repository root: the plain form at the
 * root, the package manager's workspace flag for a workspace member, and `cd <dir> && …` for a
 * folder that is not part of a workspace (or a yarn workspace whose package name is unknown).
 */
function jsScript(facts: ProjectFacts, dir: string, script: string): string {
  if (dir === ".") return jsRun(facts, script);
  const inDir = `cd ${shellQuote(dir)} && ${jsRun(facts, script)}`;
  if (!facts.monorepo) return inDir;
  switch (facts.packageManager) {
    case "pnpm":
      return `pnpm --filter ${shellQuote(`./${dir}`)} run ${script}`;
    case "yarn": {
      const name = yarnWorkspaceName(facts);
      return name ? `yarn workspace ${shellQuote(name)} ${script}` : inDir;
    }
    default:
      return `npm run ${script} --workspace ${shellQuote(dir)}`;
  }
}

/**
 * Dependency install for the app: at the root for the root app and for workspace members (the
 * root lockfile covers the whole workspace), inside the folder otherwise.
 */
function jsInstallFor(facts: ProjectFacts, dir: string): string {
  return dir === "." || facts.monorepo
    ? jsInstall(facts)
    : `cd ${shellQuote(dir)} && ${jsInstall(facts)}`;
}

/** Header note for an app in a subfolder (nothing at the root). */
function jsFolderNote(facts: ProjectFacts, dir: string): string[] {
  if (dir === ".") return [];
  return facts.monorepo
    ? [
        "# The image is built from the repository root so the root lockfile and workspace packages",
        `# are available; the app lives in ${dir}.`,
      ]
    : [`# The image is built from the repository root; the app lives in ${dir}.`];
}

/** Start script the Next.js build stage writes into the image (`/out` becomes `/app`). */
const NEXT_START_SCRIPT = "/app/opscrew-start.sh";

/**
 * Shell lines copying one standalone layout into `/out`: the standalone root, `.next/static` and
 * `public` next to the server (in `serverDir`, relative to the standalone root), and a start
 * script running that server.
 */
function standaloneToOut(dir: string, serverDir: string): string[] {
  const inApp = (path: string) => (dir === "." ? path : `${dir}/${path}`);
  const out = (path: string) => (serverDir === "." ? `/out/${path}` : `/out/${serverDir}/${path}`);
  const server = serverDir === "." ? "/app/server.js" : `/app/${serverDir}/server.js`;
  return [
    `    cp -a ${shellQuote(`${inApp(".next/standalone")}/.`)} /out/ \\`,
    `    && mkdir -p ${shellQuote(out(".next"))} \\`,
    `    && cp -a ${shellQuote(inApp(".next/static"))} ${shellQuote(out(".next/static"))} \\`,
    `    && cp -a ${shellQuote(inApp("public"))} ${shellQuote(out("public"))} \\`,
    `    && printf '#!/bin/sh\\nexec node "%s"\\n' ${shellQuote(server)} > /out/opscrew-start.sh; \\`,
  ];
}

/**
 * Next.js image that builds whether or not the config sets `output: "standalone"`. The build stage
 * gathers what runs into `/out` and writes `/out/opscrew-start.sh`: with standalone output, the
 * standalone server plus `.next/static` and `public` (a small image); without it, the whole built
 * app with its dependencies, started with `next start` on `$PORT` and `$HOSTNAME`. The runtime
 * stage copies `/out` and runs the script, so a missed config edit costs image size, never a
 * failed build. For an app in a monorepo folder (`facts.appDir`, or the `next` framework's path),
 * the image is built from the repository root so the root lockfile and workspace packages are
 * available; the standalone server is found at `<dir>/server.js` (with `outputFileTracingRoot` at
 * the repository root) or at the standalone root.
 */
export function nextStandaloneDockerfile(facts: ProjectFacts, port: number): string {
  const dir = appDirectory(facts, "next-standalone");
  const atRoot = dir === ".";
  const inApp = (path: string) => (atRoot ? path : `${dir}/${path}`);
  const command = facts.build.buildCommand ?? jsScript(facts, dir, "build");
  // A `cd` must not leak into the `mkdir` that follows, which runs from the repository root.
  const build = /^cd\s/.test(command) ? `(${command})` : command;
  const standalone = inApp(".next/standalone");
  const notes = atRoot
    ? [
        '# Builds with or without `output: "standalone"` in next.config.* (OpsCrew adds it as a code',
        "# change). With it, the image ships only the standalone server, .next/static and public;",
        "# without it, the image holds the whole built app with its dependencies and runs",
        "# `next start`. The build stage gathers what runs into /out, with /out/opscrew-start.sh as",
        "# the entry point.",
      ]
    : [
        `# Builds with or without \`output: "standalone"\` in ${dir}/next.config.*. Because the app`,
        "# lives in a monorepo, the standalone output also needs `outputFileTracingRoot` pointing at",
        "# the repository root, for example",
        `# \`outputFileTracingRoot: path.join(__dirname, "${"../".repeat(dir.split("/").length)}")\` (OpsCrew adds both as a code change).`,
        `# With them, the image ships only the standalone server (started from ${dir}/server.js),`,
        "# .next/static and public; without them, the image holds the whole built workspace with its",
        "# dependencies and runs `next start` in the app folder. The build stage gathers what runs",
        "# into /out, with /out/opscrew-start.sh as the entry point. The image is built from the",
        "# repository root so the root lockfile and workspace packages are available.",
      ];
  const resolveNext = `node -p "require.resolve('next/dist/bin/next')"`;
  const nextBin = atRoot ? resolveNext : `cd ${shellQuote(dir)} && ${resolveNext}`;
  return [
    HEADER("next-standalone"),
    ...notes,
    "",
    "FROM node:22-alpine AS build",
    "WORKDIR /app",
    "COPY . .",
    `RUN ${jsInstallFor(facts, dir)}`,
    "ENV NEXT_TELEMETRY_DISABLED=1",
    ...buildArgs(facts),
    `RUN ${build} && mkdir -p ${shellQuote(inApp("public"))}`,
    "# The standalone server when the build made one, otherwise the whole app with `next start`.",
    "RUN mkdir -p /out \\",
    `  && if [ -f ${shellQuote(`${standalone}/${inApp("server.js")}`)} ]; then \\`,
    ...standaloneToOut(dir, dir),
    ...(atRoot
      ? []
      : [
          `  elif [ -f ${shellQuote(`${standalone}/server.js`)} ]; then \\`,
          ...standaloneToOut(dir, "."),
        ]),
    "  else \\",
    `    rm -rf ${shellQuote(inApp(".next/cache"))} && cp -a . /out/ \\`,
    // Assigned first, so a next binary that cannot be found fails the build, not the deploy.
    `    && NEXT_BIN="$(${nextBin})" && [ -n "$NEXT_BIN" ] \\`,
    `    && printf '#!/bin/sh\\ncd "%s"\\nexec node "%s" start --hostname "\${HOSTNAME:-0.0.0.0}" --port "\${PORT:-${port}}"\\n' \\`,
    `      ${shellQuote(atRoot ? "/app" : `/app/${dir}`)} "$NEXT_BIN" > /out/opscrew-start.sh; \\`,
    "  fi",
    "",
    "FROM node:22-alpine AS runtime",
    "WORKDIR /app",
    `ENV NODE_ENV=production NEXT_TELEMETRY_DISABLED=1 PORT=${port} HOSTNAME=0.0.0.0`,
    copyFromBuild("/out", "./"),
    "USER node",
    `EXPOSE ${port}`,
    `CMD ["sh", ${JSON.stringify(NEXT_START_SCRIPT)}]`,
    "",
  ].join("\n");
}

/** Node.js server image; an app in a subfolder is built from the root and started from there. */
export function nodeServerDockerfile(facts: ProjectFacts, port: number): string {
  const dir = appDirectory(facts, "node-server");
  const start = facts.build.startCommand ?? jsScript(facts, dir, "start");
  const lines = [
    HEADER("node-server"),
    ...jsFolderNote(facts, dir),
    "",
    "FROM node:22-alpine AS build",
    "WORKDIR /app",
    "COPY . .",
    `RUN ${jsInstallFor(facts, dir)}`,
    ...buildArgs(facts),
  ];
  if (facts.build.buildCommand) lines.push(`RUN ${facts.build.buildCommand}`);
  lines.push(
    "",
    "FROM node:22-alpine AS runtime",
    "WORKDIR /app",
    `ENV NODE_ENV=production PORT=${port}`,
  );
  if (needsCorepack(facts)) lines.push("RUN corepack enable");
  lines.push(
    "COPY --from=build --chown=node:node /app ./",
    "USER node",
    `EXPOSE ${port}`,
    `CMD ["sh", "-c", ${JSON.stringify(start)}]`,
    "",
  );
  return lines.join("\n");
}

/**
 * Static site image. For an app in a subfolder, the default output folder is `<dir>/dist`
 * (a detected `outputDir` is already relative to the repository root).
 */
export function staticSpaDockerfile(facts: ProjectFacts): string {
  const dir = appDirectory(facts, "static-spa");
  const build = facts.build.buildCommand ?? jsScript(facts, dir, "build");
  const outputDir = facts.build.outputDir ?? (dir === "." ? "dist" : `${dir}/dist`);
  const caddyfile = [
    "{",
    "\tauto_https off",
    "\tadmin off",
    "}",
    ":8080 {",
    "\troot * /srv",
    "\tencode zstd gzip",
    "\ttry_files {path} /index.html",
    "\tfile_server",
    "}",
  ];
  return [
    HEADER("static-spa"),
    "# Builds the site with Node, then serves the static files with Caddy on port 8080 as an",
    "# unprivileged user (OpsCrew's outer Caddy terminates TLS in front of it).",
    ...jsFolderNote(facts, dir),
    "",
    "FROM node:22-alpine AS build",
    "WORKDIR /app",
    "COPY . .",
    `RUN ${jsInstallFor(facts, dir)}`,
    ...buildArgs(facts),
    `RUN ${build}`,
    "",
    "FROM caddy:2-alpine",
    copy("COPY --from=build", [`/app/${outputDir}`], "/srv"),
    `RUN printf '%s\\n' ${caddyfile.map((line) => `'${line}'`).join(" ")} > /etc/caddy/Caddyfile \\`,
    "  && chown -R 65534:65534 /data /config",
    "USER 65534",
    "EXPOSE 8080",
    "",
  ].join("\n");
}

/**
 * Base of every Python image. Only the app folder is copied into `/app`, so an app in a subfolder
 * runs exactly as it would at the root.
 */
function pythonBase(stack: DockerStack, port: number, facts: ProjectFacts): string[] {
  const version = facts.runtimeVersions.python?.match(/^3\.\d+/)?.[0] ?? "3.13";
  const dir = appDirectory(facts, stack);
  return [
    HEADER(stack),
    ...(dir === "."
      ? []
      : [`# Built from the repository root; only ${dir} is copied into the image.`]),
    "",
    `FROM python:${version}-slim`,
    `ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PIP_NO_CACHE_DIR=1 PORT=${port}`,
    "WORKDIR /app",
    "RUN useradd --create-home --uid 10001 app",
    ...pythonInstall(facts, dir),
    copy("COPY --chown=app:app", [dir], "."),
  ];
}

function pythonInstall(facts: ProjectFacts, dir: string): string[] {
  const inApp = (...files: string[]) =>
    files.map((file) => (dir === "." ? file : `${dir}/${file}`));
  switch (facts.packageManager) {
    case "poetry":
      return [
        copy("COPY", inApp("pyproject.toml", "poetry.lock*"), "./"),
        "RUN pip install poetry && poetry config virtualenvs.create false && poetry install --only main --no-root",
      ];
    case "uv":
      return [
        copy("COPY", inApp("pyproject.toml", "uv.lock*"), "./"),
        "RUN pip install uv && uv pip install --system -r pyproject.toml",
      ];
    case "pipenv":
      return [
        copy("COPY", inApp("Pipfile", "Pipfile.lock*"), "./"),
        "RUN pip install pipenv && pipenv install --system --deploy",
      ];
    default:
      return [
        copy("COPY", inApp("requirements*.txt"), "./"),
        "RUN pip install -r requirements.txt",
      ];
  }
}

/**
 * Detected start command as it runs inside the image: the `cd <dir> && ` prefix detection adds for
 * an app in a subfolder is dropped, because the image holds only that folder.
 */
function pythonStart(facts: ProjectFacts, stack: DockerStack): string | undefined {
  const start = facts.build.startCommand;
  const dir = appDirectory(facts, stack);
  if (start === undefined || dir === ".") return start;
  for (const prefix of [`cd ${dir} && `, `cd ${shellQuote(dir)} && `]) {
    if (start.startsWith(prefix)) return start.slice(prefix.length);
  }
  return start;
}

/** Uvicorn target (`module:app`) from the detected start command, or `main:app`. */
function uvicornTarget(facts: ProjectFacts): string {
  const match = pythonStart(facts, "python-fastapi")?.match(/uvicorn\s+([\w.]+:[\w]+)/);
  return match?.[1] ?? "main:app";
}

export function fastapiDockerfile(facts: ProjectFacts, port: number): string {
  return [
    ...pythonBase("python-fastapi", port, facts),
    "RUN pip install uvicorn",
    "USER app",
    `EXPOSE ${port}`,
    `CMD ["sh", "-c", "uvicorn ${uvicornTarget(facts)} --host 0.0.0.0 --port \${PORT}"]`,
    "",
  ].join("\n");
}

/** Placeholder settings so `collectstatic` can import production settings during the build. */
const DJANGO_BUILD_KEY =
  "SECRET_KEY=build-only-placeholder-not-secret DJANGO_SECRET_KEY=build-only-placeholder-not-secret";

/**
 * Runs `collectstatic` only when the settings define `STATIC_ROOT` (a fresh `startproject` app does
 * not, and `collectstatic` would then fail the build). A settings import error still fails it.
 */
const DJANGO_COLLECTSTATIC =
  `static_root="$(python manage.py shell --verbosity 0 -c 'from django.conf import settings; print(settings.STATIC_ROOT or "")')" && ` +
  'if [ -n "$static_root" ]; then python manage.py collectstatic --noinput; ' +
  'else echo "collectstatic skipped: STATIC_ROOT is not set"; fi';

export function djangoDockerfile(facts: ProjectFacts, port: number): string {
  const module =
    pythonStart(facts, "python-django")?.match(/([\w.]+)\.wsgi/)?.[1] ??
    facts.name.replace(/-/g, "_");
  return [
    ...pythonBase("python-django", port, facts),
    "RUN pip install gunicorn",
    `ENV DJANGO_WSGI_MODULE=${module}.wsgi`,
    "# Collects static files at build time when the settings set STATIC_ROOT (skipped otherwise).",
    "# The key below is a throwaway value for this step only; the real SECRET_KEY is set when the",
    "# container runs.",
    `RUN export ${DJANGO_BUILD_KEY} && ${DJANGO_COLLECTSTATIC}`,
    "USER app",
    `EXPOSE ${port}`,
    "# Run migrations as part of your release process (for example `python manage.py migrate`).",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: shell variables expanded inside the container.
    'CMD ["sh", "-c", "gunicorn ${DJANGO_WSGI_MODULE} --bind 0.0.0.0:${PORT}"]',
    "",
  ].join("\n");
}

export function pythonGenericDockerfile(facts: ProjectFacts, port: number): string {
  const start = pythonStart(facts, "python-generic") ?? "python main.py";
  return [
    ...pythonBase("python-generic", port, facts),
    "USER app",
    `EXPOSE ${port}`,
    `CMD ["sh", "-c", ${JSON.stringify(start)}]`,
    "",
  ].join("\n");
}
