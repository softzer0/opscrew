/** Container recipe chosen for an app. */
export type DockerStack =
  | "next-standalone"
  | "node-server"
  | "static-spa"
  | "python-fastapi"
  | "python-django"
  | "python-generic";

/** Prefixes of environment variables that frameworks bake into the frontend at build time. */
export const CLIENT_ENV_PREFIXES = [
  "VITE_",
  "NEXT_PUBLIC_",
  "REACT_APP_",
  "PUBLIC_",
  "NUXT_PUBLIC_",
  "EXPO_PUBLIC_",
  "GATSBY_",
] as const;

/** True when a variable is read at build time and shipped to browsers (never put secrets there). */
export function isClientExposedEnvName(name: string): boolean {
  return CLIENT_ENV_PREFIXES.some((prefix) => name.startsWith(prefix));
}

const NODE_SERVER_FRAMEWORKS = ["express", "fastify", "@nestjs/core", "nestjs", "hono", "koa"];

function hasFramework(facts: ProjectFacts, ...names: string[]): boolean {
  return facts.frameworks.some((f) => names.includes(f.name));
}

/** Picks the recipe for the detected stack, or undefined when OpsCrew has no template for it. */
export function detectStack(facts: ProjectFacts): DockerStack | undefined {
  const usesPython = facts.languages.includes("python");
  const usesJs = facts.languages.includes("javascript") || facts.languages.includes("typescript");
  if (hasFramework(facts, "fastapi")) return "python-fastapi";
  if (hasFramework(facts, "django")) return "python-django";
  if (facts.appKind === "static-spa") return "static-spa";
  if (hasFramework(facts, "next")) return "next-standalone";
  if (usesJs && (hasFramework(facts, ...NODE_SERVER_FRAMEWORKS) || facts.build.startCommand)) {
    return "node-server";
  }
  if (usesPython) return "python-generic";
  if (usesJs) return "node-server";
  return undefined;
}

/** The first lines of every Dockerfile, with the note when its base is pinned by tag only. */
const header = (stack: DockerStack, base: BaseImage) =>
  [
    `# syntax=${IMAGES.dockerfileSyntax.ref}`,
    `# Generated by OpsCrew (${stack}). You own this file: edit it freely; OpsCrew only creates it`,
    "# when it is missing.",
    ...tagOnlyNote(base),
  ].join("\n");

/** Shell snippet installing JS dependencies with the detected package manager. */
function jsInstall(facts: ProjectFacts): string {
  switch (facts.packageManager) {
    case "pnpm":
      return "corepack enable && if [ -f pnpm-lock.yaml ]; then pnpm install --frozen-lockfile; else pnpm install; fi";
    case "yarn":
      return "corepack enable && if [ -f yarn.lock ]; then yarn install --frozen-lockfile; else yarn install; fi";
    default:
      return "if [ -f package-lock.json ]; then npm ci; else npm install; fi";
  }
}

function jsRun(facts: ProjectFacts, script: string): string {
  switch (facts.packageManager) {
    case "pnpm":
      return `pnpm run ${script}`;
    case "yarn":
      return `yarn ${script}`;
    default:
      return `npm run ${script}`;
  }
}

/**
 * Shell command leaving only the production dependencies in the build stage's tree, after the
 * build. `moved`: a release tool was moved to the production dependencies, so pnpm's lockfile no
 * longer matches package.json.
 */
function jsProdInstall(facts: ProjectFacts, moved: boolean): string {
  switch (facts.packageManager) {
    case "pnpm":
      // `pnpm prune --prod` cannot prune a workspace, and an install over the full tree leaves the
      // development packages in node_modules/.pnpm, so the tree is installed again.
      return `find . -name node_modules -type d -prune -exec rm -rf {} + && ${
        moved
          ? "pnpm install --prod --no-frozen-lockfile"
          : "if [ -f pnpm-lock.yaml ]; then pnpm install --prod --frozen-lockfile; else pnpm install --prod; fi"
      }`;
    case "yarn":
      // `yarn workspaces focus` is built into Yarn 4; Yarn 2 and 3 need the workspace-tools plugin.
      return 'if [ "$(yarn --version | cut -d. -f1)" = 1 ]; then if [ -f yarn.lock ]; then yarn install --production --frozen-lockfile; else yarn install --production; fi; else yarn workspaces focus --all --production; fi';
    default:
      return "npm prune --omit=dev";
  }
}

/**
 * What the image must keep for a release command: the packages of the migration tool it runs, or
 * the package script whose tool the build stage looks up. Undefined when it runs no known tool.
 * `npmScriptsOnly`: only `npm run` scripts count (the Next.js runtime has no corepack, Bun or
 * workspace root).
 */
function releaseNeeds(
  command: string | undefined,
  npmScriptsOnly = false,
): { packages: readonly string[]; script?: string } | undefined {
  if (command === undefined) return undefined;
  const tool = releaseToolOf(command);
  if (tool?.packageScript) {
    const bare = bareCommand(command);
    const script = packageScriptOf(bare);
    if (npmScriptsOnly && !/^npm\s/.test(bare)) return undefined;
    return script === undefined ? undefined : { packages: [], script };
  }
  return tool?.packages?.length ? { packages: tool.packages } : undefined;
}

/** `node <helper> <mode> …` for the release command's needs, run from the repository root. */
function helperRun(
  mode: "move" | "versions",
  dir: string,
  needs: { packages: readonly string[]; script?: string },
): string {
  const script = needs.script === undefined ? "-" : shellQuote(needs.script);
  return [
    `node ${RELEASE_TOOLS_HELPER} ${mode}`,
    shellQuote(dir),
    script,
    ...needs.packages.map(shellQuote),
  ].join(" ");
}

/** What the comments call the tool: its packages, or the tool of the package script. */
function toolWords(needs: { packages: readonly string[]; script?: string }): string {
  return needs.script === undefined
    ? needs.packages.join(" and ")
    : `the tool the \`${needs.script}\` script runs`;
}

const TYPESCRIPT_NOTE = `# ${TYPESCRIPT_RUNNERS.join(", ")} stay too when installed, for TypeScript configs and migrations.`;

/**
 * The end of a Node.js server's build stage: only production dependencies stay, plus the packages
 * of the migration tool the release command runs (moved to the production dependencies first).
 */
function jsProdDependencies(facts: ProjectFacts, dir: string, releaseCommand?: string): string[] {
  const needs = releaseNeeds(releaseCommand);
  const inDir = (command: string) =>
    dir === "." || facts.monorepo ? command : `cd ${shellQuote(dir)} && ${command}`;
  const prune = inDir(jsProdInstall(facts, needs !== undefined));
  if (needs === undefined) {
    return [
      "# Only production dependencies go into the image: development ones (TypeScript, test tools)",
      "# stay in this stage.",
      `RUN ${prune}`,
    ];
  }
  return [
    "# Only production dependencies go into the image: development ones (TypeScript, test tools)",
    `# stay in this stage. The image keeps ${toolWords(needs)}, which the release command runs.`,
    TYPESCRIPT_NOTE,
    ...releaseToolsHelper(),
    `RUN ${helperRun("move", dir, needs)} && ${prune}`,
  ];
}

/**
 * The end of a Next.js build stage when the release command runs a migration tool: the tool is
 * installed on its own at the version this stage installed (Prisma's engines with it), then
 * `/out/node_modules` is copied over it (the standalone files win) and the result replaces it.
 * The build fails when a tool's package is then missing, so `npx` never downloads one at deploy.
 * The app folder's files (configuration, migrations) missing from `/out` are copied in, so the
 * command runs from `/app` as it does in the repository.
 */
function nextReleaseTool(dir: string, releaseCommand?: string): string[] {
  const needs = releaseNeeds(releaseCommand, true);
  if (needs === undefined) return [];
  const from = shellQuote(dir === "." ? "/app" : `/app/${dir}`);
  const to = shellQuote(dir === "." ? "/out" : `/out/${dir}`);
  return [
    `# The release command runs ${toolWords(needs)}: the image gets it, at the version this stage`,
    "# installed, with the app folder's files for its configuration and migrations.",
    TYPESCRIPT_NOTE,
    ...releaseToolsHelper(),
    `RUN tools="$(${helperRun("versions", dir, needs)})" \\`,
    '  && if [ -n "$tools" ]; then mkdir -p /tmp/release-tools /out/node_modules && cd /tmp/release-tools \\',
    `    && echo '{"private":true}' > package.json && npm install --no-audit --no-fund $tools \\`,
    "    && cp -a /out/node_modules/. node_modules/ && rm -rf /out/node_modules \\",
    "    && mv node_modules /out/node_modules; fi \\",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: a shell parameter expansion.
    '  && for tool in $tools; do name="${tool%@*}"; [ -f "/out/node_modules/$name/package.json" ] \\',
    '    || { echo "The image lacks $name, which the release command runs." >&2; exit 1; }; done \\',
    `  && mkdir -p ${to} && cd ${from} \\`,
    `  && find . -mindepth 1 -maxdepth 1 ! -name node_modules ! -name .next -exec cp -an {} ${to}/ \\;`,
  ];
}

/**
 * Build values the frontend reads while it is built (client-exposed names): non-secret ones as
 * `ARG`/`ENV` lines, secret ones as BuildKit secret mounts for the build command's `RUN`, so they
 * stay out of the image's layers and config.
 */
function buildValues(facts: ProjectFacts): { lines: string[]; mounts: string } {
  const values = facts.envVars.filter((v) => isClientExposedEnvName(v.name));
  const plain = values.filter((v) => !v.secretLikely).map((v) => v.name);
  const secret = values.filter((v) => v.secretLikely).map((v) => v.name);
  const lines = [
    ...(plain.length === 0
      ? []
      : [
          "# Values baked into the frontend at build time (public by design; never put secrets here).",
          ...plain.flatMap((name) => [`ARG ${name}`, `ENV ${name}=$${name}`]),
        ]),
    ...(secret.length === 0
      ? []
      : [
          "# Values the code treats as secrets reach the build command as BuildKit secret mounts, which",
          "# keeps them out of ARG/ENV and the image config. A client-exposed value (NEXT_PUBLIC_*,",
          "# VITE_*) still ends up in the browser bundle, whatever the mount does: never put a real",
          "# secret in one.",
        ]),
  ];
  return {
    lines,
    mounts: secret.map((name) => `--mount=type=secret,id=${name},env=${name} `).join(""),
  };
}

function needsCorepack(facts: ProjectFacts): boolean {
  return facts.packageManager === "pnpm" || facts.packageManager === "yarn";
}

/** Normalised repo-relative directory (`.` for the repository root). */
function normaliseDir(path: string): string {
  const dir = path
    .replace(/^(?:\.\/)+/, "")
    .replace(/\/+$/, "")
    .replace(/\/\.$/, "");
  return dir === "" ? "." : dir;
}

/** Repo-relative directory of the app (`facts.appDir`, normalised; `.` for the repository root). */
export function appDirectory(facts: ProjectFacts): string {
  return normaliseDir(facts.appDir);
}

const PLAIN_PATH = /^[A-Za-z0-9._/@+-]+$/;
const PLAIN_SOURCE = /^[A-Za-z0-9._/@+*-]+$/;

/** A `COPY` instruction that switches to the JSON form when a path needs quoting. */
function copy(prefix: string, sources: string[], destination: string): string {
  const paths = [...sources, destination];
  return paths.every((path) => PLAIN_SOURCE.test(path))
    ? `${prefix} ${paths.join(" ")}`
    : `${prefix} [${paths.map((path) => JSON.stringify(path)).join(", ")}]`;
}

/** `COPY --from=build` that switches to the JSON form when a path needs quoting. */
function copyFromBuild(source: string, destination: string): string {
  return copy("COPY --from=build --chown=node:node", [source], destination);
}

function shellQuote(value: string): string {
  return PLAIN_PATH.test(value) ? value : `'${value.replace(/'/g, `'\\''`)}'`;
}

/** Package name of a yarn workspace, read from the commands detection wrote. */
function yarnWorkspaceName(facts: ProjectFacts): string | undefined {
  const { buildCommand, startCommand, installCommand } = facts.build;
  for (const command of [startCommand, buildCommand, installCommand]) {
    const name = command?.match(/\byarn workspace (\S+)/)?.[1];
    if (name) return name;
  }
  return undefined;
}

/**
 * Command running a package script of the app from the repository root: the plain form at the
 * root, the package manager's workspace flag for a workspace member, and `cd <dir> && …` for a
 * folder that is not part of a workspace (or a yarn workspace whose package name is unknown).
 */
function jsScript(facts: ProjectFacts, dir: string, script: string): string {
  if (dir === ".") return jsRun(facts, script);
  const inDir = `cd ${shellQuote(dir)} && ${jsRun(facts, script)}`;
  if (!facts.monorepo) return inDir;
  switch (facts.packageManager) {
    case "pnpm":
      return `pnpm --filter ${shellQuote(`./${dir}`)} run ${script}`;
    case "yarn": {
      const name = yarnWorkspaceName(facts);
      return name ? `yarn workspace ${shellQuote(name)} ${script}` : inDir;
    }
    default:
      return `npm run ${script} --workspace ${shellQuote(dir)}`;
  }
}

/**
 * Dependency install for the app: at the root for the root app and for workspace members (the
 * root lockfile covers the whole workspace), inside the folder otherwise.
 */
function jsInstallFor(facts: ProjectFacts, dir: string): string {
  return dir === "." || facts.monorepo
    ? jsInstall(facts)
    : `cd ${shellQuote(dir)} && ${jsInstall(facts)}`;
}

/** The start of a JS image's build stage: the whole repository in `/app`, dependencies installed. */
function jsBuildStage(facts: ProjectFacts, dir: string, base: BaseImage): string[] {
  return [
    `FROM ${base.ref} AS build`,
    "WORKDIR /app",
    "COPY . .",
    `RUN ${jsInstallFor(facts, dir)}`,
  ];
}

/** Header note for an app in a subfolder (nothing at the root). */
function jsFolderNote(facts: ProjectFacts, dir: string): string[] {
  if (dir === ".") return [];
  return facts.monorepo
    ? [
        "# The image is built from the repository root so the root lockfile and workspace packages",
        `# are available; the app lives in ${dir}.`,
      ]
    : [`# The image is built from the repository root; the app lives in ${dir}.`];
}

/** Start script the Next.js build stage writes into the image (`/out` becomes `/app`). */
const NEXT_START_SCRIPT = "/app/opscrew-start.sh";

/**
 * Shell lines copying one standalone layout into `/out`: the standalone root, `.next/static` and
 * `public` next to the server (in `serverDir`, relative to the standalone root), and a start
 * script running that server.
 */
function standaloneToOut(dir: string, serverDir: string): string[] {
  const inApp = (path: string) => (dir === "." ? path : `${dir}/${path}`);
  const out = (path: string) => (serverDir === "." ? `/out/${path}` : `/out/${serverDir}/${path}`);
  const server = serverDir === "." ? "/app/server.js" : `/app/${serverDir}/server.js`;
  return [
    `    cp -a ${shellQuote(`${inApp(".next/standalone")}/.`)} /out/ \\`,
    `    && mkdir -p ${shellQuote(out(".next"))} \\`,
    `    && cp -a ${shellQuote(inApp(".next/static"))} ${shellQuote(out(".next/static"))} \\`,
    `    && cp -a ${shellQuote(inApp("public"))} ${shellQuote(out("public"))} \\`,
    `    && printf '#!/bin/sh\\nexec node "%s"\\n' ${shellQuote(server)} > /out/opscrew-start.sh; \\`,
  ];
}

/**
 * Next.js image that builds whether or not the config sets `output: "standalone"`. The build stage
 * gathers what runs into `/out` and writes `/out/opscrew-start.sh`: with standalone output, the
 * standalone server plus `.next/static` and `public` (a small image); without it, the whole built
 * app with its dependencies, started with `next start` on `$PORT` and `$HOSTNAME`. The runtime
 * stage copies `/out` and runs the script, so a missed config edit costs image size, never a
 * failed build. For an app in a monorepo folder (`facts.appDir`, or the `next` framework's path),
 * the image is built from the repository root so the root lockfile and workspace packages are
 * available; the standalone server is found at `<dir>/server.js` (with `outputFileTracingRoot` at
 * the repository root) or at the standalone root. When `releaseCommand` runs a migration tool,
 * the image also gets that tool and the app folder's files (see {@link nextReleaseTool}).
 */
export function nextStandaloneDockerfile(
  facts: ProjectFacts,
  port: number,
  base: BaseImage,
  releaseCommand?: string,
): string {
  const dir = appDirectory(facts);
  const atRoot = dir === ".";
  const inApp = (path: string) => (atRoot ? path : `${dir}/${path}`);
  const command = facts.build.buildCommand ?? jsScript(facts, dir, "build");
  // A `cd` must not leak into the `mkdir` that follows, which runs from the repository root.
  const build = /^cd\s/.test(command) ? `(${command})` : command;
  const standalone = inApp(".next/standalone");
  const notes = atRoot
    ? [
        '# Builds with or without `output: "standalone"` in next.config.* (OpsCrew adds it as a code',
        "# change). With it, the image ships only the standalone server, .next/static and public;",
        "# without it, the image holds the whole built app with its dependencies and runs",
        "# `next start`. The build stage gathers what runs into /out, with /out/opscrew-start.sh as",
        "# the entry point.",
      ]
    : [
        `# Builds with or without \`output: "standalone"\` in ${dir}/next.config.*. Because the app`,
        "# lives in a monorepo, the standalone output also needs `outputFileTracingRoot` pointing at",
        "# the repository root, for example",
        `# \`outputFileTracingRoot: path.join(__dirname, "${"../".repeat(dir.split("/").length)}")\` (OpsCrew adds both as a code change).`,
        `# With them, the image ships only the standalone server (started from ${dir}/server.js),`,
        "# .next/static and public; without them, the image holds the whole built workspace with its",
        "# dependencies and runs `next start` in the app folder. The build stage gathers what runs",
        "# into /out, with /out/opscrew-start.sh as the entry point. The image is built from the",
        "# repository root so the root lockfile and workspace packages are available.",
      ];
  const resolveNext = `node -p "require.resolve('next/dist/bin/next')"`;
  const nextBin = atRoot ? resolveNext : `cd ${shellQuote(dir)} && ${resolveNext}`;
  const values = buildValues(facts);
  return [
    header("next-standalone", base),
    ...notes,
    "",
    ...jsBuildStage(facts, dir, base),
    "ENV NEXT_TELEMETRY_DISABLED=1",
    ...values.lines,
    `RUN ${values.mounts}${build} && mkdir -p ${shellQuote(inApp("public"))}`,
    "# The standalone server when the build made one, otherwise the whole app with `next start`.",
    "RUN mkdir -p /out \\",
    `  && if [ -f ${shellQuote(`${standalone}/${inApp("server.js")}`)} ]; then \\`,
    ...standaloneToOut(dir, dir),
    ...(atRoot
      ? []
      : [
          `  elif [ -f ${shellQuote(`${standalone}/server.js`)} ]; then \\`,
          ...standaloneToOut(dir, "."),
        ]),
    "  else \\",
    // `next start` keeps the development dependencies: next.config.ts can need `typescript`.
    `    rm -rf ${shellQuote(inApp(".next/cache"))} && cp -a . /out/ \\`,
    // Assigned first, so a next binary that cannot be found fails the build, not the deploy.
    `    && NEXT_BIN="$(${nextBin})" && [ -n "$NEXT_BIN" ] \\`,
    `    && printf '#!/bin/sh\\ncd "%s"\\nexec node "%s" start --hostname "\${HOSTNAME:-0.0.0.0}" --port "\${PORT:-${port}}"\\n' \\`,
    `      ${shellQuote(atRoot ? "/app" : `/app/${dir}`)} "$NEXT_BIN" > /out/opscrew-start.sh; \\`,
    "  fi",
    ...nextReleaseTool(dir, releaseCommand),
    "",
    `FROM ${base.ref} AS runtime`,
    "WORKDIR /app",
    `ENV NODE_ENV=production NEXT_TELEMETRY_DISABLED=1 PORT=${port} HOSTNAME=0.0.0.0`,
    copyFromBuild("/out", "./"),
    "USER node",
    `EXPOSE ${port}`,
    `CMD ["sh", ${JSON.stringify(NEXT_START_SCRIPT)}]`,
    "",
  ].join("\n");
}

/**
 * Node.js server image; an app in a subfolder is built from the root and started from there. The
 * image holds the built repository with the production dependencies, plus the packages of the
 * migration tool `releaseCommand` runs.
 */
export function nodeServerDockerfile(
  facts: ProjectFacts,
  port: number,
  base: BaseImage,
  releaseCommand?: string,
): string {
  const dir = appDirectory(facts);
  const start = facts.build.startCommand ?? jsScript(facts, dir, "start");
  const values = buildValues(facts);
  const lines = [
    header("node-server", base),
    ...jsFolderNote(facts, dir),
    "",
    ...jsBuildStage(facts, dir, base),
    ...values.lines,
  ];
  if (facts.build.buildCommand) lines.push(`RUN ${values.mounts}${facts.build.buildCommand}`);
  lines.push(
    ...jsProdDependencies(facts, dir, releaseCommand),
    "",
    `FROM ${base.ref} AS runtime`,
    "WORKDIR /app",
    // HOST: servers such as @astrojs/node standalone listen on localhost unless told otherwise.
    `ENV NODE_ENV=production PORT=${port} HOST=0.0.0.0`,
  );
  if (needsCorepack(facts)) lines.push("RUN corepack enable");
  lines.push(
    "COPY --from=build --chown=node:node /app ./",
    "USER node",
    `EXPOSE ${port}`,
    `CMD ["sh", "-c", ${JSON.stringify(start)}]`,
    "",
  );
  return lines.join("\n");
}

/**
 * Static site image. For an app in a subfolder, the default output folder is `<dir>/dist`
 * (a detected `outputDir` is already relative to the repository root).
 */
export function staticSpaDockerfile(facts: ProjectFacts, base: BaseImage): string {
  const dir = appDirectory(facts);
  const build = facts.build.buildCommand ?? jsScript(facts, dir, "build");
  const outputDir = facts.build.outputDir ?? (dir === "." ? "dist" : `${dir}/dist`);
  const caddyfile = [
    "{",
    "\tauto_https off",
    "\tadmin off",
    "}",
    ":8080 {",
    "\troot * /srv",
    "\tencode zstd gzip",
    "\ttry_files {path} /index.html",
    "\tfile_server",
    "}",
  ];
  const values = buildValues(facts);
  return [
    header("static-spa", base),
    "# Builds the site with Node, then serves the static files with Caddy on port 8080 as an",
    "# unprivileged user (OpsCrew's outer Caddy terminates TLS in front of it).",
    ...jsFolderNote(facts, dir),
    "",
    ...jsBuildStage(facts, dir, base),
    ...values.lines,
    `RUN ${values.mounts}${build}`,
    "",
    `FROM ${IMAGES.caddy.ref}`,
    copy("COPY --from=build", [`/app/${outputDir}`], "/srv"),
    `RUN printf '%s\\n' ${caddyfile.map((line) => `'${line}'`).join(" ")} > /etc/caddy/Caddyfile \\`,
    "  && chown -R 65534:65534 /data /config \\",
    // The image's /usr/bin/caddy carries the file capability cap_net_bind_service, which the
    // kernel refuses to exec under `cap_drop: ALL` + `no-new-privileges`. A plain copy drops it;
    // port 8080 needs no capability.
    "  && cp /usr/bin/caddy /usr/local/bin/caddy",
    "USER 65534",
    "EXPOSE 8080",
    'CMD ["/usr/local/bin/caddy", "run", "--config", "/etc/caddy/Caddyfile", "--adapter", "caddyfile"]',
    "",
  ].join("\n");
}

/**
 * Base of every Python image. Only the app folder is copied into `/app`, so an app in a subfolder
 * runs exactly as it would at the root.
 */
function pythonBase(
  stack: DockerStack,
  port: number,
  facts: ProjectFacts,
  base: BaseImage,
): string[] {
  const dir = appDirectory(facts);
  return [
    header(stack, base),
    ...(dir === "."
      ? []
      : [`# Built from the repository root; only ${dir} is copied into the image.`]),
    "",
    `FROM ${base.ref}`,
    `ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PIP_NO_CACHE_DIR=1 PORT=${port}`,
    "WORKDIR /app",
    "RUN useradd --create-home --uid 10001 app",
    ...pythonInstall(facts, dir),
    copy("COPY --chown=app:app", [dir], "."),
  ];
}

function pythonInstall(facts: ProjectFacts, dir: string): string[] {
  const inApp = (...files: string[]) =>
    files.map((file) => (dir === "." ? file : `${dir}/${file}`));
  switch (facts.packageManager) {
    case "poetry":
      return [
        copy("COPY", inApp("pyproject.toml", "poetry.lock*"), "./"),
        "RUN pip install poetry && poetry config virtualenvs.create false && poetry install --only main --no-root",
      ];
    case "uv":
      return [
        copy("COPY", inApp("pyproject.toml", "uv.lock*"), "./"),
        "RUN pip install uv && uv pip install --system -r pyproject.toml",
      ];
    case "pipenv":
      return [
        copy("COPY", inApp("Pipfile", "Pipfile.lock*"), "./"),
        "RUN pip install pipenv && pipenv install --system --deploy",
      ];
    default:
      return [
        copy("COPY", inApp("requirements*.txt"), "./"),
        "RUN pip install -r requirements.txt",
      ];
  }
}

/**
 * Detected start command as it runs inside the image: the `cd <dir> && ` prefix detection adds for
 * an app in a subfolder is dropped, because the image holds only that folder.
 */
function pythonStart(facts: ProjectFacts): string | undefined {
  const start = facts.build.startCommand;
  return start === undefined ? undefined : inAppFolder(start, appDirectory(facts));
}

/**
 * A command detection wrote for the repository root, as it runs in an image that holds only `dir`
 * (copied to the working folder): `cd <dir> && ` goes and `cd <dir>/<sub> && ` becomes
 * `cd <sub> && `. Other commands are returned unchanged.
 */
function inAppFolder(command: string, dir: string): string {
  if (dir === ".") return command;
  for (const folder of [dir, shellQuote(dir)]) {
    if (command.startsWith(`cd ${folder} && `)) return command.slice(`cd ${folder} && `.length);
    const sub = new RegExp(`^cd ${escapeRegExp(folder)}/(\\S+) && `).exec(command);
    if (sub) return `cd ${sub[1]} && ${command.slice(sub[0].length)}`;
  }
  return command;
}

function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** The detected release command as the app's image runs it, or why the image cannot. */
export interface ImageReleaseCommand {
  /** The command for `app.releaseCommand`, when the image can run it. */
  command?: string;
  /** Plain-English reason the detected command was left out of the plan, and what to do. */
  notRun?: string;
}

/** What a known migration command needs from the image that runs it. */
interface ReleaseTool {
  /** What OpsCrew found, for messages (`Drizzle migrations`). */
  found: string;
  /** Which kind of image can run it. */
  runtime: "node" | "python" | "other";
  /** What the image must contain, for messages (`the Diesel CLI`). */
  needs: string;
  /** npm packages the command runs, which Node.js images keep (`prisma`). */
  packages?: readonly string[];
  /** A package script: the build stage reads it and keeps the tool it runs. */
  packageScript?: true;
}

const NODE_TOOL = (name: string, packages: readonly string[] = []): ReleaseTool => ({
  found: `${name} migrations`,
  runtime: "node",
  needs: `the ${name} command-line tool and the migration files`,
  packages,
});
const PYTHON_TOOL = (name: string): ReleaseTool => ({
  found: `${name} migrations`,
  runtime: "python",
  needs: "Python and the app's Python packages",
});
const OTHER_TOOL = (found: string, needs: string): ReleaseTool => ({
  found,
  runtime: "other",
  needs,
});

/**
 * Migration commands detection writes other than `npx <tool>` (see `NODE_TOOL_BINS`), after any
 * `cd …` and `VAR=value` prefixes.
 */
const RELEASE_TOOLS: readonly [RegExp, ReleaseTool][] = [
  [/^yarn rw\b/, NODE_TOOL("Redwood")],
  [/^node ace\b/, NODE_TOOL("AdonisJS")],
  [
    /^(?:npm|pnpm|yarn|bun)\s/,
    {
      found: "a migration script in package.json",
      runtime: "node",
      needs: "the package scripts, the tools they call and the migration files",
      packageScript: true,
    },
  ],
  [/^python manage\.py\b/, PYTHON_TOOL("Django")],
  [/^flask db\b/, PYTHON_TOOL("Flask")],
  [/^alembic\b/, PYTHON_TOOL("Alembic")],
  [/^aerich\b/, PYTHON_TOOL("Aerich")],
  [/^tortoise\b/, PYTHON_TOOL("Tortoise ORM")],
  [/^piccolo\b/, PYTHON_TOOL("Piccolo")],
  [/^yoyo\b/, PYTHON_TOOL("Yoyo")],
  [/^pw_migrate\b/, PYTHON_TOOL("peewee-migrate")],
  [/^python craft\b/, PYTHON_TOOL("Masonite")],
  [/^(?:bin\/rails|bundle exec)\b/, OTHER_TOOL("Ruby migrations", "Ruby and the app's gems")],
  [/^php\b/, OTHER_TOOL("PHP migrations", "PHP and the app's Composer packages")],
  [/^migrate -path\b/, OTHER_TOOL("golang-migrate migrations", "the golang-migrate CLI")],
  [/^goose\b/, OTHER_TOOL("goose migrations", "the goose CLI")],
  [/^atlas\b/, OTHER_TOOL("Atlas migrations", "the Atlas CLI")],
  [/^diesel\b/, OTHER_TOOL("Diesel migrations", "the Diesel CLI")],
  [/^sqlx\b/, OTHER_TOOL("sqlx migrations", "the sqlx CLI")],
  [/^sea-orm-cli\b/, OTHER_TOOL("SeaORM migrations", "the SeaORM CLI")],
  [/^(?:mix\b|bin\/\w+ eval\b)/, OTHER_TOOL("Ecto migrations", "the Elixir release of the app")],
  [/^dotnet\b/, OTHER_TOOL("EF Core migrations", "the .NET SDK and the dotnet-ef tool")],
];

/** A command without the `cd …` and `VAR=value` prefixes detection writes. */
function bareCommand(command: string): string {
  return command
    .replace(/^(?:cd \S+ && )+/, "")
    .replace(/^(?:[A-Za-z_]\w*=(?:'[^']*'|"[^"]*"|\S+) )+/, "");
}

/** The migration tool a release command runs, when it is one detection writes. */
function releaseToolOf(command: string): ReleaseTool | undefined {
  const bare = bareCommand(command);
  const bin = npxBin(bare);
  const npx = bin === undefined ? undefined : NODE_TOOL_BINS[bin];
  if (npx !== undefined) return NODE_TOOL(npx.name, npx.packages);
  return RELEASE_TOOLS.find(([pattern]) => pattern.test(bare))?.[1];
}

const IMAGE_NAMES: Record<Exclude<DockerStack, "static-spa">, string> = {
  "next-standalone": "Next.js standalone",
  "node-server": "Node.js",
  "python-fastapi": "Python",
  "python-django": "Python",
  "python-generic": "Python",
};

/** Why an image of another kind cannot run the command (for example Rails in a Node.js image). */
function wrongImage(tool: ReleaseTool, stack: Exclude<DockerStack, "static-spa">, command: string) {
  return `OpsCrew found ${tool.found}, but \`${command}\` needs ${tool.needs}, which the ${IMAGE_NAMES[stack]} image OpsCrew builds for this app does not include, so deploys will not run it. Set \`app.releaseCommand\` in opscrew/plan.yaml to a command the image can run, or run the migrations yourself against the production database before each deploy that changes the schema.`;
}

/**
 * The detected release command (`facts.build.releaseCommand`) as it runs in the app's image.
 * Python images hold only the app folder and its Python packages, so the folder prefix detection
 * added is dropped. Node.js images keep the command: the server image holds the repository with
 * its production packages, and both it and the Next.js standalone image get the packages of the
 * migration tool the command or its package script runs (the standalone image also the app
 * folder's files). Left out with a reason: a known migration command for another kind of image
 * (Rails or Diesel, say, which OpsCrew cannot build images for yet), a Node.js tool OpsCrew does
 * not install in the Next.js standalone image, and a command that changes into a monorepo folder
 * that image may lack. Empty without a release command or for a static site (no app container).
 */
export function imageReleaseCommand(facts: ProjectFacts): ImageReleaseCommand {
  const command = facts.build.releaseCommand;
  const stack = detectStack(facts);
  if (command === undefined || stack === undefined || stack === "static-spa") return {};
  const tool = releaseToolOf(command);
  const python = stack.startsWith("python-");
  if (tool !== undefined && tool.runtime !== (python ? "python" : "node")) {
    return { notRun: wrongImage(tool, stack, command) };
  }
  if (python) return { command: inAppFolder(command, appDirectory(facts)) };
  if (stack !== "next-standalone" || releaseNeeds(command, true) !== undefined) return { command };
  if (tool !== undefined) {
    return {
      notRun: `OpsCrew found ${tool.found}, but the Next.js standalone image keeps only the files the server needs, not ${tool.needs}, so deploys cannot run \`${command}\`. Run the migrations another way: change the Dockerfile so the image keeps them, then set \`app.releaseCommand\` in opscrew/plan.yaml; or run the command yourself against the production database before each deploy that changes the schema.`,
    };
  }
  const dir = appDirectory(facts);
  if (dir !== "." && command.startsWith("cd ")) {
    return {
      notRun: `The release command \`${command}\` changes into ${dir}, which the Next.js standalone image may not contain, so OpsCrew left it out of the plan. Set \`app.releaseCommand\` in opscrew/plan.yaml to a command that runs from the image's working folder (/app).`,
    };
  }
  return { command };
}

/** `app.releaseCommand` for the plan: {@link imageReleaseCommand}'s command, when there is one. */
export function releaseCommandInImage(facts: ProjectFacts): string | undefined {
  return imageReleaseCommand(facts).command;
}

/** Uvicorn target (`module:app`) from the detected start command, or `main:app`. */
function uvicornTarget(facts: ProjectFacts): string {
  const match = pythonStart(facts)?.match(/uvicorn\s+([\w.]+:[\w]+)/);
  return match?.[1] ?? "main:app";
}

export function fastapiDockerfile(facts: ProjectFacts, port: number, base: BaseImage): string {
  return [
    ...pythonBase("python-fastapi", port, facts, base),
    "RUN pip install uvicorn",
    "USER app",
    `EXPOSE ${port}`,
    `CMD ["sh", "-c", "uvicorn ${uvicornTarget(facts)} --host 0.0.0.0 --port \${PORT}"]`,
    "",
  ].join("\n");
}

/** Placeholder settings so `collectstatic` can import production settings during the build. */
const DJANGO_BUILD_KEY =
  "SECRET_KEY=build-only-placeholder-not-secret DJANGO_SECRET_KEY=build-only-placeholder-not-secret";

/**
 * Runs `collectstatic` only when the settings define `STATIC_ROOT` (a fresh `startproject` app does
 * not, and `collectstatic` would then fail the build). A settings import error still fails it.
 */
const DJANGO_COLLECTSTATIC =
  `static_root="$(python manage.py shell --verbosity 0 -c 'from django.conf import settings; print(settings.STATIC_ROOT or "")')" && ` +
  'if [ -n "$static_root" ]; then python manage.py collectstatic --noinput; ' +
  'else echo "collectstatic skipped: STATIC_ROOT is not set"; fi';

/** gunicorn release installed for Django apps whose dependencies do not already include it. */
const GUNICORN_VERSION = "26.2.0";

export function djangoDockerfile(facts: ProjectFacts, port: number, base: BaseImage): string {
  const module = pythonStart(facts)?.match(/([\w.]+)\.wsgi/)?.[1] ?? facts.name.replace(/-/g, "_");
  return [
    ...pythonBase("python-django", port, facts, base),
    "# gunicorn serves the app; it is added (pinned) only when the dependencies do not install it.",
    `RUN python -c "import gunicorn" 2>/dev/null || pip install gunicorn==${GUNICORN_VERSION}`,
    `ENV DJANGO_WSGI_MODULE=${module}.wsgi`,
    "# Collects static files at build time when the settings set STATIC_ROOT (skipped otherwise).",
    "# The key below is a throwaway value for this step only; the real SECRET_KEY is set when the",
    "# container runs.",
    `RUN export ${DJANGO_BUILD_KEY} && ${DJANGO_COLLECTSTATIC}`,
    "USER app",
    `EXPOSE ${port}`,
    facts.build.releaseCommand === undefined
      ? "# Run migrations as part of your release process (for example `python manage.py migrate`)."
      : "# The OpsCrew deploy runs the migrations (app.releaseCommand in opscrew/plan.yaml) first.",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: shell variables expanded inside the container.
    'CMD ["sh", "-c", "gunicorn ${DJANGO_WSGI_MODULE} --bind 0.0.0.0:${PORT}"]',
    "",
  ].join("\n");
}

export function pythonGenericDockerfile(
  facts: ProjectFacts,
  port: number,
  base: BaseImage,
): string {
  const start = pythonStart(facts) ?? "python main.py";
  return [
    ...pythonBase("python-generic", port, facts, base),
    "USER app",
    `EXPOSE ${port}`,
    `CMD ["sh", "-c", ${JSON.stringify(start)}]`,
    "",
  ].join("\n");
}
