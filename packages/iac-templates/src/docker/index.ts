export interface DockerAssetOptions {
  /** Port the app listens on inside the container (static sites always use 8080). */
  appPort: number;
  /** Health check path, for documentation in the generated files. */
  healthPath: string;
  /**
   * The plan's `app`: `build.runtime.version` picks the runtime version, `releaseCommand` the
   * migration tool a Node.js server image keeps, and a further app's `key` the plan the
   * Dockerfile's notes name. Absent: the version the app declares (else OpsCrew's default), the
   * detected release command and the first app's plan.
   */
  app?: Pick<DeployPlan["app"], "build" | "releaseCommand" | "key">;
  /**
   * Finds the digest of a runtime image OpsCrew has no pin for (a declared non-default version).
   * Without it, or when it finds none, that image is pinned by tag only and the Dockerfile says so.
   */
  resolveImageDigest?: ResolveImageDigest;
  /**
   * False when another builder builds the image (Buildpacks, Railpack, the user's own
   * Dockerfile): only `.dockerignore` and `.env.example` are rendered, for any stack. Default true.
   */
  dockerfile?: boolean;
  /**
   * The image's architecture when the plan has an enabled cron job (`supercronicArch(plan)`): the
   * runtime stage then gets the pinned supercronic for it, which the `cron` service runs.
   */
  supercronic?: PinArch;
  /**
   * The SQLite database's folder in the image for an app on SQLite (`sqliteFolder(plan)`): the
   * runtime stage of a server image makes it as the app's user, so the volume on it is theirs.
   */
  sqliteFolder?: string;
}

/** Port the container listens on for a stack. */
export function containerPort(stack: DockerStack, appPort: number): number {
  return stack === "static-spa" ? 8080 : appPort;
}

function dockerfile(
  stack: DockerStack,
  facts: ProjectFacts,
  port: number,
  options: DockerAssetOptions,
): string {
  const build = options.app?.build;
  const resolve = options.resolveImageDigest;
  const node = () => nodeImage(nodeMajor(facts, build), resolve);
  const python = () => pythonImage(pythonMinor(facts, build), resolve);
  const release = options.app ? options.app.releaseCommand : facts.build.releaseCommand;
  const cron = options.supercronic;
  const sqlite = options.sqliteFolder;
  // The app's Dockerfile serves all its environments: its notes name the app's prod plan.
  const planFile = planFilePath({ app: { key: options.app?.key } }, "prod");
  switch (stack) {
    case "next-standalone":
      return nextStandaloneDockerfile(facts, planFile, port, node(), release, cron, sqlite);
    case "node-server":
      return nodeServerDockerfile(facts, planFile, port, node(), release, cron, sqlite);
    case "static-spa":
      return staticSpaDockerfile(facts, planFile, node(), cron);
    case "python-fastapi":
      return fastapiDockerfile(facts, planFile, port, python(), cron, sqlite);
    case "python-django":
      return djangoDockerfile(facts, planFile, port, python(), cron, sqlite);
    case "python-generic":
      return pythonGenericDockerfile(facts, planFile, port, python(), cron, sqlite);
  }
}

/**
 * The secret files `.dockerignore` keeps out of every image, in its syntax: a pattern that starts
 * with `**` and a slash matches in any folder, and `!` keeps a file. The Buildpacks build removes
 * them from its checkout instead, because pack does not read `.dockerignore`.
 */
export const SECRET_FILE_PATTERNS = [
  ".env",
  ".env.*",
  "**/.env",
  "**/.env.*",
  "!.env.example",
  "!**/.env.example",
  "*.pem",
  "*.key",
  "**/*.pem",
  "**/*.key",
] as const;

const DOCKERIGNORE = [
  "# Generated by OpsCrew: keeps secrets, VCS data and local build output out of the image.",
  ".git",
  ".github",
  ...SECRET_FILE_PATTERNS,
  "opscrew",
  ".opscrew",
  ".terraform",
  "# Monorepo app folders have their own dependency and build folders too.",
  "node_modules",
  "**/node_modules",
  ".next",
  "**/.next",
  "dist",
  "build",
  "coverage",
  ".turbo",
  "**/.turbo",
  "__pycache__",
  "**/__pycache__",
  "*.pyc",
  ".venv",
  "**/.venv",
  "venv",
  ".pytest_cache",
  ".mypy_cache",
  "*.log",
  ".DS_Store",
  "Dockerfile",
  ".dockerignore",
  "",
].join("\n");

function envExample(facts: ProjectFacts): string {
  const lines = [
    "# Generated by OpsCrew: the environment variables this app reads. Names only, never values.",
    "# Copy to .env for local development; production values are stored as deploy secrets.",
  ];
  if (facts.envVars.length === 0) {
    lines.push("# No environment variables were detected.");
  }
  for (const variable of facts.envVars) {
    if (isClientExposedEnvName(variable.name) || variable.clientExposed) {
      lines.push("# Public: baked into the frontend at build time. Never put a secret here.");
    } else if (variable.secretLikely) {
      lines.push("# Secret: keep it out of git.");
    }
    lines.push(`${variable.name}=`);
  }
  return `${lines.join("\n")}\n`;
}

/**
 * `Dockerfile`, `.dockerignore` and `.env.example` for the detected stack. Callers write them only
 * when the files are missing (the user owns them afterwards). For an app in a subfolder
 * (`facts.appDir`) the Dockerfile is `<appDir>/Dockerfile`. A `.dockerignore` applies only at the
 * root of the build context; this returns it at the repository root, the build context of
 * OpsCrew's Dockerfile, which builds an app in a subfolder from there. For Buildpacks and Railpack
 * an app in a subfolder builds from its own folder, and adapt writes the file at the path design
 * gives the change (the build context's root). With `options.dockerfile`
 * false, only `.dockerignore` and `.env.example`, which need no stack.
 * Throws `INVALID_INPUT` when the Dockerfile is wanted and OpsCrew has no template for the stack.
 */
export function renderDockerAssets(
  facts: ProjectFacts,
  options: DockerAssetOptions,
): RenderedFile[] {
  const context: RenderedFile[] = [
    { path: ".dockerignore", content: DOCKERIGNORE, kind: "docker" },
    { path: ".env.example", content: envExample(facts), kind: "docker" },
  ];
  if (options.dockerfile === false) return context;
  const stack = detectStack(facts);
  if (stack === undefined) {
    throw new OpsCrewError(
      "INVALID_INPUT",
      `OpsCrew has no container template for this app (languages: ${facts.languages.join(", ") || "unknown"}).`,
      { hint: "Add a Dockerfile yourself, then run `opscrew design` again." },
    );
  }
  const port = containerPort(stack, options.appPort);
  const dir = appDirectory(facts);
  return [
    {
      path: dir === "." ? "Dockerfile" : `${dir}/Dockerfile`,
      content: dockerfile(stack, facts, port, options),
      kind: "docker",
    },
    ...context,
  ];
}
