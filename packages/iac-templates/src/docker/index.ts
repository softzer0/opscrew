function envExample(facts: ProjectFacts): string {
  const lines = [
    "# Generated by OpsCrew: the environment variables this app reads. Names only, never values.",
    "# Copy to .env for local development; production values are stored as deploy secrets.",
  ];
  if (facts.envVars.length === 0) {
    lines.push("# No environment variables were detected.");
  }
  for (const variable of facts.envVars) {
    if (isClientExposedEnvName(variable.name) || variable.clientExposed) {
      lines.push("# Public: baked into the frontend at build time. Never put a secret here.");
    } else if (variable.secretLikely) {
      lines.push("# Secret: keep it out of git.");
    }
    lines.push(`${variable.name}=`);
  }
  return `${lines.join("\n")}\n`;
}

/**
 * `Dockerfile`, `.dockerignore` and `.env.example` for the detected stack. Callers write them only
 * when the files are missing (the user owns them afterwards). For an app in a subfolder
 * (`facts.appDir`) the Dockerfile is `<appDir>/Dockerfile`; the build context, and so the
 * `.dockerignore`, stays at the repository root (Railpack's buildx context honours it too). With
 * `options.dockerfile` false, only `.dockerignore` and `.env.example`, which need no stack.
 * Throws `INVALID_INPUT` when the Dockerfile is wanted and OpsCrew has no template for the stack.
 */
export function renderDockerAssets(
  facts: ProjectFacts,
  options: DockerAssetOptions,
): RenderedFile[] {
  const context: RenderedFile[] = [
    { path: ".dockerignore", content: DOCKERIGNORE, kind: "docker" },
    { path: ".env.example", content: envExample(facts), kind: "docker" },
  ];
  if (options.dockerfile === false) return context;
  const stack = detectStack(facts);
  if (stack === undefined) {
    throw new OpsCrewError(
      "INVALID_INPUT",
      `OpsCrew has no container template for this app (languages: ${facts.languages.join(", ") || "unknown"}).`,
      { hint: "Add a Dockerfile yourself, then run `opscrew design` again." },
    );
  }
  const port = containerPort(stack, options.appPort);
  const dir = appDirectory(facts);
  return [
    {
      path: dir === "." ? "Dockerfile" : `${dir}/Dockerfile`,
      content: dockerfile(stack, facts, port, options),
      kind: "docker",
    },
    ...context,
  ];
}
