import { posix } from "node:path";
import type { DeployPlan } from "@opscrew/plan-schema";
import type { RenderedFile } from "../types";
import { planFilePath } from "../workflow/shared";
import { HEADERS_ENTRY } from "./headers";
import { cloudflareDir, siteFiles, workersTarget } from "./site";

/** The Wrangler config's path, {@link cloudflareDir}`/wrangler.jsonc`. */
export function wranglerConfigPath(plan: DeployPlan): string {
  return `${cloudflareDir(plan)}/wrangler.jsonc`;
}

/**
 * The Workers runtime's compatibility date in every generated config: the day OpsCrew's Wrangler
 * pin and the four Cloudflare adapters were tested (016's spike, 2026-10-23). Move it with them.
 */
export const COMPATIBILITY_DATE = "2026-10-23";

/**
 * The environment's Wrangler config ({@link wranglerConfigPath}), which the deploy workflow uploads
 * every version with and `wrangler deploy` works with too: the Worker's name, the compatibility
 * date and the flags of `site.compatibilityFlags`, the static files (`assets.directory`, relative
 * to the config, and `not_found_handling`), `workers_dev`, `preview_urls` and observability. For
 * `render: ssr` also `main`, the headers wrapper (the build job bundles the Worker from it, and the
 * deploy job uploads that bundle), with the `ASSETS` binding the adapters' Workers
 * read static files through, and `run_worker_first` off so static files cost no Worker call. These
 * settings live here, never in Terraform. It is OpsCrew's own config, never the adapter's
 * generated one, so no binding the adapter adds (a KV namespace, images, caches) is created. It
 * holds no secret and no account id.
 */
export function renderWranglerConfig(plan: DeployPlan): RenderedFile {
  const target = workersTarget(plan);
  const dir = cloudflareDir(plan);
  const ssr = target.render === "ssr";
  const flags = target.site.compatibilityFlags ?? [];
  const config = {
    name: target.worker,
    compatibility_date: COMPATIBILITY_DATE,
    ...(flags.length > 0 ? { compatibility_flags: flags } : {}),
    ...(ssr ? { main: HEADERS_ENTRY } : {}),
    assets: {
      directory: posix.relative(dir, siteFiles(plan).assets),
      ...(ssr ? { binding: "ASSETS" } : {}),
      not_found_handling: target.notFound,
      ...(ssr ? { run_worker_first: false } : {}),
    },
    workers_dev: target.workersDev,
    preview_urls: target.previewUrls,
    observability: { enabled: true },
  };
  const header = [
    `// Generated by OpsCrew from ${planFilePath(plan)}; \`opscrew provision\` regenerates it.`,
    "// The Worker's settings. OpsCrew's deploy workflow uploads every version with this file, and",
    "// `wrangler deploy --config` works with it too. It holds no secret and no account id.",
  ];
  return {
    path: wranglerConfigPath(plan),
    content: `${header.join("\n")}\n${JSON.stringify(config, null, 2)}\n`,
    kind: "runtime",
  };
}
