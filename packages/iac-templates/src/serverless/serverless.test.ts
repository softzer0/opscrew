/** The Wrangler config's JSON, after its `//` comment lines (the only comments it has). */
function jsonc(text: string): unknown {
  const lines = text.split("\n");
  expect(lines.slice(0, 3).every((line) => line.startsWith("// "))).toBe(true);
  return JSON.parse(lines.filter((line) => !line.startsWith("//")).join("\n"));
}

const temps: string[] = [];
async function tempDir(): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "opscrew-serverless-"));
  temps.push(dir);
  return dir;
}
afterAll(async () => {
  for (const dir of temps) await rm(dir, { recursive: true, force: true });
});

/** Writes `files` (repository paths) under a new temporary folder and returns it. */
async function tree(files: Record<string, string>): Promise<string> {
  const dir = await tempDir();
  for (const [path, content] of Object.entries(files)) {
    await mkdir(dirname(join(dir, path)), { recursive: true });
    await writeFile(join(dir, path), content);
  }
  return dir;
}

describe("the site's folders", () => {
  it("are the output folder and, for server rendering, the adapter's module, in the build context", () => {
    expect(siteFiles(cloudflarePlan())).toEqual({ assets: "dist" });
    expect(siteFiles(pagesPlan({ site: HUGO_SITE }))).toEqual({ assets: "public" });
    expect(siteFiles(ssrPlan())).toEqual({ assets: "dist/client", entry: "dist/server/entry.mjs" });
    expect(siteFiles(ssrPlan({ site: NUXT_SSR, buildContext: "apps/web" }))).toEqual({
      assets: "apps/web/.output/public",
      entry: "apps/web/.output/server/index.mjs",
    });
    expect(siteFiles(cloudflarePlan({ site: { tool: "none", outputDir: "./site/" } }))).toEqual({
      assets: "site",
    });
  });
});

describe("renderWranglerConfig", () => {
  it("writes the Worker's settings for a static site, with paths from the config's folder", () => {
    const file = renderWranglerConfig(cloudflarePlan());
    expect(file).toMatchObject({ path: "opscrew/cloudflare/wrangler.jsonc", kind: "runtime" });
    expect(jsonc(file.content)).toEqual({
      name: "example-app",
      compatibility_date: "2026-10-23",
      assets: { directory: "../../dist", not_found_handling: "single-page-application" },
      workers_dev: false,
      preview_urls: false,
      observability: { enabled: true },
    });
    expect(file.content).toMatchSnapshot();
  });

  it("names the headers wrapper as main for server rendering, with the adapter's flags and run_worker_first off", () => {
    const file = renderWranglerConfig(ssrPlan({ site: NUXT_SSR, notFound: "none" }));
    expect(jsonc(file.content)).toEqual({
      name: "example-app",
      compatibility_date: "2026-10-23",
      compatibility_flags: ["nodejs_compat"],
      main: "headers-entry.js",
      assets: {
        directory: "../../.output/public",
        binding: "ASSETS",
        not_found_handling: "none",
        run_worker_first: false,
      },
      workers_dev: false,
      preview_urls: false,
      observability: { enabled: true },
    });
    // Astro needs no flag: none are written.
    expect(jsonc(renderWranglerConfig(ssrPlan()).content)).not.toHaveProperty(
      "compatibility_flags",
    );
    expect(file.content).toMatchSnapshot();
  });

  it("gives another environment its own Worker and file, and follows the plan's switches", () => {
    const file = renderWranglerConfig(
      cloudflarePlan({
        environment: "staging",
        notFound: "404-page",
        workersDev: true,
        previewUrls: true,
      }),
    );
    expect(file.path).toBe("opscrew/environments/staging/cloudflare/wrangler.jsonc");
    expect(file.content).toContain(
      "// Generated by OpsCrew from opscrew/environments/staging/plan.yaml;",
    );
    expect(jsonc(file.content)).toMatchObject({
      name: "example-app-staging",
      assets: { directory: "../../../../dist", not_found_handling: "404-page" },
      workers_dev: true,
      preview_urls: true,
    });
  });

  it("holds no secret, no account id and no expression", () => {
    for (const plan of [cloudflarePlan({ env: ["API_KEY"] }), ssrPlan({ env: ["API_KEY"] })]) {
      const settings = JSON.stringify(jsonc(renderWranglerConfig(plan).content));
      expect(settings).not.toMatch(/secret|account|\$\{\{|API_KEY|vars/i);
    }
  });

  // FR-1714: `opscrew logs` reads Workers Logs, so every Worker OpsCrew configures keeps them on.
  it("keeps Workers Logs on: observability enabled, nothing sampled, invocation logs kept", () => {
    const plans = [
      cloudflarePlan(),
      cloudflarePlan({ environment: "staging", workersDev: true, previewUrls: true }),
      ssrPlan(),
      ssrPlan({ site: NUXT_SSR, notFound: "none" }),
    ];
    for (const plan of plans) {
      const config = jsonc(renderWranglerConfig(plan).content) as {
        observability?: { enabled?: boolean; logs?: { enabled?: boolean } };
      };
      expect(config.observability?.enabled).toBe(true);
      expect(config.observability?.logs?.enabled).not.toBe(false);
      const walk = (value: unknown): void => {
        if (typeof value !== "object" || value === null) return;
        for (const [key, item] of Object.entries(value)) {
          if (key === "head_sampling_rate") expect(item).toBeGreaterThanOrEqual(1);
          if (key === "invocation_logs") expect(item).not.toBe(false);
          walk(item);
        }
      };
      walk(config);
    }
  });

  it("refuses a plan that is not on Cloudflare's hosting", () => {
    expect(() => renderWranglerConfig(pagesPlan())).toThrow(
      expect.objectContaining({ code: "PHASE_PRECONDITION" }),
    );
  });
});

describe("OpsCrew's headers in _headers (the deploy step's program)", () => {
  // The exact text the deploy step runs, from the rendered workflow.
  const workflow = parse(renderCloudflareWorkersWorkflow(cloudflarePlan(), {}).content) as {
    jobs: { deploy: { steps: { name?: string; run?: string; shell?: string }[] } };
  };
  const step = workflow.jobs.deploy.steps.find(
    (s) => s.name === "Add OpsCrew's security headers to _headers",
  );

  /** Runs the step's program with Node.js on a site whose `_headers` is `own` (none: absent). */
  async function headersAfter(own: string | undefined): Promise<string> {
    const dir = await tree({ "program.js": step?.run ?? "", "site/index.html": "<h1>Docs</h1>\n" });
    const site = join(dir, "site");
    if (own !== undefined) await writeFile(join(site, "_headers"), own);
    const program = join(dir, "program.js");
    const result = spawnSync(process.execPath, [program], {
      env: { ...process.env, SITE: site },
      encoding: "utf8",
    });
    expect(result.status, result.stderr).toBe(0);
    return readFile(join(site, "_headers"), "utf8");
  }

  const ours = SITE_HEADERS.map(([name, value]) => `  ${name}: ${value}`);

  it("is the program, run with Node.js", () => {
    expect(step?.shell).toBe("node {0}");
    expect(step?.run).toBe(`${headersProgram(cloudflarePlan())}\nmain();\n`);
    expect(SITE_HEADERS.map(([name]) => name)).toEqual([
      "Strict-Transport-Security",
      "X-Content-Type-Options",
      "X-Frame-Options",
      "Referrer-Policy",
    ]);
  });

  it("writes OpsCrew's rule for every path when the site has no _headers", async () => {
    expect(await headersAfter(undefined)).toBe(["/*", ...ours, ""].join("\n"));
  });

  it("puts OpsCrew's rule first and keeps the site's rules when none is for every path", async () => {
    const own = "/assets/*\n  Cache-Control: public, max-age=31536000, immutable\n";
    expect(await headersAfter(own)).toBe(["/*", ...ours, "", own].join("\n"));
  });

  it("merges into the site's own /* rule, keeping each header the site sets or removes", async () => {
    const own = [
      "# The site's headers.",
      "/*",
      "  X-Frame-Options: DENY",
      "  ! Referrer-Policy",
      "/assets/*",
      "  Cache-Control: public, max-age=31536000, immutable",
      "",
    ].join("\n");
    expect(await headersAfter(own)).toBe(
      [
        "# The site's headers.",
        "/*",
        "  Strict-Transport-Security: max-age=31536000; includeSubDomains",
        "  X-Content-Type-Options: nosniff",
        "  X-Frame-Options: DENY",
        "  ! Referrer-Policy",
        "/assets/*",
        "  Cache-Control: public, max-age=31536000, immutable",
        "",
      ].join("\n"),
    );
  });

  it("merges into the last /* rule, the one Cloudflare keeps", async () => {
    const own = "/*\n  X-Robots-Tag: noindex\n/*\n  Content-Security-Policy: default-src 'self'\n";
    expect(await headersAfter(own)).toBe(
      [
        "/*",
        "  X-Robots-Tag: noindex",
        "/*",
        ...ours,
        "  Content-Security-Policy: default-src 'self'",
        "",
      ].join("\n"),
    );
  });
});

describe("renderHeadersEntry (the SSR headers wrapper)", () => {
  it("re-exports the adapter's Worker and adds OpsCrew's headers to its responses where the app set none", async () => {
    const plan = ssrPlan();
    const wrapper = renderHeadersEntry(plan);
    expect(wrapper).toMatchObject({ path: "opscrew/cloudflare/headers-entry.js", kind: "runtime" });
    expect(wrapper.content).toMatchSnapshot();
    const dir = await tree({
      "package.json": '{ "type": "module" }\n',
      [wrapper.path]: wrapper.content,
      [ASTRO_SSR.entry]: [
        "export class Room {}",
        "// Node.js has no 101 Response: the Workers runtime's carries the WebSocket.",
        "export const UPGRADE = { status: 101, webSocket: {} };",
        "export default {",
        "  async fetch(request, env) {",
        "    const { pathname } = new URL(request.url);",
        '    if (pathname === "/socket") return UPGRADE;',
        '    if (pathname === "/framed") {',
        '      return new Response("own", { headers: { "X-Frame-Options": "DENY" } });',
        "    }",
        '    return new Response("rendered " + pathname + " with " + env.API_KEY, { status: 201 });',
        "  },",
        "  scheduled() {",
        '    return "ran";',
        "  },",
        "};",
        "",
      ].join("\n"),
      "check.mjs": [
        `import worker, { Room, UPGRADE } from "./${wrapper.path}";`,
        'const env = { API_KEY: "value" };',
        'const page = await worker.fetch(new Request("https://docs.example.com/about"), env, {});',
        'const framed = await worker.fetch(new Request("https://docs.example.com/framed"), env, {});',
        'const socket = await worker.fetch(new Request("https://docs.example.com/socket"), env, {});',
        "console.log(JSON.stringify({",
        "  socket: socket === UPGRADE,",
        "  status: page.status,",
        "  body: await page.text(),",
        "  page: Object.fromEntries(page.headers),",
        "  framed: Object.fromEntries(framed.headers),",
        "  room: typeof Room,",
        "  scheduled: worker.scheduled(),",
        "}));",
        "",
      ].join("\n"),
    });
    const result = spawnSync(process.execPath, ["check.mjs"], { cwd: dir, encoding: "utf8" });
    expect(result.status, result.stderr).toBe(0);
    const seen = JSON.parse(result.stdout) as {
      socket: boolean;
      status: number;
      body: string;
      page: Record<string, string>;
      framed: Record<string, string>;
      room: string;
      scheduled: string;
    };
    const headers = Object.fromEntries(
      SITE_HEADERS.map(([name, value]) => [name.toLowerCase(), value]),
    );
    expect(seen.status).toBe(201);
    expect(seen.body).toBe("rendered /about with value");
    expect(seen.page).toMatchObject(headers);
    expect(seen.framed).toMatchObject({ ...headers, "x-frame-options": "DENY" });
    expect(seen.room).toBe("function");
    expect(seen.scheduled).toBe("ran");
    // A WebSocket's 101 passes untouched: copying it would lose the socket.
    expect(seen.socket).toBe(true);
  });

  it("imports the adapter's entry from another environment's folder", () => {
    const wrapper = renderHeadersEntry(ssrPlan({ site: NUXT_SSR, environment: "staging" }));
    expect(wrapper.path).toBe("opscrew/environments/staging/cloudflare/headers-entry.js");
    expect(wrapper.content).toContain('import worker from "../../../../.output/server/index.mjs";');
    expect(wrapper.content).toContain('export * from "../../../../.output/server/index.mjs";');
  });

  it("is only for server rendering on Cloudflare", () => {
    expect(() => renderHeadersEntry(cloudflarePlan())).toThrow("render: ssr");
    expect(() => renderHeadersEntry(pagesPlan())).toThrow(
      expect.objectContaining({ code: "PHASE_PRECONDITION" }),
    );
  });
});
