import type { DeployPlan } from "@opscrew/plan-schema";
import { planFilePath } from "../workflow/shared";

/** The first line of every file of the stack: the plan it comes from and what regenerates it. */
export function generatedBy(plan: DeployPlan): string {
  return `Generated by OpsCrew from ${planFilePath(plan)}; \`opscrew provision\` regenerates it.`;
}

/** `lines` as `#` comments, the {@link generatedBy} line first. */
export function headerComment(plan: DeployPlan, lines: readonly string[]): string[] {
  return [generatedBy(plan), ...lines].map((line) => `# ${line}`);
}
