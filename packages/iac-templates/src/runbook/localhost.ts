import type { DeployPlan } from "@opscrew/plan-schema";
import { localComposeProject } from "../runtime";
import { runtimeDir } from "../runtime-dir";
import type { RenderedFile } from "../types";

/**
 * The runbook of an app on this computer (`RUNBOOK.md` beside the plan): where it runs, the
 * everyday Docker commands, the local CA and what differs from a server. No secret and no
 * absolute path: the OpsCrew folder is named as `~/.opscrew`.
 */
export function renderLocalRunbook(
  plan: DeployPlan,
  o: { address: string; file: string },
): RenderedFile {
  const project = localComposeProject(plan);
  const target = plan.target.provider === "localhost" ? plan.target : undefined;
  const image =
    target?.image === "local-build"
      ? "built on this computer from the app's Dockerfile, for its CPU: it differs from production's image"
      : "the image production runs, from GitHub Container Registry by its digest";
  const env = plan.environment?.name;
  const flag = env === undefined ? "" : ` --env ${env}`;
  const lines = [
    `# Runbook: ${plan.app.name} on this computer`,
    "",
    "Generated by OpsCrew from the plan; `opscrew verify` writes it again.",
    "",
    "| | |",
    "|---|---|",
    `| Address | ${o.address} (from this computer only: the ports are bound to 127.0.0.1) |`,
    `| Where | Docker on this computer: the Compose project ${project}, behind OpsCrew's edge (opscrew-edge, ${target?.edge === "nginx" ? "nginx" : "Caddy"} and kamal-proxy) |`,
    `| Folders | ~/.opscrew/local/srv/apps/${plan.app.name} (the app) and ~/.opscrew/local/srv/edge (the edge) |`,
    `| Image | ${image} |`,
    `| Files | ${runtimeDir(plan)}/ in the repository, copied by each deploy |`,
    "",
    "## Everyday commands",
    "",
    `- The logs: \`docker compose -p ${project} logs -f app\``,
    `- What runs: \`opscrew status${flag}\`, or \`docker compose -p ${project} ps\``,
    `- A new version: \`opscrew provision${flag}\`${plan.environment?.runner === "local" ? `, or push with the local runner started (\`opscrew runner start${flag}\`)` : ""}`,
    `- Stop it for now: \`docker compose -p ${project} stop\`; start it again: \`docker compose -p ${project} start\``,
    `- Remove it: \`opscrew destroy${flag}\` (the data volumes stay unless you add \`--delete-data\`)`,
    "",
    "The stack starts again whenever Docker does: it is not meant to run unattended.",
    "",
    "## Certificates",
    "",
    "The site's certificate comes from OpsCrew's local certificate authority (`~/.opscrew/local-ca/ca.pem`; its key never leaves that folder). `opscrew localhost trust` makes this computer's browsers trust it, and `opscrew localhost untrust` undoes that. Without it the site still works, with a browser warning.",
    "",
    "## How it differs from a server",
    "",
    "- no SSH, server hardening, firewall, DNS records or Cloudflare;",
    "- the ports bound to 127.0.0.1 only;",
    "- certificates from OpsCrew's local CA instead of a public one;",
    `- the image: ${image};`,
    "- the services' data in Docker volumes.",
    "",
  ];
  return { path: o.file, content: lines.join("\n"), kind: "doc" };
}
