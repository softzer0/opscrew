/** Text for a Markdown table cell: pipes escaped, newlines turned into spaces. */
export function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

/**
 * What a runbook renders from besides the plan: the render context, and the app's environments
 * (`environmentsOf`), which only the caller can read. Absent, or prod alone: prod's commands name
 * no environment, as before environments.
 */
export interface RunbookContext extends RenderContext {
  environments?: readonly string[];
}

/** The environment a runbook's commands name with `--env`: its own outside prod, `prod` beside others. */
function commandEnvironment(
  plan: DeployPlan,
  environments: readonly string[] | undefined,
): string | undefined {
  return plan.environment?.name ?? (several(environments) ? "prod" : undefined);
}

/** True when the app has more than one environment. */
function several(environments: readonly string[] | undefined): boolean {
  return (environments?.length ?? 0) > 1;
}

/**
 * `opscrew <command>` for the plan's environment: `--env <name>` after it outside prod, and
 * `--env prod` for prod when the app has other `environments` (a bare command then asks which one,
 * or stops in scripts), so every command a runbook names acts on that environment only.
 */
export function opscrew(
  plan: DeployPlan,
  command: string,
  environments?: readonly string[],
): string {
  const env = commandEnvironment(plan, environments);
  return env === undefined ? `opscrew ${command}` : `opscrew ${command} --env ${env}`;
}

/**
 * The environment's folders as a runbook names them (data-model.md "Paths per environment"): its
 * artefacts (`opscrew`), its state (`.opscrew`), its OpsCrew home folder and its infrastructure
 * root, each prod's for prod and the environment's own (`…/environments/<env>`) for the others.
 */
export function runbookFolders(
  plan: DeployPlan,
  projectId: string | undefined,
): { artefacts: string; state: string; home: string; infra: string } {
  const env = plan.environment?.name;
  const own = (dir: string) => (env === undefined ? dir : `${dir}/environments/${env}`);
  return {
    artefacts: own("opscrew"),
    state: own(".opscrew"),
    home: own(`~/.opscrew/projects/${projectId ?? "<project-id>"}`),
    infra: env === undefined ? "opscrew/infra" : plan.infra.dir,
  };
}

/**
 * The title, the generation note and the first rows of "At a glance" (the app and its check), with
 * the environment's rows when the plan names its environment: which one it is, where its deploy
 * job runs (a self-hosted runner) and where its deploy secrets live.
 */
export function runbookHead(
  plan: DeployPlan,
  ctx: Pick<RunbookContext, "opscrewVersion" | "environments">,
  url: string,
): string[] {
  return [
    `# Runbook: ${plan.app.name}`,
    "",
    `Generated by OpsCrew ${ctx.opscrewVersion} from \`${runbookFolders(plan, undefined).artefacts}/plan.yaml\`. Run \`${opscrew(plan, "verify", ctx.environments)}\` to refresh it.`,
    "",
    "## At a glance",
    "",
    "| | |",
    "|---|---|",
    `| App | ${cell(url)} |`,
    `| Health check | \`${plan.app.healthPath}\` |`,
    ...environmentRows(plan, ctx.environments),
  ];
}

/**
 * "At a glance"'s rows when the plan names its environment or the app has several; none for a
 * prod-only app.
 */
function environmentRows(plan: DeployPlan, environments: readonly string[] | undefined): string[] {
  const environment = plan.environment;
  const env = commandEnvironment(plan, environments);
  if (environment === undefined && env === undefined) return [];
  const name = environmentName(plan);
  const rows = [
    env === undefined
      ? "| Environment | `prod`, one of the app's environments (`opscrew env list` shows them all) |"
      : `| Environment | \`${name}\` (\`opscrew env list\` shows them all): \`opscrew promote\` takes \`--to ${name}\`, every other command \`--env ${name}\` |`,
  ];
  if (selfHosted(plan)) {
    const label = `(label \`${runnerLabel(plan)}\`)`;
    const where =
      environment?.runner === "local"
        ? `on this computer's runner ${label}, while \`${opscrew(plan, "runner start", environments)}\` runs`
        : `on the server's own runner ${label}, so GitHub never connects to the server over SSH`;
    rows.push(`| Deploy job | ${cell(where)} |`);
  }
  if (environment?.secrets !== undefined) {
    const names =
      environment.name === undefined ? "" : `, named \`${deploySecretName(plan, "OPSCREW_…")}\``;
    const where =
      githubEnvironment(plan) === undefined
        ? `repository secrets${names}`
        : `the GitHub environment \`${githubEnvironment(plan)}\`${names}; the build values are repository secrets`;
    rows.push(`| Deploy secrets | ${cell(where)} |`);
  }
  return rows;
}

/** The "Database" cell when Postgres does not run with the app: its external services, or `None`. */
export function externalDatabaseCell(plan: DeployPlan): string {
  return plan.externalServices.length > 0
    ? `External: ${plan.externalServices.join(", ")} (not managed by OpsCrew)`
    : "None";
}

/**
 * The "Deploys" and "Image" rows of "At a glance": each push to the branch, or for a promoted
 * environment only `opscrew promote`, with the image its source environment runs.
 */
export function deployRows(plan: DeployPlan, repo: string): string[] {
  const source = plan.environment?.deploySource;
  const deploys =
    source?.from === "promote"
      ? `only by \`opscrew promote --to ${environmentName(plan)}\`, which runs \`${plan.cicd.workflowPath}\` with the image the \`${source.source}\` environment runs`
      : `every push to \`${plan.cicd.branch}\` runs \`${plan.cicd.workflowPath}\``;
  return [
    `| Deploys | ${cell(deploys)} |`,
    `| Image | \`ghcr.io/${repo.toLowerCase()}\` (GitHub Container Registry) |`,
  ];
}

/**
 * "How a deploy works" and "Roll back", with the target's notes after the build step (`build`) and
 * after the start step (`start`). A promoted environment builds nothing: `opscrew promote` starts
 * its workflow with an image's digest, which its verify job checks against the branch that builds
 * its images (`ctx.builderBranch`), and rolls back the same way.
 */
export function deploySections(
  plan: DeployPlan,
  ctx: Pick<RunbookContext, "environments" | "builderBranch">,
  notes: { build?: readonly string[]; start?: readonly string[] } = {},
): string[] {
  const { environments } = ctx;
  const branch = plan.cicd.branch;
  const name = environmentName(plan);
  const source = plan.environment?.deploySource;
  const first =
    source?.from === "promote"
      ? [
          `1. \`opscrew promote --to ${name}\` finds the image the \`${source.source}\` environment runs, checks that a push to`,
          `   \`${builderBranchOf(plan, ctx)}\` in this repository built it, checks that ${name} has no change waiting for \`${opscrew(plan, "provision", environments)}\`, and`,
          "   shows it all with the approval's hash. Only after your approval does it start the deploy workflow with the image's",
          "   digest; `--yes` never approves a promotion.",
          `2. The workflow's verify job, on GitHub's machines, checks the image's build again${plan.supplyChain.sign ? " and its cosign signature" : ""}. Nothing is rebuilt.`,
        ]
      : [
          `1. You push to \`${branch}\` (or run the "${workflowName(plan)}" workflow by hand in GitHub → Actions).`,
          "2. GitHub Actions builds the Docker image from your Dockerfile and pushes it to GitHub Container Registry.",
        ];
  const runner = selfHosted(plan)
    ? [
        `   The deploy job runs on ${plan.environment?.runner === "local" ? "this computer's runner" : "the server's own runner"} (label \`${runnerLabel(plan)}\`), so GitHub never connects`,
        "   to the server over SSH.",
      ]
    : [];
  return [
    "## How a deploy works",
    "",
    ...first,
    ...(notes.build ?? []),
    `3. It copies \`${runtimeDir(plan)}/compose.yaml\` (with the services' settings) to \`${appDir(plan)}\` on the server and`,
    `   the app's site file to the shared edge in \`/srv/edge\`, writes the app's and the services' environment from the`,
    "   deploy secrets, starts the services, runs the release command if the app has one, switches to the new version,",
    "   then restarts the workers and cron jobs with it. A worker that does not stay up sends the app back to the",
    "   previous version.",
    ...runner,
    ...(notes.start ?? []),
    `4. It checks \`${plan.app.healthPath}\`. If the app does not answer within three minutes, it restores the previous`,
    "   version automatically and the run fails.",
    "",
    "## Roll back",
    "",
    ...(source?.from === "promote"
      ? [
          `- **The previous image:** \`opscrew promote --to ${name} --digest <digest>\`, with the digest of the image tagged`,
          `  \`opscrew-${name}-previous\` in GitHub Container Registry. It runs the same checks and asks for the same approval.`,
          `- **A fix:** push it to \`${branch}\`, let the \`${source.source}\` environment deploy it, then promote it.`,
        ]
      : [
          `- **Fastest:** in GitHub → Actions, open the last successful "${workflowName(plan)}" run and choose **Re-run all jobs**.`,
          `- **With git:** revert the bad commit and push to \`${branch}\`; the workflow deploys the reverted code.`,
        ]),
    "",
  ];
}

/** A shell block that logs in with `login` and shows the app's containers in `/srv/apps/<app>`. */
export function serverCommands(plan: DeployPlan, login: readonly string[]): string[] {
  return [
    "```bash",
    ...login,
    `cd ${appDir(plan)}`,
    "docker compose ps                 # what is running",
    "docker compose logs -f app        # follow the app's logs",
    "docker compose restart app        # restart the app",
    "```",
  ];
}

