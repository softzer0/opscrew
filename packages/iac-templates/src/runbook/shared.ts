/** "Change settings and secrets", with the target's own bullets between the shared ones. */
export function settingsSection(bullets: readonly string[]): string[] {
  return [
    "## Change settings and secrets",
    "",
    "- **App environment variables:** run `opscrew provision` again; it updates the GitHub deploy secrets. Then re-run the",
    "  deploy workflow so the server picks them up.",
    ...bullets,
    "- **Infrastructure code:** `opscrew/infra/` is plain Terraform/OpenTofu that you own. You can run it yourself; state is",
    "  kept in `.opscrew/tfstate/` on the machine that ran `opscrew provision`.",
    "",
  ];
}

/**
 * The last bullet of "Check for drift": the generated files against the plan, in the
 * environment's infrastructure root and {@link runtimeDir} (prod: `opscrew/infra/` and
 * `opscrew/runtime/`).
 */
export function driftFiles(plan: DeployPlan): string[] {
  const env = plan.environment?.name;
  const infra = env === undefined ? "opscrew/infra" : plan.infra.dir;
  const planFile =
    env === undefined ? "opscrew/plan.yaml" : `opscrew/environments/${env}/plan.yaml`;
  return [
    `- **The files with the plan:** files under \`${infra}/\` and \`${runtimeDir(plan)}/\` that differ from what`,
    `  \`${planFile}\` would generate.`,
  ];
}

