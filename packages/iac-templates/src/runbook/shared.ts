/** "Change settings and secrets", with the target's own bullets between the shared ones. */
export function settingsSection(
  plan: DeployPlan,
  environments: readonly string[] | undefined,
  bullets: readonly string[],
): string[] {
  const { state, infra } = runbookFolders(plan, undefined);
  return [
    "## Change settings and secrets",
    "",
    `- **App environment variables:** run \`${opscrew(plan, "provision", environments)}\` again; it updates the GitHub deploy secrets. Then re-run the`,
    "  deploy workflow so the server picks them up.",
    ...bullets,
    `- **Infrastructure code:** \`${infra}/\` is plain Terraform/OpenTofu that you own. You can run it yourself; state is`,
    `  kept in \`${state}/tfstate/\` on the machine that ran \`${opscrew(plan, "provision", environments)}\`.`,
    "",
  ];
}

/**
 * The last bullet of "Check for drift": the generated files against the plan, in the
 * environment's infrastructure root and {@link runtimeDir} (prod: `opscrew/infra/` and
 * `opscrew/runtime/`).
 */
export function driftFiles(plan: DeployPlan): string[] {
  const { artefacts, infra } = runbookFolders(plan, undefined);
  return [
    `- **The files with the plan:** files under \`${infra}/\` and \`${runtimeDir(plan)}/\` that differ from what`,
    `  \`${artefacts}/plan.yaml\` would generate.`,
  ];
}

/** The start of "Security": the reports OpsCrew writes. */
export function securityHead(
  plan: DeployPlan,
  environments: readonly string[] | undefined,
): string[] {
  const { artefacts } = runbookFolders(plan, undefined);
  return [
    "## Security",
    "",
    `- Run \`${opscrew(plan, "secure", environments)}\` for a fresh security report (\`${artefacts}/SECURITY_REPORT.md\`) and \`${opscrew(plan, "verify", environments)}\` to check DNS,`,
    "  HTTPS, the health endpoint and security headers.",
  ];
}

/** "If something is wrong". */
export function troubleshooting(
  plan: DeployPlan,
  environments: readonly string[] | undefined,
): string[] {
  return [
    "## If something is wrong",
    "",
    `1. Open the latest "${workflowName(plan)}" run in GitHub → Actions and read the failed step.`,
    `2. Run \`${opscrew(plan, "verify", environments)}\` to see which check fails (DNS, certificate, health endpoint …).`,
    "3. On the server, `docker compose logs --tail 200 app` usually shows why the app does not start.",
    "",
  ];
}

/** The runbook's last lines. */
export function deployAgain(
  plan: DeployPlan,
  environments: readonly string[] | undefined,
): string[] {
  return [`To deploy again later, run \`${opscrew(plan, "provision", environments)}\`.`, ""];
}
