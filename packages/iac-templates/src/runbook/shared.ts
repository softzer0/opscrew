import type { DeployPlan } from "@opscrew/plan-schema";
import type { RenderContext } from "../types";

/** Text for a Markdown table cell. */
export function cell(text: string): string {
  return text.replace(/\|/g, "\\|");
}

/** The title, the generation note and the first rows of "At a glance" (the app and its check). */
export function runbookHead(
  plan: DeployPlan,
  ctx: Pick<RenderContext, "opscrewVersion">,
  url: string,
): string[] {
  return [
    `# Runbook: ${plan.app.name}`,
    "",
    `Generated by OpsCrew ${ctx.opscrewVersion} from \`opscrew/plan.yaml\`. Run \`opscrew verify\` to refresh it.`,
    "",
    "## At a glance",
    "",
    "| | |",
    "|---|---|",
    `| App | ${cell(url)} |`,
    `| Health check | \`${plan.app.healthPath}\` |`,
  ];
}

/** The "Database" cell when Postgres does not run with the app: its external services, or `None`. */
export function externalDatabaseCell(plan: DeployPlan): string {
  return plan.externalServices.length > 0
    ? `External: ${plan.externalServices.join(", ")} (not managed by OpsCrew)`
    : "None";
}

/** The "Deploys" and "Image" rows of "At a glance". */
export function deployRows(plan: DeployPlan, repo: string): string[] {
  return [
    `| Deploys | every push to \`${plan.cicd.branch}\` runs \`${plan.cicd.workflowPath}\` |`,
    `| Image | \`ghcr.io/${repo.toLowerCase()}\` (GitHub Container Registry) |`,
  ];
}

/**
 * "How a deploy works" and "Roll back", with the target's notes after the build step (`build`) and
 * after the start step (`start`).
 */
export function deploySections(
  plan: DeployPlan,
  notes: { build?: readonly string[]; start?: readonly string[] } = {},
): string[] {
  const branch = plan.cicd.branch;
  return [
    "## How a deploy works",
    "",
    `1. You push to \`${branch}\` (or run the "OpsCrew deploy" workflow by hand in GitHub → Actions).`,
    "2. GitHub Actions builds the Docker image from your Dockerfile and pushes it to GitHub Container Registry.",
    ...(notes.build ?? []),
    "3. It copies `opscrew/runtime/compose.yaml` and `opscrew/runtime/Caddyfile` to `/srv/app` on the server, writes the",
    "   app's environment from the deploy secrets, and starts the new version with Docker Compose.",
    ...(notes.start ?? []),
    `4. It checks \`${plan.app.healthPath}\`. If the app does not answer within three minutes, it restores the previous`,
    "   version automatically and the run fails.",
    "",
    "## Roll back",
    "",
    '- **Fastest:** in GitHub → Actions, open the last successful "OpsCrew deploy" run and choose **Re-run all jobs**.',
    `- **With git:** revert the bad commit and push to \`${branch}\`; the workflow deploys the reverted code.`,
    "",
  ];
}

/** A shell block that logs in with `login` and shows the app's containers in `/srv/app`. */
export function serverCommands(login: readonly string[]): string[] {
  return [
    "```bash",
    ...login,
    "cd /srv/app",
    "docker compose ps                 # what is running",
    "docker compose logs -f app        # follow the app's logs",
    "docker compose restart app        # restart the app",
    "```",
  ];
}

/** Dumping and restoring the database on the server. */
export const DATABASE_DUMP = [
  "```bash",
  "# On the server: dump the database to a file",
  'docker compose exec -T db sh -c \'pg_dump -U "$POSTGRES_USER" "$POSTGRES_DB"\' > backup.sql',
  "# Restore a dump",
  'docker compose exec -T db sh -c \'psql -U "$POSTGRES_USER" "$POSTGRES_DB"\' < backup.sql',
  "```",
  "",
];

/** "Change settings and secrets", with the target's own bullets between the shared ones. */
export function settingsSection(bullets: readonly string[]): string[] {
  return [
    "## Change settings and secrets",
    "",
    "- **App environment variables:** run `opscrew provision` again; it updates the GitHub deploy secrets. Then re-run the",
    "  deploy workflow so the server picks them up.",
    ...bullets,
    "- **Infrastructure code:** `opscrew/infra/` is plain Terraform/OpenTofu that you own. You can run it yourself; state is",
    "  kept in `.opscrew/tfstate/` on the machine that ran `opscrew provision`.",
    "",
  ];
}

