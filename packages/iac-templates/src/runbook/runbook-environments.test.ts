import { type DeployPlan, DeployPlanSchema } from "@opscrew/plan-schema";
import { describe, expect, it } from "vitest";
import { testContext, testPlan } from "../__fixtures__/plans";
import { inEnvironment, withPlan } from "../workflow/__fixtures__/plans";
import { renderRunbook } from "./index";

const ctx = testContext({ projectId: "shop-0123456789ab" });
const PROMOTE = { from: "promote", source: "staging" } as const;

/** `plan` as the named environment `name`, with the infrastructure root design gives it. */
function named(plan: DeployPlan, environment: Parameters<typeof inEnvironment>[1]): DeployPlan {
  const env = inEnvironment(plan, environment);
  return DeployPlanSchema.parse({
    ...env,
    infra: { ...env.infra, dir: `opscrew/infra/${environment.name}` },
  });
}

/** Every inline `opscrew …` command of a runbook (the text between backticks). */
function commands(content: string): string[] {
  return [...content.matchAll(/`(?:npx )?(opscrew [a-z][^`]*)`/g)].map(
    (match) => match[1] as string,
  );
}

describe("renderRunbook per environment", () => {
  const staging = named(testPlan({ domain: "shop.example.com" }), {
    name: "staging",
    secrets: "environment",
  });
  const file = renderRunbook(staging, ctx);

  it("is written beside the environment's plan, and names its own files", () => {
    expect(file.path).toBe("opscrew/environments/staging/RUNBOOK.md");
    const { content } = file;
    expect(content).toContain(
      "Generated by OpsCrew 0.1.0 from `opscrew/environments/staging/plan.yaml`. Run `opscrew verify --env staging` to refresh it.",
    );
    expect(content).toContain(
      "~/.opscrew/projects/shop-0123456789ab/environments/staging/deploy_key",
    );
    expect(content).toContain("`.opscrew/environments/staging/tfstate/`");
    expect(content).toContain("`opscrew/infra/staging/`");
    expect(content).toContain("`opscrew/environments/staging/secrets.sops.json`");
    expect(content).toContain("`opscrew/environments/staging/SECURITY_REPORT.md`");
    expect(content).toContain('"OpsCrew deploy (staging)"');
    expect(content).not.toContain(".opscrew/tfstate/");
    expect(content).not.toContain("projects/shop-0123456789ab/deploy_key");
    expect(content).not.toContain("`opscrew/secrets.sops.json`");
  });

  it("puts --env on every command that acts on the deployment", () => {
    const acting = commands(file.content).filter(
      (command) => !/^opscrew (env list|promote)\b/.test(command),
    );
    expect(acting.length).toBeGreaterThan(20);
    for (const command of acting) expect(command).toContain("--env staging");
    // The SSH commands' address lookups too.
    expect(file.content).toContain("deploy@$(opscrew status --ip --env staging)");
  });

  it("says which environment it is and where its deploy secrets live", () => {
    expect(file.content).toContain(
      "| Environment | `staging` (`opscrew env list` shows them all): `opscrew promote` takes `--to staging`, every other command `--env staging` |",
    );
    expect(file.content).toContain(
      "| Deploy secrets | the GitHub environment `staging`, named `OPSCREW_STAGING_…`; the build values are repository secrets |",
    );
    const prefixed = renderRunbook(
      named(testPlan({ domain: "shop.example.com" }), { name: "staging", secrets: "prefixed" }),
      ctx,
    ).content;
    expect(prefixed).toContain(
      "| Deploy secrets | repository secrets, named `OPSCREW_STAGING_…` |",
    );
  });

  it("changes the components in the environment's own plan, and designs it again", () => {
    expect(file.content).toContain("in `opscrew/environments/staging/plan.yaml`, then run");
    expect(file.content).toContain(
      "`opscrew design --env staging` (it checks that everything fits",
    );
  });

  it("changes a promoted environment's components in its source's plan", () => {
    const qa = named(testPlan({ domain: "shop.example.com" }), {
      name: "qa",
      deploySource: PROMOTE,
    });
    const promoted = { ...ctx, builderBranch: "main" };
    expect(renderRunbook(qa, promoted).content).toContain(
      "in `staging`'s plan (`opscrew/environments/staging/plan.yaml`): qa copies its components from it at its next design, then run",
    );
    const fromProd = named(testPlan({ domain: "shop.example.com" }), {
      name: "qa",
      deploySource: { from: "promote", source: "prod" },
    });
    expect(renderRunbook(fromProd, promoted).content).toContain(
      "in `prod`'s plan (`opscrew/plan.yaml`): qa copies its components from it at its next design",
    );
  });

  it("deploys a promoted environment only by promotion, and rolls it back the same way", () => {
    const prod = inEnvironment(testPlan({ domain: "shop.example.com" }), {
      deploySource: PROMOTE,
      secrets: "environment",
    });
    // staging, which prod is promoted from, follows develop.
    const { content } = renderRunbook(prod, { ...ctx, builderBranch: "develop" });
    expect(content).toContain(
      "| Deploys | only by `opscrew promote --to prod`, which runs `.github/workflows/opscrew-deploy.yml` with the image the `staging` environment runs |",
    );
    expect(content).toContain(
      "1. `opscrew promote --to prod` finds the image the `staging` environment runs, checks that a push to\n   `develop` in this repository built it,",
    );
    expect(() => renderRunbook(prod, ctx)).toThrow(/without the branch that builds its images/);
    expect(content).toContain("`--yes` never approves a promotion.");
    expect(content).toContain("checks the image's build again. Nothing is rebuilt.");
    expect(content).toContain(
      "- **The previous image:** `opscrew promote --to prod --digest <digest>`, with the digest of the image tagged",
    );
    expect(content).toContain("`opscrew-prod-previous` in GitHub Container Registry.");
    expect(content).not.toContain("builds the Docker image");
    expect(content).not.toContain("Re-run all jobs");
    // Prod's own commands and files stay prod's.
    expect(content).not.toContain("--env");
    expect(content).toContain(
      "| Deploy secrets | the GitHub environment `production`; the build values are repository secrets |",
    );

    const signed = renderRunbook(withPlan(prod, { supplyChain: { sign: true } }), {
      ...ctx,
      builderBranch: "main",
    }).content;
    expect(signed).toContain(
      "checks the image's build again and its cosign signature. Nothing is rebuilt.",
    );
  });

  it("names the server's runner, and leaves out the tunnel's SSH for its deploys", () => {
    const own = named(testPlan({ provider: "own", access: "tunnel", domain: "shop.example.com" }), {
      name: "staging",
      runner: "server",
    });
    const { content } = renderRunbook(own, ctx);
    expect(content).toContain(
      "| Deploy job | on the server's own runner (label `opscrew-shop-staging`), so GitHub never connects to the server over SSH |",
    );
    expect(content).toContain(
      "   The deploy job runs on the server's own runner (label `opscrew-shop-staging`), so GitHub never connects",
    );
    expect(content).not.toContain("installs a pinned `cloudflared`");
    expect(content).toContain("`opscrew destroy --undo-host --env staging`");
    expect(file.content).not.toContain("| Deploy job |");
  });

  it("leaves a prod-only app's runbook without environment rows", () => {
    const { content } = renderRunbook(testPlan({ domain: "shop.example.com" }), ctx);
    expect(content).not.toContain("| Environment |");
    expect(content).not.toContain("| Deploy secrets |");
    expect(content).not.toContain("--env");
  });

  it("puts --env prod on prod's commands beside other environments, and nothing with prod alone", () => {
    for (const provider of ["hetzner", "own"] as const) {
      const prod = testPlan({ provider, domain: "shop.example.com" });
      const before = renderRunbook(prod, ctx).content;
      expect(renderRunbook(prod, { ...ctx, environments: ["prod"] }).content).toBe(before);

      const { content } = renderRunbook(prod, { ...ctx, environments: ["prod", "staging"] });
      const acting = commands(content).filter(
        (command) => !/^opscrew (env list|promote|portainer)\b/.test(command),
      );
      expect(acting.length).toBeGreaterThan(15);
      for (const command of acting) expect(command).toContain("--env prod");
      expect(content).toContain(
        "| Environment | `prod` (`opscrew env list` shows them all): `opscrew promote` takes `--to prod`, every other command `--env prod` |",
      );
      // Prod's files stay where they are.
      expect(content).toContain("Generated by OpsCrew 0.1.0 from `opscrew/plan.yaml`.");
      expect(content).toContain("`opscrew/secrets.sops.json`");
      expect(content).not.toContain("environments/prod");
    }
  });
});
