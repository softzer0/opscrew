import type { DeployPlan } from "@opscrew/plan-schema";
import { siteHosts } from "../runtime";
import type { RenderContext, RenderedFile } from "../types";

const PENDING = "_(set by `opscrew provision`)_";

function money(plan: DeployPlan): string {
  const { amount, currency } = plan.cost.monthly;
  const symbol = currency === "EUR" ? "€" : "$";
  const vat = plan.cost.pricesIncludeVat ? "incl. VAT" : "excl. VAT";
  const source =
    plan.cost.source === "static"
      ? `, estimate from Hetzner's price list of ${plan.cost.asOf.slice(0, 10)}`
      : "";
  return `${symbol}${amount.toFixed(2)} per month (${vat}${source})`;
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|");
}

/**
 * `opscrew/RUNBOOK.md`: how this deployment works and how to operate it, in plain English, with
 * the real values from the plan. Deterministic; contains no secrets or absolute paths.
 */
export function renderRunbook(plan: DeployPlan, ctx: RenderContext): RenderedFile {
  const ip = plan.deployment.serverIpv4 ?? ctx.serverIpv4;
  const ipv6 = plan.deployment.serverIpv6 ?? ctx.serverIpv6;
  const hosts = siteHosts(plan);
  const url = hosts.length > 0 ? `https://${hosts[0]}` : ip ? `http://${ip}` : PENDING;
  const keyPath = `~/.opscrew/projects/${ctx.projectId ?? "<project-id>"}/deploy_key`;
  const ssh = ip ? `ssh -i ${keyPath} deploy@${ip}` : `ssh -i ${keyPath} deploy@<server-ip>`;
  const branch = plan.cicd.branch;
  const repo = `${ctx.github.owner}/${ctx.github.repo}`;
  const db = plan.services.postgres
    ? `PostgreSQL 17 in a container on the server, data in \`/srv/data/postgres\`${plan.target.backups ? "; Hetzner automated backups are on" : "; automated backups are off"}`
    : plan.externalServices.length > 0
      ? `External: ${plan.externalServices.join(", ")} (not managed by OpsCrew)`
      : "None";
  const dns =
    plan.dns.provider === "cloudflare" && plan.dns.domain
      ? `Cloudflare, ${plan.dns.proxied ? "proxied (the server IP is hidden behind Cloudflare)" : "DNS only"}`
      : "No domain yet: the app is served over plain HTTP on the server IP";

  const lines = [
    `# Runbook: ${plan.app.name}`,
    "",
    `Generated by OpsCrew ${ctx.opscrewVersion} from \`opscrew/plan.yaml\`. Run \`opscrew verify\` to refresh it.`,
    "",
    "## At a glance",
    "",
    "| | |",
    "|---|---|",
    `| App | ${cell(url)} |`,
    `| Health check | \`${plan.app.healthPath}\` |`,
    `| Server | ${cell(`${plan.app.name} — Hetzner Cloud ${plan.target.serverType} in ${plan.target.location}`)} |`,
    `| IPv4 / IPv6 | ${ip ?? PENDING} / ${ipv6 ?? PENDING} |`,
    `| Deploys | every push to \`${branch}\` runs \`${plan.cicd.workflowPath}\` |`,
    `| Image | \`ghcr.io/${repo.toLowerCase()}\` (GitHub Container Registry) |`,
    `| Database | ${cell(db)} |`,
    `| DNS | ${cell(dns)} |`,
    `| Cost | ${cell(money(plan))} |`,
    "",
    "## How a deploy works",
    "",
    `1. You push to \`${branch}\` (or run the "OpsCrew deploy" workflow by hand in GitHub → Actions).`,
    "2. GitHub Actions builds the Docker image from your Dockerfile and pushes it to GitHub Container Registry.",
    "3. It copies `opscrew/runtime/compose.yaml` and `opscrew/runtime/Caddyfile` to `/srv/app` on the server, writes the",
    "   app's environment from the deploy secrets, and starts the new version with Docker Compose.",
    `4. It checks \`${plan.app.healthPath}\`. If the app does not answer within three minutes, it restores the previous`,
    "   version automatically and the run fails.",
    "",
    "## Roll back",
    "",
    '- **Fastest:** in GitHub → Actions, open the last successful "OpsCrew deploy" run and choose **Re-run all jobs**.',
    `- **With git:** revert the bad commit and push to \`${branch}\`; the workflow deploys the reverted code.`,
    "",
    "## Connect to the server",
    "",
    "```bash",
    ssh,
    "cd /srv/app",
    "docker compose ps                 # what is running",
    "docker compose logs -f app        # follow the app's logs",
    "docker compose restart app        # restart the app",
    "```",
    "",
    "The deploy key is stored only on the machine where you ran `opscrew provision` (and as a GitHub Actions",
    "secret). Password login and root login are disabled on the server.",
    "",
  ];

  if (plan.services.postgres) {
    lines.push(
      "## Database backups",
      "",
      plan.target.backups
        ? "Hetzner takes a backup of the whole server every day and keeps the last seven (Hetzner Console → your server → Backups)."
        : "Automated server backups are **off**. Turn them on with `opscrew design` (20% of the server price) or make your own backups:",
      "",
      "```bash",
      "# On the server: dump the database to a file",
      'docker compose exec -T db sh -c \'pg_dump -U "$POSTGRES_USER" "$POSTGRES_DB"\' > backup.sql',
      "# Restore a dump",
      'docker compose exec -T db sh -c \'psql -U "$POSTGRES_USER" "$POSTGRES_DB"\' < backup.sql',
      "```",
      "",
    );
  }

  lines.push(
    "## Change settings and secrets",
    "",
    "- **App environment variables:** run `opscrew provision` again; it updates the GitHub deploy secrets. Then re-run the",
    "  deploy workflow so the server picks them up.",
    "- **Server size, location, domain:** run `opscrew design` and `opscrew provision`. OpsCrew shows the plan and the cost",
    "  change and applies nothing without your approval. Destroying or replacing the server always needs a typed confirmation.",
    "- **Infrastructure code:** `opscrew/infra/` is plain Terraform/OpenTofu that you own. You can run it yourself; state is",
    "  kept in `.opscrew/tfstate/` on the machine that ran `opscrew provision`.",
    "",
    "## Security",
    "",
    "- Run `opscrew secure` for a fresh security report (`opscrew/SECURITY_REPORT.md`) and `opscrew verify` to check DNS,",
    "  HTTPS, the health endpoint and security headers.",
    "- What OpsCrew set up on the server: a `deploy` user with key-only SSH, no root login, fail2ban against brute force,",
    "  automatic security updates, a host firewall (22/80/443) in addition to the Hetzner firewall, and Docker log limits.",
  );
  if (plan.dns.provider === "cloudflare" && plan.dns.proxied) {
    lines.push(
      "- Web traffic reaches the server only through Cloudflare; the server's firewall accepts ports 80 and 443 only from",
      "  Cloudflare's IP ranges.",
    );
  }
  lines.push(
    "",
    "## If something is wrong",
    "",
    '1. Open the latest "OpsCrew deploy" run in GitHub → Actions and read the failed step.',
    "2. Run `opscrew verify` to see which check fails (DNS, certificate, health endpoint …).",
    "3. On the server, `docker compose logs --tail 200 app` usually shows why the app does not start.",
    "",
  );
  return { path: "opscrew/RUNBOOK.md", content: lines.join("\n"), kind: "doc" };
}
