import { EDGE_PROJECT } from "../edge";
import { IMAGES } from "../pins";
import { shellQuote } from "../runtime/services";

/**
 * The formats of a value the preview server generates for a placeholder
 * `@SECRET:<name>:<format>@`: `hex32` (32 random bytes as hex), `hex64` (64 bytes as hex, Rails'
 * `SECRET_KEY_BASE`), `b64k32` (`base64:` and 32 random bytes in base64, Laravel's `APP_KEY`) and
 * `gk` (`GK` and 12 random bytes as hex, a Garage key id).
 */
export const PREVIEW_SECRET_FORMATS = ["hex32", "hex64", "b64k32", "gk"] as const;

/** One of {@link PREVIEW_SECRET_FORMATS}. */
export type PreviewSecretFormat = (typeof PREVIEW_SECRET_FORMATS)[number];

/**
 * Every `@SECRET:<name>:<format>@` placeholder (an extended regular expression, for JavaScript and
 * `grep -E`), the format its group.
 */
export const PREVIEW_SECRET_PLACEHOLDER = `@SECRET:[A-Za-z][A-Za-z0-9_-]*:(${PREVIEW_SECRET_FORMATS.join("|")})@`;

/** A generated value's name in a placeholder: a letter, then letters, digits, `_` or `-`. */
export const PREVIEW_SECRET_NAME = /^[A-Za-z][A-Za-z0-9_-]{0,63}$/;

/**
 * How `opscrew-preview` tells which step of the start script failed: the start of the line that
 * step prints (`switchCommands`' messages); any other failure is the step `start`.
 */
const START_FAILURES = {
  release: "::error::The release command (app.releaseCommand in ",
  edge: "::error::OpsCrew's shared edge on the server ",
  health: "::error::The new version did not pass its health check ",
} as const;

/**
 * `/srv/apps/<app>/bin/opscrew-preview`, the preview server's command (POSIX sh). It reads its
 * request from `SSH_ORIGINAL_COMMAND` when set (the preview key's forced command: `up`, `down`
 * and `list` only), else from its arguments (the deploy key and cron: also `gc` and `logs`), and
 * refuses any other request before it reads or writes anything:
 * - `up <n> <IMAGE_NAME>@sha256:<digest> <commit>`, the registry token on stdin: creates preview
 *   `<n>` (the app `<APP>-pr-<n>`, the cap checked under the recipe's lock) or updates it under
 *   its own lock: fills `template/` into `/srv/apps/<APP>-pr-<n>/` (`@N@`, and each
 *   `@SECRET:<name>:<format>@` from the preview's `secrets.env`, generated the first time a name
 *   appears), logs in to the registry in the preview's `.docker` (removed when `up` ends), pulls,
 *   runs `start.sh` (on a failed update `rollback.sh` puts the previous image back; on a failed
 *   creation nothing stays routed), then the seed while `.seeded` is absent;
 * - `down <n>`: `.preview` and `.seeded`, the route, the site, the containers, networks and
 *   volumes, the data, then the folder, in an order a later `down` repeats, stopping at a step
 *   that fails;
 * - `list`: `<n> <state> <commit> <created> <updated> <digest>` per preview (`-` for what a preview
 *   half made or half removed lacks);
 * - `gc` (cron): `down` for each preview not updated for `LIFETIME_DAYS` days, logged as `gc`; it
 *   prints nothing unless a removal fails, which prints its line on stderr and exits non-zero;
 * - `logs <n>`: the last 200 lines of each of the preview's containers, then `listed <n>`
 *   (`removed <n>` when there is no such preview).
 * The steps' output goes to the preview's `up.log`; the caller gets only the script's own lines,
 * the last `opscrew-preview: <state> <detail>` with the contract's exit code. Each lock taken is
 * checked to still be the preview's after the wait. Every `up` and `down`, and each preview `gc`
 * removes, appends a line to `previews.log`. The server's folders come from the absolute path it
 * runs by (`<srv>/apps/<APP>/bin/opscrew-preview`; any other fails closed), never from its
 * environment.
 */
export function previewScript(): string {
  return `#!/bin/sh
# opscrew-preview: the only command a pull request's job runs on this preview server, through the
# preview key. Generated by OpsCrew; opscrew provision installs it, with the recipe it enforces, in
# the folder above. Requests: up <number> <image>@sha256:<digest> <commit> (the registry token on
# stdin), down <number> and list; with the deploy key or cron also gc and logs <number>. Every
# value it writes comes from settings.env, template/, values.env, a request word that matched its
# pattern, or /dev/urandom. Its last line is always: opscrew-preview: <state> <detail>.
set -eu
umask 022
LC_ALL=C
export LC_ALL
# A caller that went away must not stop it before it cleans up.
trap "" PIPE

# The forced command and cron run it by its absolute path, <srv>/apps/<app>/bin/opscrew-preview.
case "$0" in
  /*/apps/*/bin/opscrew-preview) ;;
  *)
    echo "opscrew-preview: failed start"
    exit 4
    ;;
esac
RECIPE="\${0%/bin/opscrew-preview}"
SRV="\${RECIPE%/apps/*}"
APPS_DIR="$SRV/apps"
EDGE_DIR="$SRV/edge"
DATA_DIR="$SRV/data"

caller=local
log_as=""
finished=""
step=start
docker_config=""
n=""

# One line in previews.log: the time, the command and number, the caller and the state.
record() {
  printf '%s %s %s %s %s\\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$log_as" "$n" "$caller" "$1" >> "$RECIPE/previews.log"
}

# The last line, opscrew-preview: <state> <detail>, then exit code $3.
finish() {
  finished=1
  if [ -n "$docker_config" ]; then rm -rf "$docker_config"; fi
  if [ -n "$log_as" ]; then record "$1"; fi
  echo "opscrew-preview: $1 $2"
  exit "$3"
}

# The registry login goes when the script ends; an error nobody expected fails the step it was in.
on_exit() {
  if [ -z "$finished" ]; then finish failed "$step" 4; fi
}
trap on_exit EXIT

refuse() {
  finish refused "$1" 2
}

# A pull request's number: 1 to 6 digits, not starting with 0.
number_ok() {
  case "$1" in "" | 0* | *[!0-9]*) return 1 ;; esac
  [ "\${#1}" -le 6 ]
}

if [ -n "\${SSH_ORIGINAL_COMMAND+set}" ]; then
  caller=key
  if [ "$#" -gt 0 ]; then refuse request; fi
  request="$SSH_ORIGINAL_COMMAND"
else
  request="$*"
fi
# Words of a-z 0-9 . _ / @ : - separated by single spaces: nothing for a shell to expand.
case "$request" in
  "" | " "* | *" " | *"  "* | *[!a-z0-9._/@:' '-]*) refuse request ;;
esac
set -- $request
if [ "$#" -gt 4 ]; then refuse request; fi
case "$1" in
  up | down | list) ;;
  gc | logs) if [ "$caller" = key ]; then refuse command; fi ;;
  *) refuse command ;;
esac
case "$1 $#" in
  "up 4" | "down 2" | "list 1" | "gc 1" | "logs 2") ;;
  *) refuse request ;;
esac

. "$RECIPE/settings.env"

case "$1" in
  up | down | logs)
    if ! number_ok "$2"; then refuse number; fi
    n="$2"
    ;;
esac
if [ "$1" = up ]; then
  case "$3" in
    "$IMAGE_NAME@sha256:"*) hex="\${3#"$IMAGE_NAME@sha256:"}" ;;
    *) refuse image ;;
  esac
  case "$hex" in *[!0-9a-f]*) refuse image ;; esac
  if [ "\${#hex}" -ne 64 ]; then refuse image; fi
  case "$4" in *[!0-9a-f]*) refuse commit ;; esac
  if [ "\${#4}" -ne 40 ]; then refuse commit; fi
  token="$(head -c 4097)"
  case "$token" in "" | *[!A-Za-z0-9._~+/=-]*) refuse token ;; esac
  if [ "\${#token}" -gt 4096 ]; then refuse token; fi
fi

NAME="$APP-pr-$n"
P="$APPS_DIR/$NAME"
HOST="pr-$n.$BASE"

edge() {
  docker compose -p ${EDGE_PROJECT} -f "$EDGE_DIR/compose.yaml" "$@" < /dev/null
}

# The previews' numbers, from their folders, smallest first.
numbers() {
  for dir in "$APPS_DIR/$APP"-pr-*; do
    k="\${dir#"$APPS_DIR/$APP-pr-"}"
    if [ -d "$dir" ] && number_ok "$k"; then echo "$k"; fi
  done | sort -n
}

# The value of $2 in the .preview file of the preview in folder $1, else $3.
field() {
  value="$(sed -n "s/^$2=//p" "$1/.preview" 2> /dev/null | head -n 1)"
  echo "\${value:-$3}"
}

# The preview's state and this up's commit and digest, with its creation and update times.
write_preview() {
  printf 'state=%s\\ncommit=%s\\ndigest=%s\\ncreated=%s\\nupdated=%s\\n' "$1" "$commit" "$digest" "$created" "$(date +%s)" > "$P/.preview.new"
  mv -f "$P/.preview.new" "$P/.preview"
}

# True when the preview in folder $1 was not updated for LIFETIME_DAYS days: its .preview, else
# the time of its compose.yaml (every up writes it, a removal leaves it), else of its folder.
idle() {
  updated="$(field "$1" updated "")"
  case "$updated" in
    "" | *[!0-9]*)
      since="$1"
      if [ -f "$1/compose.yaml" ]; then since="$1/compose.yaml"; fi
      updated="$(date -r "$since" +%s)"
      ;;
  esac
  [ "$(($(date +%s) - updated))" -gt "$((LIFETIME_DAYS * 86400))" ]
}

# Takes the preview's own lock (busy after 600 seconds). False when the preview has no folder, or
# when a removal took the folder, and so the lock, away while this one waited.
lock_preview() {
  if [ ! -d "$P" ]; then return 1; fi
  exec 7> "$P/.lock"
  flock -w 600 7 || finish busy 600 6
  if [ "$P/.lock" -ef /proc/self/fd/7 ]; then return 0; fi
  exec 7>&-
  return 1
}

# Takes the preview's own lock; a preview without a folder gets one first, under the recipe's
# lock, after the cap check.
enter() {
  until lock_preview; do
    exec 8> "$RECIPE/.lock"
    flock -w 600 8 || finish busy 600 6
    if [ ! -d "$P" ]; then
      count="$(numbers | wc -l | tr -d ' ')"
      if [ "$count" -ge "$CAP" ]; then finish cap "$count/$CAP" 3; fi
      mkdir "$P"
      created="$(date +%s)"
      write_preview failed
    fi
    exec 8>&-
  done
}

# A new random value in the format $1.
generate() {
  case "$1" in
    hex32) od -An -tx1 -N32 /dev/urandom | tr -d ' \\n' ;;
    hex64) od -An -tx1 -N64 /dev/urandom | tr -d ' \\n' ;;
    b64k32) printf 'base64:%s' "$(head -c 32 /dev/urandom | base64 | tr -d '\\n')" ;;
    gk) printf 'GK%s' "$(od -An -tx1 -N12 /dev/urandom | tr -d ' \\n')" ;;
  esac
}

# template/ filled into the preview's folder: @N@ is its number, each @SECRET:<name>:<format>@
# the value secrets.env keeps for the name, made the first time the name appears. The app's env
# file is values.env, then the filled env/app.env; the services' env files are owner-only too.
fill() {
  script="$P/.fill.sed"
  (
    umask 077
    touch "$P/secrets.env"
    printf 's|@N@|%s|g\\n' "$n" > "$script"
    for placeholder in $(grep -rhoE '${PREVIEW_SECRET_PLACEHOLDER}' "$RECIPE/template" | sort -u); do
      rest="\${placeholder#@SECRET:}"
      name="\${rest%%:*}"
      format="\${rest#*:}"
      value="$(sed -n "s/^$name=//p" "$P/secrets.env" | head -n 1)"
      if [ -z "$value" ]; then
        value="$(generate "\${format%@}")"
        printf '%s=%s\\n' "$name" "$value" >> "$P/secrets.env"
      fi
      printf 's|%s|%s|g\\n' "$placeholder" "$value" >> "$script"
    done
  )
  (cd "$RECIPE/template" && find . -type f) | while IFS= read -r file; do
    file="\${file#./}"
    case "$file" in
      env/app.env)
        (
          umask 077
          {
            cat "$RECIPE/values.env"
            if [ -n "$(tail -c 1 "$RECIPE/values.env")" ]; then echo; fi
            sed -f "$script" "$RECIPE/template/$file"
          } > "$P/app.env"
        )
        ;;
      env/*) (umask 077 && sed -f "$script" "$RECIPE/template/$file" > "$P/\${file#env/}") ;;
      *)
        target="$P/$file"
        while :; do
          case "$target" in *@N@*) target="\${target%%@N@*}$n\${target#*@N@}" ;; *) break ;; esac
        done
        if [ ! -d "\${target%/*}" ]; then mkdir -p "\${target%/*}"; fi
        sed -f "$script" "$RECIPE/template/$file" > "$target"
        ;;
    esac
  done
  rm -f "$script"
}

# The start script's step that failed, from the line it printed.
failed_step() {
${Object.entries(START_FAILURES)
  .map(
    ([step, line]) =>
      `  if grep -qF ${shellQuote(line)} "$P/up.log"; then echo ${step}; return; fi`,
  )
  .join("\n")}
  echo start
}

up_preview() {
  image="$1"
  commit="$2"
  digest="\${image#"$IMAGE_NAME@"}"
  log_as=up
  enter
  created="$(field "$P" created "$(date +%s)")"
  # The steps' output can quote data (the seed's): owner-only, as the release command's log.
  (umask 077 && : > "$P/up.log")
  fill
  step=pull
  docker_config="$P/.docker"
  mkdir -p "$docker_config"
  owner="\${IMAGE_NAME#ghcr.io/}"
  if ! printf '%s\\n' "$token" | DOCKER_CONFIG="$docker_config" docker login ghcr.io -u "\${owner%%/*}" --password-stdin >> "$P/up.log" 2>&1 ||
    ! (cd "$P" && APP_IMAGE="$image" DOCKER_CONFIG="$docker_config" docker compose pull < /dev/null >> up.log 2>&1); then
    write_preview failed
    finish failed pull 4
  fi
  token=""
  step=start
  previous=""
  rm -f "$P/.env.previous"
  if [ -f "$P/.env" ]; then
    cp "$P/.env" "$P/.env.previous"
    previous=1
  fi
  if ! (cd "$P" && OPSCREW_APPS_DIR="$APPS_DIR" OPSCREW_EDGE_DIR="$EDGE_DIR" sh ./start.sh "$image" < /dev/null >> up.log 2>&1); then
    why="$(failed_step)"
    (cd "$P" && OPSCREW_APPS_DIR="$APPS_DIR" OPSCREW_EDGE_DIR="$EDGE_DIR" sh ./rollback.sh "$image" < /dev/null >> up.log 2>&1) || true
    if [ -z "$previous" ]; then
      edge exec -T kamal-proxy kamal-proxy remove "$NAME" >> "$P/up.log" 2>&1 || true
      rm -f "$P/.env"
    fi
    write_preview failed
    finish failed "$why" 4
  fi
  step=seed
  if [ "$SEED" = 1 ] && [ ! -f "$P/.seeded" ]; then
    if (cd "$P" && APP_IMAGE="$image" docker compose run --rm --no-deps -T seed < /dev/null >> up.log 2>&1); then
      : > "$P/.seeded"
    else
      write_preview seed-failed
      finish seed-failed "$HOST" 5
    fi
  fi
  write_preview running
  finish running "$HOST" 0
}

# Removes the preview in an order a later down repeats, stopping at the first step that fails:
# its .preview and .seeded (a preview made again in a folder left half removed is seeded again),
# its route, its site, its containers, networks and volumes, its data, then its folder.
remove() {
  rm -f "$P/.preview" "$P/.seeded"
  step=edge
  edge exec -T kamal-proxy kamal-proxy remove "$NAME" > /dev/null 2>&1 || true
  if [ -f "$EDGE_DIR/sites/$NAME.caddy" ]; then
    exec 9> "$EDGE_DIR/.lock"
    flock -w 600 9 || finish busy 600 6
    rm -f "$EDGE_DIR/sites/$NAME.caddy"
    edge exec -T caddy caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile > /dev/null 2>&1 || true
    exec 9>&-
  fi
  step=start
  label="label=com.docker.compose.project=$NAME"
  ids="$(docker ps -aq --filter "$label" 2> /dev/null)"
  if [ -n "$ids" ]; then docker rm -f $ids > /dev/null 2>&1; fi
  ids="$(docker network ls -q --filter "$label" 2> /dev/null)"
  if [ -n "$ids" ]; then docker network rm $ids > /dev/null 2>&1; fi
  ids="$(docker volume ls -q --filter "$label" 2> /dev/null)"
  if [ -n "$ids" ]; then docker volume rm $ids > /dev/null 2>&1; fi
  if [ -e "$DATA_DIR/$NAME" ]; then
    docker run --rm --network none --user 0:0 --entrypoint rm -v "$DATA_DIR:/d" ${IMAGES.caddy.ref} -rf "/d/$NAME" > /dev/null 2>&1
  fi
  rm -rf "$P"
}

# Nothing to remove (no folder, or another removal took it while this one waited) is success.
down_preview() {
  log_as=down
  if lock_preview; then remove; fi
  finish removed "$n" 0
}

list_previews() {
  count=0
  for k in $(numbers); do
    p="$APPS_DIR/$APP-pr-$k"
    echo "$k $(field "$p" state failed) $(field "$p" commit -) $(field "$p" created -) $(field "$p" updated -) $(field "$p" digest -)"
    count=$((count + 1))
  done
  finish listed "$count/$CAP" 0
}

# Cron's: each preview not updated for LIFETIME_DAYS days goes as down removes it, logged as gc,
# and nothing is printed. A removal that fails stops there, keeping the folder, prints its line on
# stderr and makes the exit code its own; the others go on.
gc_previews() {
  code=0
  for k in $(numbers); do
    if ! idle "$APPS_DIR/$APP-pr-$k"; then continue; fi
    set +e
    (
      set -e
      trap on_exit EXIT
      log_as=gc
      n="$k"
      NAME="$APP-pr-$n"
      P="$APPS_DIR/$NAME"
      if lock_preview && idle "$P"; then
        remove
        record removed
      fi
      finished=1
    ) >&2
    result=$?
    set -e
    if [ "$result" -ne 0 ]; then code="$result"; fi
  done
  finished=1
  exit "$code"
}

preview_logs() {
  if [ ! -d "$P" ]; then finish removed "$n" 0; fi
  for name in $(docker ps -a --filter "label=com.docker.compose.project=$NAME" --format '{{.Names}}' | sort); do
    echo "== $name =="
    docker logs --tail 200 "$name" 2>&1
  done
  finish listed "$n" 0
}

case "$1" in
  up) up_preview "$3" "$4" ;;
  down) down_preview ;;
  list) list_previews ;;
  gc) gc_previews ;;
  logs) preview_logs ;;
esac
`;
}
