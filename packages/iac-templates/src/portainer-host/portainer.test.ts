import { DeployPlanSchema } from "@opscrew/plan-schema";
import { describe, expect, it } from "vitest";
import { parse } from "yaml";
import { testPlan } from "../__fixtures__/plans";
import { withPlacement } from "../catalog/__fixtures__/plans";
import { IMAGES } from "../pins";
import { inEnvironment, ofApp } from "../workflow/__fixtures__/plans";
import { PORTAINER_PASSWORD_FILE, renderPortainerCompose } from "./index";

const plan = testPlan({ provider: "own", portainer: { access: "local" } });

describe("renderPortainerCompose", () => {
  const first = renderPortainerCompose(plan, { initialAdmin: true });
  const compose = parse(first.content);
  const service = compose.services.portainer;

  it("runs the pinned Portainer CE as its own project, reachable only from the server", () => {
    expect(first.path).toBe("opscrew/runtime/portainer/compose.yaml");
    expect(compose.name).toBe("opscrew-portainer");
    expect(service.image).toBe("portainer/portainer-ce:2.33.1");
    expect(service.ports).toEqual(["127.0.0.1:9443:9443"]);
    expect(first.content).not.toMatch(/8000|9000|0\.0\.0\.0/);
    expect(service.command).toContain("--http-disabled");
    expect(service.restart).toBe("unless-stopped");
  });

  it("mounts the Docker socket and the portainer_data volume", () => {
    expect(service.volumes).toEqual([
      "/var/run/docker.sock:/var/run/docker.sock",
      "portainer_data:/data",
    ]);
    expect(compose.volumes).toEqual({ portainer_data: {} });
  });

  it("creates the admin from the password file on first start", () => {
    expect(service.command).toEqual([
      "--http-disabled",
      "--admin-password-file",
      "/run/secrets/portainer_admin_password",
    ]);
    expect(service.secrets).toEqual(["portainer_admin_password"]);
    expect(compose.secrets).toEqual({
      portainer_admin_password: { file: `./${PORTAINER_PASSWORD_FILE}` },
    });
  });

  it("drops the password file once the admin exists (Portainer refuses a missing file)", () => {
    const later = parse(renderPortainerCompose(plan, { initialAdmin: false }).content);
    expect(later.services.portainer.command).toEqual(["--http-disabled"]);
    expect(later.services.portainer.secrets).toBeUndefined();
    expect(later.secrets).toBeUndefined();
    expect(later.services.portainer.volumes).toEqual(service.volumes);
  });

  it("is hardened like the app's infrastructure services", () => {
    expect(service.security_opt).toEqual(["no-new-privileges:true"]);
    expect(service.privileged).toBeUndefined();
  });

  it("rotates its own logs, so Docker's daemon settings on the server can stay as they are", () => {
    for (const initialAdmin of [true, false]) {
      const doc = parse(renderPortainerCompose(plan, { initialAdmin }).content);
      expect(doc.services.portainer.logging).toEqual({
        driver: "json-file",
        options: { "max-size": "10m", "max-file": "3" },
      });
      expect(doc.services.portainer.security_opt).toEqual(["no-new-privileges:true"]);
    }
  });

  it("pins the plan's version on every target", () => {
    const hetzner = testPlan({ portainer: { access: "local" } });
    expect(
      parse(renderPortainerCompose(hetzner, { initialAdmin: false }).content).services.portainer
        .image,
    ).toBe("portainer/portainer-ce:2.33.1");
  });

  it("runs OpsCrew's pinned version by digest, and another version by tag with a comment", () => {
    const tag = IMAGES.portainer.ref.slice(0, IMAGES.portainer.ref.indexOf("@")).split(":")[1];
    const pinnedPlan = DeployPlanSchema.parse({
      ...plan,
      portainer: { ...plan.portainer, version: tag },
    });
    const pinned = renderPortainerCompose(pinnedPlan, { initialAdmin: false }).content;
    expect(parse(pinned).services.portainer.image).toBe(IMAGES.portainer.ref);
    expect(pinned).not.toContain("pinned by tag only");

    const other = renderPortainerCompose(plan, { initialAdmin: false }).content;
    expect(parse(other).services.portainer.image).toBe("portainer/portainer-ce:2.33.1");
    expect(other).toContain(
      "# Portainer CE 2.33.1 (portainer.version in the plan) is pinned by tag only, not by digest.",
    );
  });

  it("is the same file from every app's and environment's plan, naming none", () => {
    const file = renderPortainerCompose(plan, { initialAdmin: false }).content;
    expect(file.split("\n")[0]).toBe(
      "# Generated by OpsCrew and shared by every OpsCrew app on this server; any app's `opscrew provision` regenerates it.",
    );
    const staging = ofApp(inEnvironment(plan, { name: "staging" }), "docs");
    expect(renderPortainerCompose(staging, { initialAdmin: false }).content).toBe(file);
  });

  it("is also published on the app's private address on a server for this app alone", () => {
    const devices = withPlacement(plan, { devices: ["laptop"] });
    const content = renderPortainerCompose(devices, {
      initialAdmin: false,
      dashboardsOnNetwork: true,
    }).content;
    expect(parse(content).services.portainer.ports).toEqual([
      "127.0.0.1:9443:9443",
      "10.200.4.1:9443:9443",
    ]);
    expect(content.split("\n").slice(1, 4)).toEqual([
      "# Portainer CE listens on the server itself and, for your devices on the app's private network only,",
      "# on its private address 10.200.4.1. It controls Docker through the socket, which is root on this",
      "# server: never publish its port anywhere else.",
    ]);
    // By default (a server other apps may share) the file stays the same from every app's plan.
    for (const initialAdmin of [true, false]) {
      expect(renderPortainerCompose(devices, { initialAdmin })).toEqual(
        renderPortainerCompose(plan, { initialAdmin }),
      );
    }
  });

  it("needs Portainer settings in the plan", () => {
    expect(() => renderPortainerCompose(testPlan(), { initialAdmin: true })).toThrow(
      /no Portainer settings/,
    );
  });

  it("matches the snapshot", () => {
    expect(first.content).toMatchSnapshot();
  });
});
