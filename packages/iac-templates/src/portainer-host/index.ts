import type { DeployPlan } from "@opscrew/plan-schema";
import { stringify } from "yaml";
import { IMAGES } from "../pins";
import { dashboardAddress } from "../runtime/network";
import { hardened } from "../runtime/services";
import { runtimeDir } from "../runtime-dir";
import { PORTAINER_PORT } from "../tunnel";
import type { RenderContext, RenderedFile } from "../types";

/** Portainer CE image repository; the tag is `plan.portainer.version`. */
export const PORTAINER_IMAGE = "portainer/portainer-ce";

/**
 * Name of the admin password file next to Portainer's compose file on the server (mode 0600, in a
 * directory only its owner can read). It exists only until Portainer has created its admin.
 */
export const PORTAINER_PASSWORD_FILE = "admin_password";

/** Where the container sees the admin password file. */
const PASSWORD_IN_CONTAINER = "/run/secrets/portainer_admin_password";

export interface PortainerComposeOptions extends Pick<RenderContext, "dashboardsOnNetwork"> {
  /**
   * True for the first start: Portainer creates its admin from {@link PORTAINER_PASSWORD_FILE}
   * (`--admin-password-file`). Portainer refuses to start when that flag names a missing file, so
   * once the admin exists the server gets the compose file rendered with `false` (same container,
   * same data) before the password file is deleted.
   */
  initialAdmin: boolean;
}

/**
 * `<runtimeDir>/portainer/compose.yaml`: Portainer CE as its own Compose project
 * (`opscrew-portainer`), pinned to `plan.portainer.version` (by digest when it is the version
 * in `pins.ts`, else by tag), listening only on `127.0.0.1:9443` (no Edge port 8000, HTTP port
 * 9000 disabled), and with `options.dashboardsOnNetwork` also on the app's server's private
 * address ({@link dashboardAddress}), with the Docker socket and the `portainer_data` volume.
 * Throws when the plan has no Portainer settings.
 */
export function renderPortainerCompose(
  plan: DeployPlan,
  options: PortainerComposeOptions,
): RenderedFile {
  const portainer = plan.portainer;
  if (portainer === undefined) {
    throw new Error("The plan has no Portainer settings (plan.portainer) to render.");
  }
  // OpsCrew's pinned version runs by digest; another version the user chose runs by its tag.
  const pinned = IMAGES.portainer.ref.startsWith(`${PORTAINER_IMAGE}:${portainer.version}@`);
  const address = dashboardAddress(plan, options);
  const service: Record<string, unknown> = {
    image: pinned ? IMAGES.portainer.ref : `${PORTAINER_IMAGE}:${portainer.version}`,
    restart: "unless-stopped",
    command: [
      "--http-disabled",
      ...(options.initialAdmin ? ["--admin-password-file", PASSWORD_IN_CONTAINER] : []),
    ],
    ports: [
      `127.0.0.1:${PORTAINER_PORT}:${PORTAINER_PORT}`,
      ...(address === undefined ? [] : [`${address}:${PORTAINER_PORT}:${PORTAINER_PORT}`]),
    ],
    volumes: ["/var/run/docker.sock:/var/run/docker.sock", "portainer_data:/data"],
    ...hardened(),
  };
  if (options.initialAdmin) {
    // Mounted read-only at /run/secrets/portainer_admin_password.
    service.secrets = ["portainer_admin_password"];
  }
  const document: Record<string, unknown> = {
    name: "opscrew-portainer",
    services: { portainer: service },
    volumes: { portainer_data: {} },
  };
  if (options.initialAdmin) {
    document.secrets = { portainer_admin_password: { file: `./${PORTAINER_PASSWORD_FILE}` } };
  }
  // One Portainer serves the whole server and the host plan compares the server's copy with this
  // file, so it is the same from every app's plan and names none, unless the server hosts this app
  // alone (`dashboardsOnNetwork`).
  const header = [
    "# Generated by OpsCrew and shared by every OpsCrew app on this server; any app's `opscrew provision` regenerates it.",
    ...(address === undefined
      ? [
          "# Portainer CE listens only on the server itself: open it through an SSH tunnel (`opscrew portainer",
          "# status` prints the command) or, when you opted in, its Cloudflare Access subdomain. It controls",
          "# Docker through the socket, which is root on this server: never publish its port.",
        ]
      : [
          "# Portainer CE listens on the server itself and, for your devices on the app's private network only,",
          `# on its private address ${address}. It controls Docker through the socket, which is root on this`,
          "# server: never publish its port anywhere else.",
        ]),
    ...(options.initialAdmin
      ? ["# First start: Portainer creates its admin from ./admin_password, which is then deleted."]
      : []),
    ...(pinned
      ? []
      : [
          `# Portainer CE ${portainer.version} (portainer.version in the plan) is pinned by tag only, not by digest.`,
        ]),
  ].join("\n");
  return {
    path: `${runtimeDir(plan)}/portainer/compose.yaml`,
    content: `${header}\n${stringify(document, { lineWidth: 0 })}`,
    kind: "runtime",
  };
}
