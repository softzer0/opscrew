// biome-ignore-all lint/suspicious/noTemplateCurlyInString: these strings are Compose syntax, not JavaScript templates.
import type { OpsCrewError } from "@opscrew/core";
import type { DeployPlan } from "@opscrew/plan-schema";
import { stringify } from "yaml";
import { webOnlyFromCloudflare } from "../predicates";
import { wrongTarget } from "../providers";
import { TUNNEL_ORIGIN_PORT, tunnelMode } from "../tunnel";
import type { RenderContext, RenderedFile } from "../types";
import {
  CADDY_IMAGE,
  cacheService,
  caddyfile,
  cloudflaredService,
  dbService,
  hardened,
} from "./services";

const HEADER = [
  "# Generated by OpsCrew from opscrew/plan.yaml; `opscrew provision` regenerates it.",
  "# The deploy workflow copies it to /srv/app on the server.",
].join("\n");

/** A Portainer target's stack holds both files: reaching these renderers with one is a bug. */
function notForPortainer(): OpsCrewError {
  return wrongTarget(
    "An app in your existing Portainer has no server Compose file or Caddyfile: OpsCrew writes its Portainer stack (opscrew/runtime/compose.yaml) instead.",
  );
}

/**
 * True when a server the user owns serves the site directly behind Cloudflare's proxy with
 * OpsCrew's web filter (public mode, a proxied Cloudflare domain, `security.httpAllowedFrom:
 * cloudflare`). The site is then published on IPv4 only: Docker serves an IPv6 host port of a
 * container without IPv6 through docker-proxy, around the filter in `DOCKER-USER`.
 */
export function webFilterMode(plan: DeployPlan): boolean {
  return (
    plan.target.provider === "own" && plan.target.access === "public" && webOnlyFromCloudflare(plan)
  );
}

/** Caddy's published ports: loopback in tunnel mode, IPv4 only in web-filter mode, else all. */
function caddyPorts(plan: DeployPlan): string[] {
  if (tunnelMode(plan)) return [`127.0.0.1:${TUNNEL_ORIGIN_PORT}:80`];
  if (webFilterMode(plan)) return ["0.0.0.0:80:80", "0.0.0.0:443:443", "0.0.0.0:443:443/udp"];
  return ["80:80", "443:443", "443:443/udp"];
}

/** Hostnames Caddy serves; empty when the plan has no domain yet. */
export function siteHosts(plan: DeployPlan): string[] {
  const domain = plan.dns.domain;
  if (!domain) return [];
  return plan.dns.www ? [domain, `www.${domain}`] : [domain];
}

/**
 * `opscrew/runtime/compose.yaml`: app, optional Postgres and Valkey, and Caddy in front. Throws for
 * a Portainer target, whose stack `renderPortainerStack` renders.
 */
export function renderCompose(plan: DeployPlan, _ctx: RenderContext): RenderedFile {
  if (plan.target.provider === "portainer") throw notForPortainer();
  const image = "${APP_IMAGE:?APP_IMAGE is not set; deploy with the OpsCrew workflow}";
  const app: Record<string, unknown> = {
    image,
    restart: "unless-stopped",
    env_file: ["app.env"],
    environment: { PORT: String(plan.app.port) },
    ...hardened({ noCapabilities: true, internal: true }),
  };
  const dependsOn: Record<string, { condition: string }> = {};
  const services: Record<string, unknown> = { app };
  const release = plan.app.releaseCommand;
  if (release !== undefined) {
    // A one-off container of the app's image, environment and network; only
    // `docker compose run release` starts it (the deploy does, before the app is replaced).
    services.release = {
      image,
      profiles: ["release"],
      env_file: ["app.env"],
      environment: { PORT: String(plan.app.port) },
      // `$$` keeps Compose from substituting variables: the shell in the container sees `$`.
      command: ["sh", "-c", release.replaceAll("$", () => "$$")],
      ...hardened({ noCapabilities: true, internal: true }),
    };
  }
  if (plan.services.postgres) {
    services.db = dbService({ env_file: ["db.env"] }, "/srv/data/postgres");
    dependsOn.db = { condition: "service_healthy" };
  }
  if (plan.services.redis) {
    services.cache = cacheService("/srv/data/valkey");
    dependsOn.cache = { condition: "service_started" };
  }
  if (Object.keys(dependsOn).length > 0) app.depends_on = dependsOn;

  services.caddy = {
    image: CADDY_IMAGE,
    restart: "unless-stopped",
    // In tunnel mode only the tunnel connector (host network) reaches Caddy, on a loopback port;
    // behind OpsCrew's web filter only IPv4 is published (the filter covers IPv4 only).
    ports: caddyPorts(plan),
    volumes: ["./Caddyfile:/etc/caddy/Caddyfile:ro", "caddy_data:/data", "caddy_config:/config"],
    depends_on: ["app"],
    ...hardened({ internal: true }),
  };

  const document = {
    name: plan.app.name,
    services,
    networks: { internal: {} },
    volumes: { caddy_data: {}, caddy_config: {} },
  };
  const header =
    release === undefined
      ? HEADER
      : `${HEADER}\n# \`release\` runs app.releaseCommand from opscrew/plan.yaml before each new version starts.`;
  return {
    path: "opscrew/runtime/compose.yaml",
    content: `${header}\n${stringify(document, { lineWidth: 0 })}`,
    kind: "runtime",
  };
}

/**
 * `opscrew/runtime/Caddyfile`: TLS (with a domain), compression, security headers, proxy to the
 * app; in tunnel mode Cloudflare terminates TLS and the connector reaches Caddy over plain HTTP.
 * Throws for a Portainer target, whose stack holds Caddy's configuration inline.
 */
export function renderCaddyfile(plan: DeployPlan, ctx: RenderContext): RenderedFile {
  if (plan.target.provider === "portainer") throw notForPortainer();
  const lines = [
    "# Generated by OpsCrew from opscrew/plan.yaml; `opscrew provision` regenerates it.",
    ...caddyfile({
      mode: tunnelMode(plan) ? "tunnel" : "direct",
      hosts: siteHosts(plan),
      port: plan.app.port,
      acmeEmail: ctx.acmeEmail,
    }),
  ];
  return { path: "opscrew/runtime/Caddyfile", content: lines.join("\n"), kind: "runtime" };
}

const CONNECTOR_HEADER = [
  "# Generated by OpsCrew from opscrew/plan.yaml. The Cloudflare Tunnel connector: it runs on the host",
  "# network so it reaches the app (127.0.0.1:18080), SSH and Portainer on localhost, and it opens",
  "# no port. tunnel.env next to this file holds TUNNEL_TOKEN (root-only; never committed).",
].join("\n");

/**
 * `opscrew/runtime/cloudflared/compose.yaml`: the tunnel connector as its own Compose project
 * (`opscrew-tunnel`). The token comes from `tunnel.env` in the same directory on the server
 * (`TUNNEL_TOKEN=<terraform output tunnel_token>`, mode 0600), which this file never contains.
 */
export function renderTunnelConnectorCompose(
  _plan: DeployPlan,
  _ctx?: RenderContext,
): RenderedFile {
  const document = {
    name: "opscrew-tunnel",
    services: {
      cloudflared: cloudflaredService({ env_file: ["tunnel.env"], network_mode: "host" }),
    },
  };
  return {
    path: "opscrew/runtime/cloudflared/compose.yaml",
    content: `${CONNECTOR_HEADER}\n${stringify(document, { lineWidth: 0 })}`,
    kind: "runtime",
  };
}
