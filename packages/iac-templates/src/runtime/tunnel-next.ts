import type { DeployPlan } from "@opscrew/plan-schema";
import { stringify } from "yaml";
import { runtimeDir } from "../runtime-dir";
import { CONNECTOR_MEMORY_MB, CONNECTOR_METRICS } from "../tunnel";
import type { RenderedFile } from "../types";
import { planFilePath } from "../workflow/shared";
import { memoryLimit } from "./components";
import { cloudflaredService } from "./services";

/**
 * `<runtimeDir>/cloudflared-next/compose.yaml`: while the app moves to another Cloudflare account,
 * the connector of that account's tunnel as a Compose project of its own (`<app>-tunnel-next`)
 * beside the app's connector, which it matches: the host network, metrics on a free loopback port,
 * and the token from `tunnel.env` in the same directory on the server (`TUNNEL_TOKEN=<the new
 * account's tunnel token>`, mode 0600), which this file never contains.
 */
export function renderNextTunnelConnectorCompose(plan: DeployPlan): RenderedFile {
  const document = {
    name: `${plan.app.name}-tunnel-next`,
    services: {
      cloudflared: cloudflaredService({
        env_file: ["tunnel.env"],
        network_mode: "host",
        command: ["tunnel", "--no-autoupdate", "--metrics", CONNECTOR_METRICS, "run"],
        ...memoryLimit(CONNECTOR_MEMORY_MB),
      }),
    },
  };
  const header = [
    `# Generated by OpsCrew from ${planFilePath(plan)}. While this app moves to another Cloudflare account,`,
    "# that account's tunnel connector, beside the app's own: it runs on the host network as that one does,",
    "# and it opens no port. tunnel.env next to this file holds TUNNEL_TOKEN (root-only; never committed).",
  ].join("\n");
  return {
    path: `${runtimeDir(plan)}/cloudflared-next/compose.yaml`,
    content: `${header}\n${stringify(document, { lineWidth: 0 })}`,
    kind: "runtime",
  };
}
