import type { DeployPlan } from "@opscrew/plan-schema";
import type { AppEnvironment } from "../runtime-dir";
import { planFilePath } from "../workflow/shared";

/** The folder `name` beside `plan.infra.dir` (in its parent folder), with forward slashes. */
export function besideInfraDir(plan: Pick<DeployPlan, "infra">, name: string): string {
  const dir = plan.infra.dir.replace(/\\/g, "/").replace(/\/+$/, "");
  return `${dir.slice(0, dir.lastIndexOf("/") + 1)}${name}`;
}

/** First lines of every root-module file, naming the plan's file ({@link planFilePath}). */
export function rootHeader(plan: AppEnvironment): string {
  return [
    `# Generated by OpsCrew from ${planFilePath(plan)}. You own this code, but \`opscrew provision\``,
    "# regenerates this file; change the plan (or the vendored modules) instead.",
  ].join("\n");
}

/** A Terraform provider requirement: local name, registry source and version constraint. */
export interface ProviderRequirement {
  name: string;
  source: string;
  version: string;
}

export const CLOUDFLARE_PROVIDER: ProviderRequirement = {
  name: "cloudflare",
  source: "cloudflare/cloudflare",
  version: "~> 5.27",
};

/** `versions.tf` requiring `providers` in order, with the local backend. */
export function versionsTf(
  plan: AppEnvironment,
  providers: readonly ProviderRequirement[],
): string {
  return [
    rootHeader(plan),
    "",
    "terraform {",
    '  required_version = ">= 1.6.0"',
    "",
    "  required_providers {",
    ...providers.flatMap(({ name, source, version }) => [
      `    ${name} = {`,
      `      source  = "${source}"`,
      `      version = "${version}"`,
      "    }",
    ]),
    "  }",
    "",
    "  # State lives outside the repository; OpsCrew passes the path with -backend-config at init.",
    '  backend "local" {}',
    "}",
    "",
  ].join("\n");
}

