/** The header of every settings file OpsCrew writes for a service. */
function header(comment: string, ...lines: string[]): string[] {
  return [
    `${comment} Generated by OpsCrew from opscrew/plan.yaml; \`opscrew provision\` regenerates it.`,
    ...lines.map((line) => `${comment} ${line}`),
  ];
}

/** {@link header} as XML comments. */
function xmlHeader(...lines: string[]): string[] {
  return header("#", ...lines).map((line) => `<!-- ${line.slice(2)} -->`);
}

/** `vars` plus the app's own detected variable, which gets `address`. */
function withVariable(
  ctx: ServiceContext,
  address: string,
  vars: Record<string, string>,
): Record<string, string> {
  return ctx.variable === undefined ? vars : { ...vars, [ctx.variable]: address };
}

/** A URL the app logs in with: `<scheme>://<user>:<password>@<service>:<port><path>`. */
function loginUrl(ctx: ServiceContext, scheme: string, port: number, path: string): string {
  return `${scheme}://app:${ctx.secretRef(PASSWORD.name)}@${ctx.service.name}:${port}${path}`;
}

/** True for a Valkey in queue mode. */
function queueMode(service: PlanService): boolean {
  return service.kind === "valkey" && service.options.mode === "queue";
}

