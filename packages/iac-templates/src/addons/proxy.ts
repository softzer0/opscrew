// biome-ignore-all lint/suspicious/noTemplateCurlyInString: Compose interpolation, not JavaScript templates.
import { IMAGES } from "../pins";
import { memoryLimit } from "../runtime/components";
import { hardened } from "../runtime/services";

/** Where the add-ons see the proxy's socket: a volume only the proxy and the add-on mount. */
export const PROXY_SOCKET_DIR = "/run/opscrew-docker-ro";

/** The proxy's socket, as `DOCKER_HOST` and Alloy's `host` name it. */
export const PROXY_SOCKET = `unix://${PROXY_SOCKET_DIR}/docker.sock`;

/** The Compose volume holding the proxy's socket. */
export const PROXY_VOLUME = "docker_ro";

/**
 * The Docker API paths each add-on reads (research.md R5, spike result 1). Beszel needs the
 * containers' list and stats; Alloy also needs the networks (`discovery.docker`), and each
 * container's inspect and logs (`loki.source.docker` inspects before it tails).
 */
const ALLOWED_PATHS = {
  beszel: ["_ping", "version", "info", "containers/json", "containers/{id}/stats"],
  "grafana-cloud": [
    "_ping",
    "version",
    "info",
    "containers/json",
    "networks",
    "containers/{id}/stats",
    "containers/{id}/logs",
    "containers/{id}/json",
  ],
} as const;

/** A container's id or name, in a path. */
const CONTAINER = "[A-Za-z0-9][A-Za-z0-9_.-]*";

/**
 * The `path_regexp` of an add-on's allow-list: its paths, with or without an API version prefix
 * (`/v1.47/…`), and nothing else.
 */
export function allowedPathPattern(kind: keyof typeof ALLOWED_PATHS): string {
  const plain = ALLOWED_PATHS[kind].filter((path) => !path.includes("{id}"));
  const byContainer = ALLOWED_PATHS[kind]
    .filter((path) => path.includes("{id}"))
    .map((path) => path.slice("containers/{id}/".length));
  return `^(/v1\\.[0-9]+)?/(${[...plain, `containers/${CONTAINER}/(${byContainer.join("|")})`].join("|")})$`;
}

/**
 * The proxy's Caddyfile: a socket in the add-on's volume, readable by the deploy user's group, that
 * passes only `GET` and `HEAD` on the add-on's allow-list to Docker's socket, streaming (`flush_interval
 * -1`, for followed logs), and answers anything else with 403. No admin API, no certificates and no
 * saved configuration.
 */
export function renderProxyCaddyfile(kind: keyof typeof ALLOWED_PATHS): string {
  return [
    "# Generated by OpsCrew: Docker's API for the add-on, read-only. Only GET and HEAD on the paths",
    "# below reach Docker; anything else (starting, stopping, exec, files, images, volumes) gets 403.",
    "{",
    "\tadmin off",
    "\tauto_https off",
    "\tpersist_config off",
    "}",
    "",
    "http:// {",
    `\tbind unix/${PROXY_SOCKET_DIR}/docker.sock|0660`,
    "\t@allowed {",
    "\t\tmethod GET HEAD",
    `\t\tpath_regexp ${allowedPathPattern(kind)}`,
    "\t}",
    "\thandle @allowed {",
    "\t\treverse_proxy unix//var/run/docker.sock {",
    "\t\t\tflush_interval -1",
    "\t\t}",
    "\t}",
    "\thandle {",
    "\t\trespond 403",
    "\t}",
    "}",
    "",
  ].join("\n");
}

/**
 * The proxy's Compose service: Caddy as root (Docker's socket is root's) in the deploy user's group
 * (its own socket is that group's), with no network, no capability but binding (Caddy's binary
 * carries it), a read-only root and the memory limit `memoryMb`.
 */
export function proxyService(memoryMb: number): object {
  return {
    image: IMAGES.caddy.ref,
    restart: "unless-stopped",
    user: "0:${OPSCREW_DEPLOY_GID}",
    network_mode: "none",
    volumes: [
      "./Caddyfile:/etc/caddy/Caddyfile:ro",
      "/var/run/docker.sock:/var/run/docker.sock",
      `${PROXY_VOLUME}:${PROXY_SOCKET_DIR}`,
    ],
    read_only: true,
    tmpfs: ["/data", "/config"],
    cap_add: ["NET_BIND_SERVICE"],
    ...memoryLimit(memoryMb),
    ...hardened({ noCapabilities: true }),
  };
}
