// biome-ignore-all lint/suspicious/noTemplateCurlyInString: Beszel's token placeholder, not a JavaScript template.
import type { BeszelSettings, DeployPlan } from "@opscrew/plan-schema";
import { IMAGES } from "../pins";
import { memoryLimit } from "../runtime/components";
import { hardened } from "../runtime/services";
import { BESZEL_PORT } from "../tunnel";
import { planFilePath } from "../workflow/shared";
import { addonImage, composeFile, DEPLOY_USER } from "./compose";
import { PROXY_SOCKET, PROXY_SOCKET_DIR, PROXY_VOLUME, proxyService } from "./proxy";

/**
 * What `config.yml` holds in place of the agent's token, a secret: the host step replaces it with
 * the token (from its stdin) when it writes the file on the server.
 */
export const BESZEL_TOKEN_PLACEHOLDER = "${BESZEL_TOKEN}";

/** Where the agent keeps its fingerprint (`DATA_DIR`), so a restart keeps the hub's trust. */
const AGENT_DATA_DIR = "/var/lib/beszel-agent";

/**
 * Beszel's `compose.yaml` (project `opscrew-beszel`): the agent and the read-only Docker proxy, and
 * in hub mode the hub. Every container runs as the deploy user with no capability, a read-only root
 * and the plan's memory limit:
 * - the hub listens on the server's loopback only, keeps its data in the bind-mounted `data/`
 *   folder (the host step writes OpsCrew's key there as `data/id_ed25519`), reads `config.yml`, and
 *   creates its user from `hub.env` (`USER_EMAIL`, `USER_PASSWORD`);
 * - the agent runs on the host network (the server's network figures), reads Docker only through
 *   the proxy, connects out to the hub over WebSocket with `TOKEN` (and in hub mode `KEY`) from
 *   `agent.env`, and keeps its fingerprint in `agent_data/`.
 */
export function renderBeszelCompose(plan: DeployPlan, beszel: BeszelSettings): string {
  const hubMode = beszel.mode === "hub";
  const hub = addonImage(IMAGES.beszel.ref, beszel.version);
  const agent = addonImage(IMAGES.beszelAgent.ref, beszel.version);
  const services: Record<string, unknown> = { proxy: proxyService(beszel.memoryMb.proxy) };
  if (hubMode) {
    services.hub = {
      image: hub.image,
      restart: "unless-stopped",
      user: DEPLOY_USER,
      ports: [`127.0.0.1:${BESZEL_PORT}:${BESZEL_PORT}`],
      env_file: ["hub.env"],
      // No container details (inspect, logs) in the dashboard, and no SSH: the agent dials in.
      environment: { CONTAINER_DETAILS: "false", DISABLE_SSH: "true" },
      volumes: ["./data:/beszel_data", "./config.yml:/beszel_data/config.yml:ro"],
      read_only: true,
      tmpfs: ["/tmp"],
      ...memoryLimit(beszel.memoryMb.hub),
      ...hardened({ noCapabilities: true }),
    };
  }
  services.agent = {
    image: agent.image,
    restart: "unless-stopped",
    user: DEPLOY_USER,
    network_mode: "host",
    env_file: ["agent.env"],
    environment: {
      HUB_URL: hubMode ? `http://127.0.0.1:${BESZEL_PORT}` : beszel.hubUrl,
      ...(hubMode ? {} : { KEY: beszel.hubKey }),
      DISABLE_SSH: "true",
      DOCKER_HOST: PROXY_SOCKET,
      DOCKER_IMAGE_CHECK: "false",
      DATA_DIR: AGENT_DATA_DIR,
    },
    volumes: [`${PROXY_VOLUME}:${PROXY_SOCKET_DIR}`, `./agent_data:${AGENT_DATA_DIR}`],
    depends_on: hubMode ? ["proxy", "hub"] : ["proxy"],
    read_only: true,
    ...memoryLimit(beszel.memoryMb.agent),
    ...hardened({ noCapabilities: true }),
  };
  const header = [
    `Generated by OpsCrew from ${planFilePath(plan)}; \`opscrew addon enable beszel\` regenerates it.`,
    hubMode
      ? "Beszel's hub (its dashboard, on this server's loopback only) and its agent, which reads Docker"
      : `Beszel's agent, connected out to your hub at ${beszel.hubUrl}. It reads Docker`,
    "only through OpsCrew's read-only proxy. Its secrets are in files beside this one that only the",
    "deploy user can read, never in this file.",
    ...(hub.pinned && agent.pinned
      ? []
      : [
          `Beszel ${beszel.version} (beszel.version in the plan) is pinned by tag only, not by digest.`,
        ]),
  ];
  return composeFile(header, {
    name: "opscrew-beszel",
    services,
    volumes: { [PROXY_VOLUME]: {} },
  });
}

/**
 * The hub's `config.yml`: this server as its one system, reached by the local agent, with the
 * agent's token as {@link BESZEL_TOKEN_PLACEHOLDER}. Without `users`, Beszel gives the system to
 * its first user, the one `hub.env` creates.
 */
export function renderBeszelConfig(plan: DeployPlan): string {
  // Quoted, so YAML never reads a name or a token of digits as a number.
  return [
    `# Generated by OpsCrew from ${planFilePath(plan)}; \`opscrew addon enable beszel\` regenerates it.`,
    `# On the server, OpsCrew writes the agent's token in place of ${BESZEL_TOKEN_PLACEHOLDER}.`,
    "systems:",
    `  - name: ${JSON.stringify(plan.app.name)}`,
    "    host: localhost",
    "    port: 45876",
    `    token: "${BESZEL_TOKEN_PLACEHOLDER}"`,
    "",
  ].join("\n");
}
