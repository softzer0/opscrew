import type { DeployPlan } from "@opscrew/plan-schema";
import { stringify } from "yaml";
import { usesCloudflare } from "../predicates";
import { portainerTarget } from "../providers";
import { memoryLimit } from "../runtime/components";
import { cloudflaredService } from "../runtime/services";
import { CONNECTOR_MEMORY_MB } from "../tunnel";
import { type PortainerStackFile, portainerConnectorStackName, portainerStackName } from "./stack";

/** The connector's token, from the stack's environment in Portainer. */
const TOKEN = { TUNNEL_TOKEN: "${TUNNEL_TOKEN}" };

const ENVIRONMENT_NOTE = "# environment in Portainer, never in a file. It opens no port.";

/**
 * While the app moves to another Cloudflare account, the connectors of that account's tunnels, each
 * a stack beside the app's own connector, with its token as `TUNNEL_TOKEN` in the stack's
 * environment in Portainer:
 * - web mode `tunnel`: `opscrew-<app>-tunnel-next`, cloudflared on the app stack's network
 *   (`opscrew-<app>_internal`, external to this stack), reaching Caddy at `caddy:80`;
 * - redeploy mode `cloudflare`: `opscrew-<app>-portainer-tunnel-next`, as the webhook's connector
 *   stack, reaching Portainer through `host.docker.internal` when its address is not reachable from
 *   containers.
 * None for a plan with neither.
 */
export function renderNextConnectorStacks(plan: DeployPlan): PortainerStackFile[] {
  const target = portainerTarget(plan.target);
  const stacks: PortainerStackFile[] = [];
  if (usesCloudflare(plan) && target.web.mode === "tunnel") {
    const name = `${portainerStackName(plan)}-tunnel-next`;
    stacks.push(
      stack(
        name,
        {
          services: {
            cloudflared: cloudflaredService(
              { environment: TOKEN, ...memoryLimit(CONNECTOR_MEMORY_MB) },
              true,
            ),
          },
          networks: { internal: { name: `${portainerStackName(plan)}_internal`, external: true } },
        },
        [
          "# Generated by OpsCrew. While the app moves to another Cloudflare account, the connector of that",
          "# account's tunnel for the app, beside the app stack's own, on that stack's network (it reaches",
          "# Caddy at http://caddy:80). Its token is in this stack's",
          ENVIRONMENT_NOTE,
        ],
      ),
    );
  }
  if (target.redeploy === "cloudflare") {
    stacks.push(
      stack(
        `${portainerConnectorStackName(plan)}-next`,
        {
          services: {
            cloudflared: cloudflaredService({
              environment: TOKEN,
              extra_hosts: ["host.docker.internal:host-gateway"],
              ...memoryLimit(CONNECTOR_MEMORY_MB),
            }),
          },
        },
        [
          "# Generated by OpsCrew. While the app moves to another Cloudflare account, the connector of that",
          "# account's tunnel to Portainer's webhook, beside the current one. Its token is in this stack's",
          ENVIRONMENT_NOTE,
        ],
      ),
    );
  }
  return stacks;
}

function stack(name: string, document: object, header: string[]): PortainerStackFile {
  const content = stringify({ name, ...document }, { lineWidth: 0, aliasDuplicateObjects: false });
  return { name, content: `${header.join("\n")}\n${content}` };
}
