/*
 * Runs the updater's loop in sh with a fake curl and sleep: a failing call must not stop the loop,
 * and the URL and the key reach curl as single arguments, never as shell code.
 */
function shWorks(): boolean {
  try {
    const probe = spawnSync("sh", ["-c", "echo ok"], { encoding: "utf8" });
    return probe.status === 0 && probe.stdout.trim() === "ok";
  } catch {
    return false;
  }
}

describe.skipIf(!shWorks())("the updater's loop (sh)", () => {
  const script = (stack(renderUpdaterStack(full).content).services.updater?.entrypoint?.[2] ?? "")
    // What Compose hands the container: `$$` becomes `$`.
    .replaceAll("$$", "$");

  function runLoop(env: Record<string, string>) {
    const work = mkdtempSync(join(tmpdir(), "opscrew-updater-")).replaceAll("\\", "/");
    const prelude = [
      'curl() { n=$(( $(cat "$WORK/calls" 2>/dev/null || echo 0) + 1 )); echo "$n" > "$WORK/calls";',
      '  for arg in "$@"; do printf "[%s]" "$arg"; done >> "$WORK/args"; echo >> "$WORK/args";',
      '  [ "$n" -ne 1 ]; }',
      'sleep() { [ "$(cat "$WORK/calls")" -lt 3 ] || exit 0; }',
    ].join("\n");
    const result = spawnSync("sh", ["-c", `${prelude}\n${script}`], {
      env: { ...process.env, WORK: work, ...env },
      encoding: "utf8",
      timeout: 20_000,
    });
    const args = existsSync(join(work, "args")) ? readFileSync(join(work, "args"), "utf8") : "";
    const pwned = existsSync(join(work, "pwned"));
    rmSync(work, { recursive: true, force: true });
    return { status: result.status, stderr: result.stderr, args, pwned };
  }

  it("keeps calling after a failed call, with the key pinned and the URL quoted", () => {
    const url = "https://host.docker.internal:9443/api/stacks/webhooks/$(touch $WORK/pwned)";
    const key = "sha256//AAAA BBBB=";
    const run = runLoop({ PORTAINER_WEBHOOK_URL: url, PORTAINER_PINNED_KEY: key });
    expect(run.status).toBe(0);
    const calls = run.args.trim().split("\n");
    expect(calls).toHaveLength(3);
    for (const call of calls) {
      expect(call).toBe(
        `[-fsS][--connect-timeout][10][--max-time][900][-X][POST][-o][/dev/null][--insecure][--pinnedpubkey][${key}][${url}]`,
      );
    }
    expect(run.pwned).toBe(false);
    expect(run.stderr).toContain("trying again in 60 seconds");
    expect(run.stderr).not.toContain("webhooks");
  });

  it("verifies the certificate the usual way when no key is pinned", () => {
    const run = runLoop({
      PORTAINER_WEBHOOK_URL: "https://portainer.example/api/x",
      PORTAINER_PINNED_KEY: "",
    });
    expect(run.status).toBe(0);
    expect(run.args).not.toContain("--insecure");
    expect(run.args).not.toContain("--pinnedpubkey");
  }, 30_000);
});
