function stack(content: string): Stack {
  return parse(content) as Stack;
}

/** Every `${VAR}` Compose interpolates in `content` (`$${…}` is escaped for the container). */
function interpolated(content: string): string[] {
  const names = new Set<string>();
  for (const match of content.matchAll(/(?<!\$)\$\{([A-Za-z_][A-Za-z0-9_]*)/g)) {
    names.add(match[1] ?? "");
  }
  return [...names].sort();
}

