type Service = {
  image?: string;
  environment?: Record<string, string>;
  ports?: string[];
  depends_on?: Record<string, { condition: string }> | string[];
  command?: string[];
  entrypoint?: string[];
  volumes?: string[];
  configs?: { source: string; target: string }[];
  labels?: Record<string, string>;
  logging?: unknown;
  security_opt?: string[];
  extra_hosts?: string[];
  read_only?: boolean;
  cap_drop?: string[];
  restart?: string;
};
type Stack = {
  name: string;
  services: Record<string, Service>;
  volumes?: Record<string, unknown>;
  configs?: Record<string, { content?: string; file?: string }>;
  networks?: Record<string, unknown>;
};

