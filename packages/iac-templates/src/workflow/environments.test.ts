describe("deploySecretNamesFor", () => {
  const app = [DEPLOY_SECRETS.appEnv, DEPLOY_SECRETS.dbEnv];
  const build = [DEPLOY_SECRETS.buildEnv, DEPLOY_SECRETS.buildSecrets];
  const connection = [DEPLOY_SECRETS.host, DEPLOY_SECRETS.sshKey, DEPLOY_SECRETS.knownHosts];
  const tunnel = testPlan({ provider: "own", access: "tunnel", domain: "shop.example.com" });

  it("lists the connection secrets only for a deploy from GitHub's machines", () => {
    expect(deploySecretNamesFor(prod)).toEqual([
      ...connection,
      ...app,
      DEPLOY_SECRETS.originTls,
      ...build,
    ]);
    const server = inEnvironment(serverPlan(), { name: "staging", runner: "server" });
    expect(deploySecretNamesFor(server)).toEqual([...app, DEPLOY_SECRETS.originTls, ...build]);
    expect(deploySecretNamesFor(tunnel)).toEqual([
      ...connection,
      ...Object.values(TUNNEL_DEPLOY_SECRETS),
      ...app,
      ...build,
    ]);
    expect(deploySecretNamesFor(inEnvironment(tunnel, { runner: "server" }))).toEqual([
      ...app,
      ...build,
    ]);
  });

  it("lists no build values for a promoted environment, and Portainer's own", () => {
    expect(deploySecretNamesFor(promotedProd)).toEqual([
      ...connection,
      ...app,
      DEPLOY_SECRETS.originTls,
    ]);
    expect(deploySecretNamesFor(portainerTestPlan({ redeploy: "updater" }))).toEqual(build);
    expect(deploySecretNamesFor(portainerTestPlan({ redeploy: "cloudflare" }))).toEqual([
      ...build,
      ...Object.values(PORTAINER_DEPLOY_SECRETS),
    ]);
  });

  it("covers every secret the rendered workflow reads, under the environment's names", () => {
    const server = inEnvironment(serverPlan(), { name: "qa", runner: "server" });
    for (const plan of [prod, staging, promotedProd, server, tunnel]) {
      const listed = new Set(deploySecretNamesFor(plan).map((n) => deploySecretName(plan, n)));
      for (const [, name] of content(plan).matchAll(/secrets\.([A-Z_]+)/g)) {
        if (name !== "GITHUB_TOKEN") expect(listed.has(name ?? ""), name).toBe(true);
      }
    }
  });
});

