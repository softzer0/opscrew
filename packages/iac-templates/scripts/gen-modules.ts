// Embeds the vendored HCL modules (packages/iac-templates/modules/**) into
// src/generated/modules.ts, and the scheduled check's script (packages/iac-templates/check/check.mjs)
// into src/generated/check.ts, so the bundled CLI can write them into a user's repository.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const modulesDir = join(packageDir, "modules");
const sharedDir = join(packageDir, "shared");
const checkScript = join(packageDir, "check", "check.mjs");

/** Files several modules use, kept once in `shared/` and written into each module listed. */
const SHARED_FILES: Readonly<Record<string, readonly string[]>> = {
  "cloud-init.yaml.tftpl": ["hetzner-vps", "digitalocean-droplet"],
};

const read = (path: string) => readFileSync(path, "utf8").replace(/\r\n/g, "\n");

export function collectModuleFiles(dir = modulesDir): Record<string, string> {
  const files: Record<string, string> = {};
  const walk = (current: string) => {
    for (const entry of readdirSync(current).sort()) {
      const full = join(current, entry);
      if (statSync(full).isDirectory()) walk(full);
      else files[relative(dir, full).split("\\").join("/")] = read(full);
    }
  };
  walk(dir);
  for (const [file, modules] of Object.entries(SHARED_FILES)) {
    for (const module of modules) files[`${module}/${file}`] = read(join(sharedDir, file));
  }
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1)));
}

export function renderGeneratedModule(files: Record<string, string>): string {
  const body = Object.entries(files)
    .map(([path, content]) => `  ${JSON.stringify(path)}: ${JSON.stringify(content)},`)
    .join("\n");
  return [
    "// Generated by scripts/gen-modules.ts from packages/iac-templates/modules and shared. Do not edit.",
    "// Run `pnpm --filter @opscrew/iac-templates gen:modules` after changing a module.",
    "export const MODULE_FILES: Readonly<Record<string, string>> = {",
    body,
    "};",
    "",
  ].join("\n");
}

/** The scheduled check's script, as OpsCrew writes it into a repository. */
export function readCheckScript(path = checkScript): string {
  return read(path);
}

export function renderGeneratedCheck(script: string): string {
  return [
    "// Generated by scripts/gen-modules.ts from packages/iac-templates/check/check.mjs. Do not edit.",
    "// Run `pnpm --filter @opscrew/iac-templates gen:modules` after changing check.mjs.",
    `export const CHECK_SCRIPT = ${JSON.stringify(script)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const generated = join(packageDir, "src", "generated");
  const outputs = {
    "modules.ts": renderGeneratedModule(collectModuleFiles()),
    "check.ts": renderGeneratedCheck(readCheckScript()),
  };
  for (const [name, content] of Object.entries(outputs)) {
    writeFileSync(join(generated, name), content);
    console.log(`wrote ${relative(packageDir, join(generated, name))}`);
  }
}
